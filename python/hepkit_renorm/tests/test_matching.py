"""Matching of class data onto the bases, the pole identity, the breaking and its anomaly analysis
(hepkit_renorm.matching), on the toy SU(2) x U(1) model of test_bases.py (fast; the Standard-Model gates are in
test_sm_gates.py, slow).

The class data are generated by local functionals (FunctionalData): a singular counterterm built from the derived
field and parameter directions plus evanescent operators with chosen coefficients, and breakings that are
b-exact or anomalous (the abelian anomaly eps omega_Y dY dY of the toy content, whose hypercharge anomaly does not
cancel).
"""

from fractions import Fraction

import numpy as np
import pytest
from symbolica import Expression

from hepkit_renorm import Density, LocalFunctional, Occurrence, model_from_dict
from hepkit_renorm import tensors as tn
from hepkit_renorm.brst import BRST
from hepkit_renorm.fingerprint import Fingerprinter
from hepkit_renorm.matching import (
    CombinedData,
    FunctionalData,
    MatchingError,
    OrderContext,
    field_directions,
    match_breaking,
    match_singular,
    parameter_directions,
    pole_identity,
)
from hepkit_renorm.st_solve import AnomalyError, solve_restoring

TOY = {"name": "toy", "gauge": {"X": {"group": "SU(2)", "coupling": "gx"}, "Y": {"group": "U(1)", "coupling": "gy"}},
       "fermions": {"P": {"chirality": "L", "X": "F", "Y": "1/3"}, "N": {"chirality": "R", "Y": "1/3"}},
       "scalars": {"phi": {"complex": False, "X": "A"}},
       "parameters": {"mphi": {}},
       "potential": [{"coupling": "mphi", "bilinears": [["phi", "phi"]]}],
       "gauge_fixing": {"kind": "linear_covariant", "xi": "1"}}


def q(a, b=1):
    return Expression.num(a) / b


def equal_external(model, a, b, dimensions=(4,), samples=3, physical_classes=()):
    """``a == b`` on every leg class without auxiliary fields, in each dimension (fingerprints); the classes in
    ``physical_classes`` are compared on physical external spinors."""
    from hepkit_renorm.class_results import physical_samples

    diff = LocalFunctional.integrate(a - b)
    classes = [c for c in diff.leg_classes() if not any(model.fields[n].kind == "auxiliary" for n in c)]
    for D in dimensions:
        fp = Fingerprinter(model, dimension=D)
        for c in classes:
            smp = fp.samples(list(c), samples, salt=3)
            if tuple(c) in physical_classes:
                smp = physical_samples(fp, smp)
            if np.any(fp.functional(diff, smp)):
                return False
    return True


@pytest.fixture(scope="module")
def toy():
    return model_from_dict(TOY)


@pytest.fixture(scope="module")
def brst(toy):
    return BRST(toy)


@pytest.fixture(scope="module")
def ctx(toy, brst):
    return OrderContext(toy, brst=brst)


@pytest.fixture(scope="module")
def directions(toy, brst, ctx):
    return field_directions(toy, brst.action) + parameter_directions(toy, brst.action)


@pytest.fixture(scope="module")
def counterterm(toy, ctx, directions):
    """C = sum of directions with polynomial coefficients of the right grade, plus two evanescent operators."""
    gx, gy, m = toy.param("gx"), toy.param("gy"), toy.param("mphi")
    coeff = {"Z[X]": q(3) * gx**2 - gy**2 / 7, "Z[gh_X]": q(5, 2) * gx**2, "Z[Y]": -gy**2, "Z[P]": gx**2 + gy**2,
             "Z[N]": q(-2, 3) * gy**2, "Z[phi]": q(4) * gx**2, "d[gx]": q(-7, 6) * gx**3, "d[gy]": q(1, 3) * gy**3,
             "d[mphi]": q(5) * gx**2 * m}
    total = Density(toy.fields)
    simp = toy.simplifier()
    for d in directions:
        if d.name in coeff:
            c = coeff[d.name] / 2 if d.kind == "field" else coeff[d.name]
            f = d.functional
            if d.name in ("Z[P]", "Z[N]"):      # without the evanescent kinetic term psibar dhat chi (not rescaled)
                f = LocalFunctional.integrate(f.physical(simp))
            total = total + f.scale(c)
    ev = ctx.singular.evanescent
    total = total + ev[0].functional.scale(q(2, 3) * gx**2) + ev[-1].functional.scale(-gy**2)
    return LocalFunctional.integrate(total), coeff, (ev[0].name, ev[-1].name)


@pytest.fixture(scope="module")
def singular(ctx, brst, counterterm):
    return match_singular(ctx, FunctionalData(brst, counterterm=counterterm[0]))


def test_singular_counterterm_recovers_the_constants(ctx, singular, counterterm):
    _, coeff, (e_first, e_last) = counterterm
    space = ctx.space
    for name, value in coeff.items():
        assert space.expression(singular.constants[name]) == value.expand(), name
    assert not singular.constants["Z[gh_Y]"]            # no ghost-Y term was put in
    gx, gy = ctx.model.param("gx"), ctx.model.param("gy")
    ev = {k: space.expression(v[0]) for k, v in singular.evanescent.items()}
    assert ev == {e_first: (q(2, 3) * gx**2).expand(), e_last: (-gy**2).expand()}
    assert singular.relative("gx") == (q(-7, 6) * gx**2).expand()
    # the four-dimensional limit is b-closed (all relations of b on the coefficients hold) and the d-dimensional
    # functional is the input
    assert equal_external(ctx.model, singular.functional(), counterterm[0], (6, 8))
    assert singular.closure_rank > 0 and not singular.unmatched_directions


def test_singular_rejects_data_outside_the_span(ctx, brst, toy):
    """A pole with hatted components of the external fields (outside the one-loop singular basis) is reported
    with its class."""
    mu, nu = tn.fresh(tn.LORENTZ), tn.fresh(tn.LORENTZ)
    a = tn.fresh(toy.factors["X"].adjoint_space())
    bad = LocalFunctional.integrate(Density.monomial(toy.fields, toy.param("gx") ** 2 * tn.ghat(mu, nu),
                                                     Occurrence("X", (mu, a)), Occurrence("X", (nu, a))))
    with pytest.raises(MatchingError) as err:
        match_singular(ctx, FunctionalData(brst, counterterm=bad))
    assert ("X", "X") in err.value.classes


def test_pole_identity(ctx, brst, singular, counterterm):
    good = FunctionalData(brst, counterterm=counterterm[0])
    assert pole_identity(ctx, singular, good).holds
    variation = LocalFunctional.integrate(brst.b_d(counterterm[0]))
    wrong = FunctionalData(brst, counterterm=counterterm[0], counterterm_variation=variation.scale(2))
    res = pole_identity(ctx, singular, wrong)
    assert not res.holds and res.failed


def _restoring_target(ctx):
    """A restoring counterterm in the allowed space of the standard normalisation: the fermion-gauge vertex of
    the hypercharge."""
    gx, gy = ctx.model.param("gx"), ctx.model.param("gy")
    e = next(e for e in ctx.Q.elements if set(e.leg_class) == {"P", "Pbar", "Y"})
    return LocalFunctional.integrate(e.functional.scale(q(5, 4) * gx**2 * gy)), e.name


def test_breaking_exact_and_anomalous(ctx, brst, toy):
    target, _ = _restoring_target(ctx)
    X = LocalFunctional.integrate(brst.b(target).scale(-1))
    res = match_breaking(ctx, FunctionalData(brst, breaking=X))
    assert res.closed and not res.anomaly.anomalous
    # the abelian anomaly of the toy content: eps omega_Y dY dY is b-closed and not b-exact
    gy = toy.param("gy")
    mu, nu, al, be = (tn.fresh(tn.LORENTZ) for _ in range(4))
    anom = LocalFunctional.integrate(Density.monomial(toy.fields, gy**3 * tn.eps(mu, nu, al, be),
                                                      Occurrence("gh_Y"), Occurrence("Y", (nu,), (mu,)),
                                                      Occurrence("Y", (be,), (al,))))
    Xa = LocalFunctional.integrate(X + anom.scale(q(1, 9)))
    data = FunctionalData(brst, breaking=Xa)
    ra = match_breaking(ctx, data, cohomology=True)
    assert ra.closed and ra.anomaly.anomalous
    assert ra.anomaly.cohomology is not None and ra.anomaly.cohomology >= 1
    with pytest.raises(AnomalyError) as err:
        solve_restoring(ctx, data)
    assert err.value.report.anomalous
    # linear in the anomaly: twice the anomaly gives twice the components
    r2 = match_breaking(ctx, FunctionalData(brst, breaking=LocalFunctional.integrate(X + anom.scale(q(2, 9)))))
    p = ra.anomaly.field.p
    assert np.array_equal((2 * ra.anomaly.coefficients) % p, r2.anomaly.coefficients % p)


def test_combined_data(ctx, brst, counterterm):
    """A class served by another provider gives the same result when the data agree, and a detected error when
    they do not."""
    C = counterterm[0]
    same = CombinedData(FunctionalData(brst, counterterm=C), {("X", "X"): FunctionalData(brst, counterterm=C)})
    res = match_singular(ctx, same)
    assert res.constants == match_singular(ctx, FunctionalData(brst, counterterm=C)).constants
    # doubled data in the X two-point class: still in the span of the basis, but the four-dimensional limit is no
    # longer b-closed (the two- and three-point coefficients of the X field direction no longer match)
    off = CombinedData(FunctionalData(brst, counterterm=C),
                       {("X", "X"): FunctionalData(brst, counterterm=LocalFunctional.integrate(C.scale(2)))})
    with pytest.raises(MatchingError, match="not b-closed"):
        match_singular(ctx, off)


def test_fixed_point_space(toy, brst, counterterm):
    """All parameters fixed to rationals: exact numbers at that point (the mode for loop data)."""
    values = {"gx": Fraction(3, 2), "gy": Fraction(1, 2), "mphi": Fraction(1, 4)}
    ctx = OrderContext(toy, brst=brst, fixed=values)
    res = match_singular(ctx, FunctionalData(brst, counterterm=counterterm[0]))
    assert res.constants["Z[X]"] == {(): Fraction(3) * Fraction(9, 4) - Fraction(1, 4) / 7}
    assert res.constants["d[gx]"] == {(): Fraction(-7, 6) * Fraction(27, 8)}
