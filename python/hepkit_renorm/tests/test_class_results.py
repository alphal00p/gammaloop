"""Per-class local results from first principles (hepkit_renorm.class_results): gates V5 and V6.

Golden data: ``tests/data/class_results_golden.json`` (generated by ``SCRATCHPAD/automation/ms27_diagrams/
make_golden.py`` with the reference engines of the report, see tests/data/README.md), for every leg class of ghost
number 0 and 1 derived by :mod:`hepkit_renorm.classes`, two explicit configurations each, at a rational coupling
point:

* pole (``D = 6``, full Dirac spinors): ``V_G`` (ghost number 0) with ``delta S^(1) = -G/(16 pi^2 eps)`` assembled
  from the g0 final results (``phase4/pole_consistency/gfunc.py``), and ``V_{b_d G}`` (ghost number 1, the pole
  identity of ``phase4/pole_consistency``); compared with ``c[0, 1]`` summed over the graphs;
* breaking (``D = 4``, physical spinors): ``V_{X_1}``, ``X_1 = sum X[N] N`` with the coefficients of
  ``final_counterterms.json`` (``X.engine_names``) on the N basis of ``st/bases_n.py``; compared with ``c[1, 1]``.

The default run checks a selection that covers every sector (about 30 s with 4 worker processes,
``HEPKIT_RENORM_PROCESSES`` to change); all 842 cases (every class) run with ``pytest --runslow
tests/test_class_results.py`` (``HEPKIT_RENORM_PROCESSES`` workers, default all cores; ``HEPKIT_RENORM_CACHE`` =
a directory outside the repository for the per-graph cache). Measured: 132 cases with at most three legs in 194 s
on one process; the classes with four and five legs in about 50 min on 48 processes.
"""

from __future__ import annotations

import json
import os
from collections import defaultdict
from fractions import Fraction

import numpy as np
import pytest
from conftest import DATA

from hepkit_renorm.class_results import ClassComputer, ResultCache, physical_samples
from hepkit_renorm.fingerprint import Fingerprinter
from hepkit_renorm.store import tree_store

pytestmark = pytest.mark.filterwarnings("ignore:This process .* is multi-threaded:DeprecationWarning")

SELECTION = [
    # ghost number 0: gauge 2/3/4-point, fermion 2/3-point, Higgs 2/3/4-point, Yukawa, ghost and source functions
    ("G", "G"), ("W", "W", "W"), ("G", "G", "G", "G"), ("Q", "Qbar"), ("G", "Q", "Qbar"), ("H", "Hdag"),
    ("W", "H", "Hdag"), ("H", "H", "Hdag", "Hdag"), ("Q", "Ubar", "H"), ("gh_G", "src_G"),
    ("gh_G", "gh_G", "src_gh_G"), ("gh_W", "Q", "src_Q"),
    # ghost number 1: omega A, omega A A, omega Psibar Psi, omega Psibar Psi A, omega H^dag H, omega omega Rbar Psi
    ("G", "gh_G"), ("B", "gh_B"), ("G", "G", "gh_G"), ("gh_G", "Q", "Qbar"), ("G", "gh_G", "Q", "Qbar"),
    ("gh_W", "H", "Hdag"), ("gh_G", "gh_G", "Q", "src_Q"),
]


@pytest.fixture(scope="module")
def golden():
    with open(DATA / "class_results_golden.json") as fh:
        doc = json.load(fh)
    groups = defaultdict(list)
    for case in doc["cases"]:
        groups[(tuple(case["fields"]), case["quantity"], case["dimension"])].append(case)
    return {k: Fraction(v) for k, v in doc["couplings"].items()}, dict(groups)


@pytest.fixture(scope="module")
def computer(sm):
    return ClassComputer(sm, tree_store(sm), processes=int(os.environ.get("HEPKIT_RENORM_PROCESSES", "4")))


def _fingerprinters(sm, couplings):
    return {D: Fingerprinter(sm, dimension=D, values=couplings) for D in (4, 6)}


def _samples(fp, fields, cases):
    rep = fp.rep
    to_gf = np.vectorize(lambda a, b: rep.complex(Fraction(a), Fraction(b)), otypes=[object])
    moms = np.array([c["momenta"] for c in cases], dtype=np.int64) % rep.p
    pols = [np.array([to_gf(np.array(c["polarisations"][k][0], dtype=object),
                            np.array(c["polarisations"][k][1], dtype=object)) for c in cases],
                     dtype=object).astype(np.int64) for k in range(len(fields))]
    want = np.array([rep.complex(Fraction(c["value"][0]), Fraction(c["value"][1])) for c in cases], dtype=np.int64)
    return fp.explicit_samples(list(fields), moms, pols), want


def _check(computer, fps, key, cases):
    fields, quantity, D = key
    fp = fps[D]
    smp, want = _samples(fp, fields, cases)
    res = computer.compute(fields, fp, smp)
    r = 0 if quantity == "pole" else 1
    assert res.compare(want, r, 1), (fields, quantity, D, [g.name for g in res.graphs])
    return res


@pytest.mark.parametrize("fields", SELECTION, ids=[" ".join(f) for f in SELECTION])
def test_selected_classes(sm, golden, computer, fields):
    """V5 (poles, D = 6, every structure incl. evanescent ones) and V6 (finite breaking P N1 in D = 4) from the
    graphs, class by class."""
    couplings, groups = golden
    fps = _fingerprinters(sm, couplings)
    keys = [k for k in groups if k[0] == fields]
    g = sum(sm.fields[f].ghost_number for f in fields)
    assert {k[1] for k in keys} == ({"pole"} if g == 0 else {"pole", "breaking"})
    for key in keys:
        _check(computer, fps, key, groups[key])


@pytest.mark.slow
def test_all_classes(sm, golden):
    """Every class of ghost number 0 and 1 (842 cases), V5 and V6 complete."""
    couplings, groups = golden
    cache_dir = os.environ.get("HEPKIT_RENORM_CACHE")
    computer = ClassComputer(sm, tree_store(sm), cache=ResultCache(cache_dir) if cache_dir else None,
                             processes=int(os.environ.get("HEPKIT_RENORM_PROCESSES", str(os.cpu_count() or 1))))
    fps = _fingerprinters(sm, couplings)
    bad = []
    for key, cases in groups.items():
        try:
            _check(computer, fps, key, cases)
        except AssertionError:
            bad.append(key)
    assert not bad, bad


def test_graphs_of_the_hand_enumeration_gap_vanish(sm, computer):
    """The three Higgs bubbles of W W W missing from the hand enumeration vanish one by one (Tr tau^a = 0)."""
    fields = ("W", "W", "W")
    fp = Fingerprinter(sm, dimension=6, seed=11)
    enum, recs = computer.records(fields)
    bubbles = [r for t, r in zip(enum.topologies, recs)
               if len(t.vertices) == 2 and all(xy == ("H", "Hdag") for _, _, xy in t.lines)]
    assert len(bubbles) == 3
    smp = fp.samples(list(fields), 2)
    for g in bubbles:
        lau = computer.backend.evaluate(computer.backend.prepare(g, sm), fp, smp)
        assert all(not np.asarray(c).any() for c in lau.coefficients.values())


def test_physical_samples(sm, computer):
    """Projection on the physical chirality: idempotent; Delta_1 = s S_0 vanishes on physical fermion legs (it couples
    the physical to the sterile chirality), its evanescent pole needs full spinors."""
    fields = ["gh_G", "Q", "Qbar"]
    fp = Fingerprinter(sm, dimension=6, seed=2)
    raw = computer.samples(fp, fields, 3)
    phys = computer.samples(fp, fields, 3, physical=True)
    again = physical_samples(fp, phys)
    assert all(np.array_equal(a, b) for a, b in zip(phys.polarisations, again.polarisations))
    delta = computer.store.entry("Delta1").coefficient(0)
    assert fp.functional(delta, raw).any() and not fp.functional(delta, phys).any()


def test_cache(sm, tmp_path):
    """A second computation reads every graph from the cache with identical values; other samples miss."""
    store = tree_store(sm)
    cache = ResultCache(tmp_path / "cache")
    fp = Fingerprinter(sm, dimension=4, seed=5)
    fields = ("G", "gh_G")
    first = ClassComputer(sm, store, cache=cache)
    smp = first.samples(fp, fields, 2)
    a = first.compute(fields, fp, smp)
    assert a.cached == 0 and len(a.graphs) == 3
    b = ClassComputer(sm, store, cache=ResultCache(tmp_path / "cache")).compute(fields, fp, smp)
    assert b.cached == 3
    for x, y in zip(a.graphs, b.graphs):
        assert set(x.laurent.coefficients) == set(y.laurent.coefficients)
        assert all(np.array_equal(x.laurent.coefficient(*k), y.laurent.coefficient(*k)) for k in x.laurent.coefficients)
    c = first.compute(fields, fp, first.samples(fp, fields, 2, salt=1))
    assert c.cached == 0
    d = first.compute(fields, fp.replace(values={"g_s": 3}), smp)      # other parameter values: other keys
    assert d.cached == 0
