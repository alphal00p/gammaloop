/// Every tabulated (name, representations, value).
#[cfg(test)]
pub(crate) fn entries() -> impl Iterator<Item = (&'static str, &'static [Rep], Terms)> {
    TABLE.iter().copied()
}

/// The SU(N) value of `name` with representations `reps` (in the
/// invariant's canonical argument order; gram arguments sorted adjoint first).
pub(crate) fn value(name: &str, reps: &[Rep]) -> Option<Terms> {
    TABLE.iter().find(|(n, r, _)| *n == name && *r == reps).map(|(_, _, t)| *t)
}
