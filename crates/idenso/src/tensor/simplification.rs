/// Completion is relative to the requested capabilities and output forms.
/// A deferred or capped result retains the exact expression.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, PartialOrd, Ord)]
pub enum ReductionStatus {
    #[default]
    Complete,
    Deferred,
    Capped,
}

/// Structural work permitted in addition to identity prerequisites.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub enum AlgebraContraction {
    /// All structural contractions, including chain and trace collection.
    #[default]
    Fully,
    /// Full contraction and canonical index-free dot notation.
    Dots,
    /// Structural contraction without multiplying out independent sum alternatives.
    /// Enabled algebra identities retain their required local distribution.
    Minimal,
    /// Additional connections selected by representation, not by tensor factor.
    Selected(Vec<spenso::structure::representation::LibraryRep>),
    /// Only the structural prerequisites of enabled identities.
    None,
}

/// Independent identity and output capabilities for the shared domain planner.
/// Enabling a family always authorizes its structural prerequisites.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AlgebraSettings {
    pub gamma: Option<GammaSimplifySettings>,
    pub color: Option<ColorSimplifySettings>,
    pub epsilon: bool,
    pub contract: AlgebraContraction,
    /// Collect exact coefficients generated by identities, retaining unrelated
    /// input sums as opaque factors. Disable to retain nested recurrence output.
    pub collect_coefficients: bool,
    /// Optional limit on successful transformations per domain. `None` is unlimited.
    pub max_passes: Option<usize>,
}

impl Default for AlgebraSettings {
    fn default() -> Self {
        Self {
            gamma: None,
            color: None,
            epsilon: false,
            contract: AlgebraContraction::Fully,
            collect_coefficients: true,
            max_passes: None,
        }
    }
}

impl AlgebraSettings {
    pub fn hep() -> Self {
        Self {
            gamma: Some(GammaSimplifySettings::default()),
            color: Some(ColorSimplifySettings::default()),
            epsilon: true,
            ..Self::default()
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum ReductionPolicy {
    Algebra(AlgebraSettings),
    Contract {
        representations: Option<Vec<spenso::structure::representation::LibraryRep>>,
        metrics: bool,
        rank_one: bool,
        collect_chains: bool,
        collect_traces: bool,
        expand: bool,
        order: Option<Vec<usize>>,
        max_passes: Option<usize>,
    },
}

#[derive(Clone, Debug)]
pub(crate) struct ReductionRecord {
    // Every entry describes this exact immutable expression. A no-op
    // under another policy preserves those facts; any domain change drops them.
    completed: Vec<ReductionPolicy>,
    pub(crate) status: ReductionStatus,
}

#[derive(Clone, Copy)]
pub(crate) enum ReductionRequest<'a> {
    Algebra(&'a AlgebraSettings),
    Contract(ContractSettings<'a>),
}

const STRUCTURE: u8 = 1;
const GAMMA: u8 = 2;
const COLOR: u8 = 4;
const EPSILON: u8 = 8;
const DOTS: u8 = 16;

impl ReductionRequest<'_> {
    fn policy(self) -> ReductionPolicy {
        match self {
            Self::Algebra(settings) => ReductionPolicy::Algebra(settings.clone()),
            Self::Contract(settings) => ReductionPolicy::Contract {
                representations: settings.representations.map(<[_]>::to_vec),
                metrics: settings.metrics,
                rank_one: settings.rank_one,
                collect_chains: settings.collect_chains,
                collect_traces: settings.collect_traces,
                expand: settings.expand,
                order: settings.order.map(<[_]>::to_vec),
                max_passes: settings.max_passes,
            },
        }
    }

    fn budget(self) -> Option<usize> {
        match self {
            Self::Algebra(settings) => settings.max_passes,
            Self::Contract(settings) => settings.max_passes,
        }
    }

    fn enabled(self) -> u8 {
        match self {
            Self::Contract(_) => STRUCTURE,
            Self::Algebra(settings) => {
                (u8::from(settings.gamma.is_some()) * GAMMA)
                    | (u8::from(settings.color.is_some()) * COLOR)
                    | (u8::from(settings.epsilon) * EPSILON)
                    | (u8::from(settings.contract != AlgebraContraction::None) * STRUCTURE)
                    | (u8::from(settings.contract == AlgebraContraction::Dots) * DOTS)
            }
        }
    }
}

/// Scratch for one domain; the payload remains the existing symbolic tensor.
struct DomainPlan {
    value: SymbolicTensor<PartialStructure>,
    observed: Arc<DomainObservations>,
    pending: u8,
    changes: usize,
    deferred: u8,
    settled: HashMap<u8, SettledRegions>,
    status: ReductionStatus,
}

impl DomainPlan {
    fn new(value: SymbolicTensor<PartialStructure>, pending: u8) -> Self {
        let observed = Arc::clone(value.reduction_observations());
        Self {
            value,
            observed,
            pending,
            changes: 0,
            deferred: 0,
            settled: HashMap::new(),
            status: ReductionStatus::Complete,
        }
    }

    fn local_candidates(&self) -> u8 {
        self.observed.identity_candidates()
            | STRUCTURE
            | if self.observed.needs_dot_normalization() {
                DOTS
            } else {
                0
            }
    }
}

/// Index labels spelled like Symbolica wildcards (`a_`, also nested as in
/// `coad(8,h(a_))`). Normalization neither sorts nor zeroes an antisymmetric
/// function whose arguments contain one, so `f(a_,a_,c)` would survive and
/// equal terms would not merge. The colour verb reduces private aliases and
/// restores the admitted labels on publication; no pattern is built from them.
struct WildcardLabelAliases {
    forward: HashMap<Symbol, Symbol>,
    backward: HashMap<Symbol, Symbol>,
}

impl WildcardLabelAliases {
    fn of(expression: AtomView<'_>) -> Option<Self> {
        let mut slots = spenso::structure::slot::SlotMatcher::default();
        let mut labels = std::collections::BTreeSet::new();
        expression.visitor(&mut |node| {
            if !matches!(
                slots.classify(node),
                spenso::structure::slot::SlotMatch::Explicit(_)
            ) {
                return true;
            }
            node.visitor(&mut |payload| {
                if let AtomView::Var(variable) = payload
                    && variable.get_symbol().get_wildcard_level() > 0
                {
                    labels.insert(variable.get_symbol());
                }
                true
            });
            false
        });
        if labels.is_empty() {
            return None;
        }
        // The renaming must be injective: an alias never names a symbol the
        // expression already contains. Collect those once, not per label.
        let present = expression.get_all_symbols(true);
        let forward = labels
            .into_iter()
            .map(|label| {
                let alias = (0..)
                    .map(|attempt| {
                        symbolica::symbol!(&format!(
                            "idenso::wildcard_label_{}_{attempt}",
                            label.get_id()
                        ))
                    })
                    .find(|alias| !present.contains(alias))
                    .unwrap();
                (label, alias)
            })
            .collect::<HashMap<_, _>>();
        let backward = forward
            .iter()
            .map(|(&label, &alias)| (alias, label))
            .collect();
        Some(Self { forward, backward })
    }

    fn reduce(
        &self,
        value: &SymbolicTensor<PartialStructure>,
        request: ReductionRequest<'_>,
    ) -> Result<SymbolicTensor<PartialStructure>, TensorInferenceError> {
        let reduced = value
            .with_renamed_symbols(&self.forward)?
            .plan_reduction(request)?;
        let mut restored = reduced.with_renamed_symbols(&self.backward)?;
        restored.proofs.contracted = reduced.proofs.contracted;
        restored.proofs.reduction = reduced.proofs.reduction;
        Ok(restored)
    }
}

impl SymbolicTensor<PartialStructure> {
    /// Apply the identity families and output policy in [`AlgebraSettings`],
    /// preserving unrelated scalar factorization. Enabled identities authorize
    /// their required contractions, including under [`AlgebraContraction::Minimal`].
    /// The shared contraction planner reports completion relative to this policy.
    pub fn simplify_algebra(
        &self,
        settings: &AlgebraSettings,
    ) -> Result<Self, TensorInferenceError> {
        self.plan_reduction(ReductionRequest::Algebra(settings))
    }

    pub fn reduction_status(&self) -> ReductionStatus {
        self.proofs
            .reduction
            .as_ref()
            .map_or(ReductionStatus::Deferred, |record| record.status)
    }

    pub fn contraction_complete(&self) -> bool {
        self.proofs.contracted
    }

    /// Both public settings types lower into this scheduler. A head is only a
    /// candidate; an unchanged kernel discharges it until its inputs change.
    pub(crate) fn plan_reduction(
        &self,
        request: ReductionRequest<'_>,
    ) -> Result<Self, TensorInferenceError> {
        #[cfg(feature = "reference-cases")]
        let _phase =
            crate::reference_cases::timing::scope(crate::reference_cases::timing::Phase::Planning);
        #[cfg(feature = "reference-cases")]
        let diagnostic_operation = match request {
            ReductionRequest::Contract(_) => "contract",
            ReductionRequest::Algebra(_) => "simplify_algebra",
        };
        self.ensure_validated()?;
        let policy = request.policy();
        if let Some(record) = &self.proofs.reduction
            && record.completed.contains(&policy)
        {
            #[cfg(feature = "reference-cases")]
            crate::reference_cases::timing::outcome(
                diagnostic_operation,
                ReductionStatus::Complete,
            );
            let mut result = self.clone();
            result.proofs.reduction.as_mut().unwrap().status = ReductionStatus::Complete;
            return Ok(result);
        }
        if let ReductionRequest::Algebra(settings) = request
            && settings.color.is_some()
            && let Some(aliases) = WildcardLabelAliases::of(self.expression.as_view())
        {
            return aliases.reduce(self, request);
        }
        let enabled = request.enabled();
        // Identity prerequisites are independent of the additional structural
        // filter. Both requests use the same contractor with different scope.
        let prerequisite_settings = ContractSettings {
            collect_chains: false,
            collect_traces: false,
            ..Default::default()
        };
        let structural = match request {
            ReductionRequest::Contract(settings) => settings,
            ReductionRequest::Algebra(settings) => match &settings.contract {
                AlgebraContraction::None => prerequisite_settings,
                AlgebraContraction::Minimal => ContractSettings {
                    expand: false,
                    max_passes: settings.max_passes,
                    ..Default::default()
                },
                AlgebraContraction::Selected(representations) => ContractSettings {
                    representations: Some(representations),
                    ..Default::default()
                },
                _ => ContractSettings::default(),
            },
        };
        // Whether colour rounds certify their fixed points.
        let one_shot_colour = matches!(request, ReductionRequest::Algebra(settings)
            if settings.color.is_some_and(|color| color.one_shot_traces));
        let mut plan = DomainPlan::new(self.clone(), enabled);
        while plan.pending != 0 {
            let candidates = plan.local_candidates();
            plan.pending &= candidates;
            // Another identity can remove the region whose work was deferred.
            // Completion follows the current expression, not a vanished head.
            plan.deferred &= candidates;
            if plan.status == ReductionStatus::Deferred && plan.deferred == 0 {
                plan.status = ReductionStatus::Complete;
            }
            let mut eligible = plan.pending;
            if eligible & STRUCTURE != 0
                && (structural.order.is_none() || plan.changes != 0)
                && !plan.value.structural_work_permitted(structural)
            {
                plan.pending &= !STRUCTURE;
                eligible &= !STRUCTURE;
                plan.deferred &= !STRUCTURE;
                if plan.deferred == 0 {
                    plan.status = ReductionStatus::Complete;
                }
            }
            // Exact notation work can discharge a no-op without charging budget.
            let dot_result = if eligible == DOTS {
                let value = plan.value.to_dots()?;
                if value == plan.value {
                    plan.pending &= !DOTS;
                    eligible = 0;
                }
                Some(value)
            } else {
                None
            };
            if eligible == 0 {
                break;
            }
            if request.budget().is_some_and(|limit| plan.changes >= limit) {
                plan.status = ReductionStatus::Capped;
                break;
            }
            // Prefer an eligible identity before optional notation can hide it.
            // Recompute costs only when the region's observations have changed.
            let operation = [STRUCTURE, GAMMA, COLOR, EPSILON, DOTS]
                .into_iter()
                .filter(|operation| eligible & operation != 0)
                .min_by_key(|operation| {
                    let counts = &plan.observed.candidates.counts;
                    match *operation {
                        STRUCTURE => usize::MAX - 1,
                        GAMMA => (1 + counts[8..17].iter().sum::<usize>())
                            .saturating_mul(plan.observed.identity_branch_cost(GAMMA)),
                        COLOR => (2 + counts[1..4].iter().sum::<usize>())
                            .saturating_mul(plan.observed.identity_branch_cost(COLOR)),
                        DOTS => usize::MAX,
                        _ => 8 + counts[4].saturating_mul(counts[4]),
                    }
                })
                .unwrap();
            plan.pending &= !operation;
            // Set when the colour kernel certifies its result as a fixed point.
            let mut certified = false;
            // Set when a structural round only collected chain/trace notation.
            let mut notation_only = false;
            let mut before = plan.value.clone();
            before.proofs.frontier = ReductionStatus::Complete;
            let (value, operation_status) = match request {
                ReductionRequest::Contract(settings) => {
                    let settings = ContractSettings {
                        order: if plan.changes == 0 {
                            settings.order
                        } else {
                            None
                        },
                        ..settings
                    };
                    let value;
                    let status;
                    (value, status, notation_only) = before.contract_domain(settings)?;
                    (value, status)
                }
                ReductionRequest::Algebra(settings) => {
                    if operation == DOTS {
                        (
                            dot_result.expect("dot notation follows eligible identities"),
                            ReductionStatus::Complete,
                        )
                    } else if operation == STRUCTURE {
                        let value;
                        let status;
                        (value, status, notation_only) = before.contract_domain(structural)?;
                        (value, status)
                    } else {
                        let observed = &plan.observed;
                        let prerequisites = before.contract_prerequisites(prerequisite_settings, |value| {
                            // A metric is a prerequisite, not the identity's seed.
                            if matches!(value, AtomView::Fun(function) if function.get_symbol() == spenso::network::library::symbolic::ETS.metric) { return false; }
                            if let Some(region) = observed.region(value) { return region.identity_candidates() & operation != 0; }
                            match operation {
                                GAMMA => spenso::shadowing::TensorCollectFilter::Reps([crate::representations::Bispinor {}.into()]).matches(value),
                                COLOR => spenso::shadowing::TensorCollectFilter::Reps([crate::representations::ColorFundamental {}.into(), crate::representations::ColorAdjoint {}.into(), crate::representations::ColorSextet {}.into()]).matches(value),
                                _ => matches!(value, AtomView::Fun(function) if function.get_symbol() == *crate::epsilon::EPSILON_SYMBOL),
                            }
                        }, |representation| {
                            // Spinor wavefunctions are an optional boundary
                            // contraction. Preserve the gamma word until its
                            // identities run; Lorentz vector prerequisites remain enabled.
                            operation != GAMMA || representation.base() != crate::representations::Bispinor {}.into()
                        })?;
                        if prerequisites.root != before
                            || prerequisites.status == ReductionStatus::Capped
                        {
                            (prerequisites.root, prerequisites.status)
                        } else {
                            #[cfg(test)]
                            IDENTITY_KERNEL_CALLS.with(|calls| {
                                let mut counts = calls.get();
                                counts[match operation {
                                    GAMMA => 0,
                                    COLOR => 1,
                                    EPSILON => 2,
                                    _ => unreachable!(),
                                }] += 1;
                                calls.set(counts);
                            });
                            let value = match operation {
                                GAMMA => before.simplify_gamma_parts(settings.gamma.unwrap(), settings.collect_coefficients, plan.settled.entry(GAMMA).or_default(), settings.max_passes.map(|limit| limit.saturating_sub(plan.changes)))?,
                                COLOR => {
                                    let value;
                                    (value, certified) = before.simplify_color_parts(settings.color.unwrap(), plan.settled.entry(COLOR).or_default())?;
                                    value
                                }
                                EPSILON if observed.epsilon_degree < 2 => before.clone(),
                                EPSILON => before.collect_with_map(crate::tensor::CollectionMode::Monomials, None,
                                    |value| matches!(value, AtomView::Fun(function) if function.get_symbol() == *crate::epsilon::EPSILON_SYMBOL),
                                    |selected, complete, _| plan.settled.entry(EPSILON).or_default().run(selected, complete, |selected| {
                                        let expression = EpsilonSimplifierPass::step(selected.expression.as_view());
                                        let rewritten = selected.with_identity_result(expression, None)?;
                                        if rewritten == selected { return Ok(rewritten); }
                                        let (mut value, status, _) = rewritten.contract_domain(prerequisite_settings)?;
                                        value.proofs.frontier = status;
                                        Ok(value)
                                    }))?,
                                _ => unreachable!("only enabled identities enter the algebra queue"),
                            };
                            let status = value.proofs.frontier;
                            (value, status)
                        }
                    }
                }
            };
            if value.structure != before.structure {
                return Err(TensorInferenceError::invalid(
                    "reduction changes its established logical interface",
                ));
            }
            if value != before {
                value.observe_replacement(&before);
                let observed = Arc::clone(value.reduction_observations());
                let dirty = if std::mem::discriminant(&before.expression.as_view())
                    == std::mem::discriminant(&value.expression.as_view())
                    && before.normalization_is_intrinsic()
                    && value.normalization_is_intrinsic()
                {
                    observed.changed_identity_families(&plan.observed)
                } else {
                    None
                };
                // In one-shot mode a colour fixed point, certified or confirmed
                // by a no-op round, survives another family's intrinsic change
                // that adds no colour work, instead of needing a confirming
                // colour round.
                let colour_settled = operation != COLOR
                    && dirty.is_some()
                    && (plan.pending | plan.deferred) & COLOR == 0
                    && one_shot_colour
                    && (observed.adds_no_colour_work(&plan.observed)
                        || (notation_only
                            && observed.notation_adds_no_colour_work(&plan.observed)));
                plan.observed = observed;
                plan.value = value;
                plan.changes += 1;
                // Preserve work not yet visited. A disjoint intrinsic rewrite
                // does not unset another family's settled inputs; structural
                // output and newly affected identities still need consideration.
                plan.pending |=
                    enabled & dirty.map_or(enabled, |families| STRUCTURE | DOTS | families);
                if colour_settled {
                    plan.pending &= !COLOR;
                }
                // A certified colour result needs no confirming no-op round.
                if certified {
                    plan.pending &= !COLOR;
                }
                // Nor does a notation-only structural result.
                if notation_only {
                    plan.pending &= !STRUCTURE;
                }
            }
            if operation_status == ReductionStatus::Deferred {
                plan.deferred |= operation;
            } else {
                plan.deferred &= !operation;
            }
            plan.status = if operation_status == ReductionStatus::Capped {
                ReductionStatus::Capped
            } else if plan.deferred != 0 {
                ReductionStatus::Deferred
            } else {
                ReductionStatus::Complete
            };
            if operation_status == ReductionStatus::Capped {
                break;
            }
        }
        let changed = plan.changes != 0;
        let status = plan.status;
        let mut result = plan.value;
        result.proofs.contracted = (!changed && self.proofs.contracted)
            || ((matches!(request, ReductionRequest::Contract(settings) if settings.unrestricted())
                || matches!(request, ReductionRequest::Algebra(settings) if matches!(settings.contract, AlgebraContraction::Fully | AlgebraContraction::Dots)))
                && status == ReductionStatus::Complete);
        let mut completed = if changed {
            Vec::new()
        } else {
            self.proofs
                .reduction
                .as_ref()
                .map_or_else(Vec::new, |record| record.completed.clone())
        };
        if status == ReductionStatus::Complete {
            completed.push(policy);
        }
        result.proofs.reduction = Some(ReductionRecord { completed, status });
        #[cfg(feature = "reference-cases")]
        crate::reference_cases::timing::outcome(diagnostic_operation, status);
        Ok(result)
    }
}
