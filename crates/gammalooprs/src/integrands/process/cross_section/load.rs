impl StandaloneCrossSectionArchive<(), String> {
    pub fn load(self) -> Result<LoadedStandaloneCrossSection> {
        if self.version != STANDALONE_EVALUATORS_VERSION {
            return Err(eyre!(
                "Unsupported version {} (expected {})",
                self.version,
                STANDALONE_EVALUATORS_VERSION
            ));
        }

        let mut symbolica_state = Vec::new();
        State::export(&mut symbolica_state)
            .with_context(|| "Failed to export Symbolica state for standalone cross section")?;
        let mut state_cursor = Cursor::new(&symbolica_state);
        let state_map = State::import(&mut state_cursor, None)?;

        self.load_impl(&state_map)
    }
}

impl StandaloneCrossSectionArchive {
    pub fn load(self) -> Result<LoadedStandaloneCrossSection> {
        if self.version != STANDALONE_EVALUATORS_VERSION {
            return Err(eyre!(
                "Unsupported version {} (expected {})",
                self.version,
                STANDALONE_EVALUATORS_VERSION
            ));
        }

        let mut state_cursor = Cursor::new(&self.symbolica_state);
        let state_map = State::import(&mut state_cursor, None)?;
        self.load_impl(&state_map)
    }
}

impl<S, A: ImportWithMap + Clone + PartialEq> StandaloneCrossSectionArchive<S, A> {
    pub fn load_impl(self, state_map: &StateMap) -> Result<LoadedStandaloneCrossSection> {
        let mut graph_terms = Vec::new();

        for graph in self.graph_terms {
            if let Some(metadata) = &graph.threshold_counterterm_metadata {
                validate_threshold_counterterm_metadata_archive(
                    metadata,
                    &graph.graph_name,
                    &graph.counterterms,
                )?;
            }
            let threshold_counterterm_metadata = graph.threshold_counterterm_metadata.clone();
            let params = graph
                .param_builder_params
                .iter()
                .map(|param| param.import_with_map(state_map))
                .collect::<Result<Vec<_>>>()?;

            let build_indexed_stack_collection = |payloads: Vec<
                StandaloneIndexedEvaluatorStackArchive<A>,
            >,
                                                  label: &str|
             -> Result<
                BTreeMap<StandaloneCutCFFIndex, LoadedStandaloneEvaluatorStack>,
            > {
                payloads
                    .into_iter()
                    .enumerate()
                    .map(|(slot, payload)| {
                        Ok((
                            payload.cut_cff_index,
                            build_stack(
                                payload.evaluator_stack,
                                &params,
                                &graph.fn_map_entries,
                                state_map,
                                &graph.graph_name,
                                &format!("{label}.slot[{slot}]"),
                            )?,
                        ))
                    })
                    .collect::<Result<BTreeMap<_, _>>>()
            };

            let build_indexed_generic_evaluator_collection = |payloads: Vec<
                StandaloneIndexedGenericEvaluatorArchive<A>,
            >,
                                                              label: &str|
             -> Result<
                BTreeMap<StandaloneCutCFFIndex, LoadedGenericEvaluator>,
            > {
                let parsed_fn_map_entries = parse_fn_map_entries(&graph.fn_map_entries, state_map)?;
                payloads
                    .into_iter()
                    .enumerate()
                    .map(|(slot, payload)| {
                        let started = Instant::now();
                        let evaluator = build_evaluator(
                            payload.evaluator,
                            &params,
                            parsed_fn_map_entries.clone(),
                            state_map,
                            false,
                        )?;
                        println!(
                            "[timing] build_evaluator {}::{}.slot[{}] took {:?}",
                            graph.graph_name,
                            label,
                            slot,
                            started.elapsed()
                        );
                        Ok((payload.cut_cff_index, evaluator))
                    })
                    .collect::<Result<BTreeMap<_, _>>>()
            };

            let cut_group_integrands = graph
                .cut_group_integrands
                .into_iter()
                .enumerate()
                .map(|(cut_group_id, derivative_stacks)| {
                    build_indexed_stack_collection(
                        derivative_stacks,
                        &format!("cut_group[{cut_group_id}]"),
                    )
                })
                .collect::<Result<Vec<_>>>()?;

            let counterterms = graph
                .counterterms
                .into_iter()
                .enumerate()
                .map(|(cut_id, counterterm)| {
                    let build_stack_collection =
                        |payloads: Vec<StandaloneIndexedEvaluatorStackArchive<A>>,
                         label: &str|
                         -> Result<BTreeMap<StandaloneCutCFFIndex, LoadedStandaloneEvaluatorStack>> {
                            build_indexed_stack_collection(
                                payloads,
                                &format!("counterterm[{cut_id}]::{label}"),
                            )
                        };

                    let build_stack_iterated =
                        |payloads: StandaloneIteratedCollectionArchive<_>,
                         label: &str,
                         num_left_thresholds: usize,
                         num_right_thresholds: usize|
                         -> Result<
                            LoadedStandaloneIteratedCollection<
                                BTreeMap<StandaloneCutCFFIndex, LoadedStandaloneEvaluatorStack>,
                            >,
                        > {
                            let expected_len = num_left_thresholds
                                .checked_mul(num_right_thresholds)
                                .ok_or_else(|| eyre!("{label} dimensions overflow usize"))?;
                            if payloads.num_right_thresholds != num_right_thresholds
                                || payloads.data.len() != expected_len
                            {
                                return Err(eyre!(
                                    "counterterm[{cut_id}]::{label} has dimensions inconsistent with its left/right threshold collections: data_len={}, stored_right_count={}, expected={}x{}",
                                    payloads.data.len(),
                                    payloads.num_right_thresholds,
                                    num_left_thresholds,
                                    num_right_thresholds,
                                ));
                            }
                            let data = payloads
                                .data
                                .into_iter()
                                .enumerate()
                                .map(|(i, payload)| {
                                    build_stack_collection(payload, &format!("{label}[{i}]"))
                                })
                                .collect::<Result<Vec<_>>>()?;

                            Ok(LoadedStandaloneIteratedCollection {
                                data,
                                num_right_thresholds: payloads.num_right_thresholds,
                            })
                        };

                    let build_helper_iterated =
                        |payloads: StandaloneIteratedCollectionArchive<_>,
                         label: &str,
                         num_left_thresholds: usize,
                         num_right_thresholds: usize|
                         -> Result<
                            LoadedStandaloneIteratedCollection<
                                BTreeMap<StandaloneCutCFFIndex, LoadedGenericEvaluator>,
                            >,
                        > {
                            let expected_len = num_left_thresholds
                                .checked_mul(num_right_thresholds)
                                .ok_or_else(|| eyre!("{label} dimensions overflow usize"))?;
                            if payloads.num_right_thresholds != num_right_thresholds
                                || payloads.data.len() != expected_len
                            {
                                return Err(eyre!(
                                    "counterterm[{cut_id}]::{label} has dimensions inconsistent with its left/right threshold collections: data_len={}, stored_right_count={}, expected={}x{}",
                                    payloads.data.len(),
                                    payloads.num_right_thresholds,
                                    num_left_thresholds,
                                    num_right_thresholds,
                                ));
                            }
                            let data = payloads
                                .data
                                .into_iter()
                                .enumerate()
                                .map(|(i, payload)| {
                                    build_indexed_generic_evaluator_collection(
                                        payload,
                                        &format!("counterterm[{cut_id}]::{label}[{i}]"),
                                    )
                                })
                                .collect::<Result<Vec<_>>>()?;

                            Ok(LoadedStandaloneIteratedCollection {
                                data,
                                num_right_thresholds: payloads.num_right_thresholds,
                            })
                        };

                    let pass_two_evaluator = counterterm
                        .pass_two_evaluator
                        .into_iter()
                        .enumerate()
                        .map(|(order, payload)| {
                            let started = Instant::now();
                            let evaluator = build_evaluator(
                                payload,
                                &params,
                                parse_fn_map_entries(&graph.fn_map_entries, state_map)?,
                                state_map,
                                false,
                            )?;
                            println!(
                                "[timing] build_evaluator {}::counterterm[{cut_id}]::pass_two_evaluator[{order}] took {:?}",
                                graph.graph_name,
                                started.elapsed()
                            );
                            Ok(evaluator)
                        })
                        .collect::<Result<Vec<_>>>()?;

                    let left_thresholds_evaluator = counterterm
                        .left_thresholds_evaluator
                        .into_iter()
                        .enumerate()
                        .map(|(i, payload)| {
                            build_stack_collection(
                                payload,
                                &format!("left_thresholds_evaluator[{i}]"),
                            )
                        })
                        .collect::<Result<Vec<_>>>()?;
                    let right_thresholds_evaluator = counterterm
                        .right_thresholds_evaluator
                        .into_iter()
                        .enumerate()
                        .map(|(i, payload)| {
                            build_stack_collection(
                                payload,
                                &format!("right_thresholds_evaluator[{i}]"),
                            )
                        })
                        .collect::<Result<Vec<_>>>()?;
                    let left_threshold_helpers = counterterm
                        .left_threshold_helpers
                        .into_iter()
                        .enumerate()
                        .map(|(i, payload)| {
                            build_indexed_generic_evaluator_collection(
                                payload,
                                &format!(
                                    "counterterm[{cut_id}]::left_threshold_helpers[{i}]"
                                ),
                            )
                        })
                        .collect::<Result<Vec<_>>>()?;
                    let right_threshold_helpers = counterterm
                        .right_threshold_helpers
                        .into_iter()
                        .enumerate()
                        .map(|(i, payload)| {
                            build_indexed_generic_evaluator_collection(
                                payload,
                                &format!(
                                    "counterterm[{cut_id}]::right_threshold_helpers[{i}]"
                                ),
                            )
                        })
                        .collect::<Result<Vec<_>>>()?;
                    let iterated_evaluator = build_stack_iterated(
                        counterterm.iterated_evaluator,
                        "iterated_evaluator",
                        left_thresholds_evaluator.len(),
                        right_thresholds_evaluator.len(),
                    )?;
                    let iterated_helpers = build_helper_iterated(
                        counterterm.iterated_helpers,
                        "iterated_helpers",
                        left_threshold_helpers.len(),
                        right_threshold_helpers.len(),
                    )?;
                    let threshold_multipliers = counterterm
                        .threshold_multipliers
                        .map(|collection| {
                            build_threshold_multiplier_collection(
                                collection,
                                left_thresholds_evaluator.len(),
                                right_thresholds_evaluator.len(),
                                state_map,
                            )
                            .with_context(|| {
                                format!(
                                    "graph '{}' counterterm[{cut_id}] has invalid threshold multipliers",
                                    graph.graph_name,
                                )
                            })
                        })
                        .transpose()?;

                    Ok(LoadedStandaloneCounterterm {
                        left_thresholds_evaluator,
                        right_thresholds_evaluator,
                        iterated_evaluator,
                        left_threshold_helpers,
                        right_threshold_helpers,
                        iterated_helpers,
                        threshold_multipliers,
                        pass_two_evaluator,
                    })
                })
                .collect::<Result<Vec<_>>>()?;

            graph_terms.push(LoadedStandaloneCrossSectionGraphTerm {
                graph_name: graph.graph_name,
                orientations: graph.orientations,
                param_builder_params: params,
                cut_group_integrands,
                counterterms,
                threshold_counterterm_metadata,
            });
        }

        Ok(LoadedStandaloneCrossSection { graph_terms })
    }
}

fn load_bin(path: impl AsRef<Path>) -> Result<LoadedStandaloneCrossSection> {
    let binary =
        fs::read(&path).with_context(|| format!("Cannot read {}", path.as_ref().display()))?;
    let (archive, _): (StandaloneCrossSectionArchive, _) =
        bincode::decode_from_slice(&binary, bincode::config::standard())?;
    archive.load()
}

fn load_json(path: impl AsRef<Path>) -> Result<LoadedStandaloneCrossSection> {
    let binary =
        fs::read(&path).with_context(|| format!("Cannot read {}", path.as_ref().display()))?;
    let archive: StandaloneCrossSectionArchive<(), String> = serde_json::from_slice(&binary)?;
    archive.load()
}

fn default_input_path() -> PathBuf {
    let binary = PathBuf::from("standalone_cross_section.bin");
    if binary.exists() {
        binary
    } else {
        PathBuf::from("standalone_cross_section.json")
    }
}

