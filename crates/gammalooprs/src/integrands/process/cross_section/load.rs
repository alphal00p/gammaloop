type SerializedFnMapEntry<A> = (A, A, Vec<A>, Vec<A>);
type ParsedFnMapEntry = (Atom, Atom, Vec<Atom>, Vec<Indeterminate>);
type LoadedGenericEvaluator = (
    Vec<Atom>,
    Vec<Replacement>,
    ExpressionEvaluator<Complex<f64>>,
    Vec<Complex<f64>>,
);

pub trait ImportWithMap {
    fn import_with_map(&self, state_map: &StateMap) -> Result<Atom>;
}

impl ImportWithMap for Vec<u8> {
    fn import_with_map(&self, state_map: &StateMap) -> Result<Atom> {
        let mut cursor = Cursor::new(self);
        Atom::import_with_map(&mut cursor, state_map).map_err(|e| eyre!(e))
    }
}

impl ImportWithMap for String {
    fn import_with_map(&self, _: &StateMap) -> Result<Atom> {
        try_parse!(self).map_err(|e| eyre!(e))
    }
}

fn parse_fn_map_entries<A: ImportWithMap>(
    entries: &[SerializedFnMapEntry<A>],
    state_map: &StateMap,
) -> Result<Vec<ParsedFnMapEntry>> {
    entries
        .iter()
        .map(|(lhs, rhs, tags, args)| {
            let lhs_atom = lhs.import_with_map(state_map)?;
            let rhs_atom = rhs.import_with_map(state_map)?;
            let tags = tags
                .iter()
                .map(|tag| tag.import_with_map(state_map))
                .collect::<Result<Vec<_>>>()?;
            let args = args
                .iter()
                .map(|arg| {
                    let arg = arg.import_with_map(state_map)?;
                    arg.clone().try_into().map_err(|_| {
                        eyre!("Expected indeterminate in function argument, got {arg}")
                    })
                })
                .collect::<Result<Vec<_>>>()?;

            Ok((lhs_atom, rhs_atom, tags, args))
        })
        .collect()
}

fn apply_fn_map_entries(
    parsed_entries: Vec<ParsedFnMapEntry>,
) -> Result<(Vec<Replacement>, Vec<Replacement>, FunctionMap)> {
    let mut all_replacements = Vec::new();
    let mut fn_map = FunctionMap::new();
    let mut replacements = Vec::new();
    fn_map
        .add_aliases([(parse_lit!(gammalooprs::x), Atom::Zero)])
        .map_err(|e| eyre!(e))?;

    for (lhs, rhs, tags, args) in parsed_entries {
        if let AtomView::Var(_) = lhs.as_view() {
            if let Ok(value) = Complex::<Rational>::try_from(rhs.as_view()) {
                fn_map
                    .add_aliases([(lhs.clone(), Atom::num(value))])
                    .map_err(|e| eyre!(e))?;
                all_replacements.push(Replacement::new(lhs.to_pattern(), rhs.clone()));
            } else {
                replacements.push(Replacement::new(lhs.to_pattern(), rhs.clone()));
            }
        } else if let AtomView::Fun(f) = lhs.as_view() {
            if tags.is_empty() {
                let wildcards = args
                    .iter()
                    .enumerate()
                    .map(|(i, arg)| {
                        let atom: Atom = arg.clone().into();
                        Replacement::new(
                            atom.to_pattern(),
                            Atom::var(symbolica::symbol!(format!("x{i}_"))),
                        )
                        .allow_new_wildcards_on_rhs(true)
                    })
                    .collect::<Vec<_>>();

                fn_map
                    .add_function(f.get_symbol(), args, rhs.clone())
                    .map_err(|e| eyre!(e))?;

                all_replacements.push(Replacement::new(
                    lhs.replace_multiple(&wildcards).to_pattern(),
                    rhs.replace_multiple(&wildcards),
                ));
            } else {
                fn_map
                    .add_tagged_function(f.get_symbol(), tags, args, rhs.clone())
                    .map_err(|e| eyre!(e))?;
                all_replacements.push(Replacement::new(lhs.to_pattern(), rhs.clone()));
            }
        } else {
            all_replacements.push(Replacement::new(lhs.to_pattern(), rhs.clone()));
            replacements.push(Replacement::new(lhs.to_pattern(), rhs.clone()));
        }
    }

    Ok((replacements, all_replacements, fn_map))
}

fn build_evaluator<A: ImportWithMap>(
    payload: StandaloneGenericEvaluatorArchive<A>,
    params: &[Atom],
    mut fn_map_entries: Vec<ParsedFnMapEntry>,
    state_map: &StateMap,
    iterate: bool,
) -> Result<LoadedGenericEvaluator> {
    let optimization_settings = OptimizationSettings::new()
        .horner_iterations(10)
        .cores(10)
        .abort_check(None);
    let cpe_iterations = None;
    let exprs = payload
        .exprs
        .iter()
        .map(|expr| expr.import_with_map(state_map))
        .collect::<Result<Vec<_>>>()?;

    let additional_reps = parse_fn_map_entries(&payload.additional_fn_map_entries, state_map)?;
    fn_map_entries.extend(additional_reps);

    let result = vec![Complex::new(0.0, 0.0); exprs.len()];
    let (replacements, all_replacements, fn_map) = apply_fn_map_entries(fn_map_entries)?;

    if iterate {
        let mut tree: Option<RationalExpressionTree> = None;

        for expr in &exprs {
            let eval = expr
                .replace_multiple(&replacements)
                .evaluator(params)
                .function_map(fn_map.clone())
                .optimization_settings(optimization_settings.clone())
                .build()
                .map_err(|e| eyre!("{e} for {expr}:{}", expr.replace_multiple(&replacements)))?;

            tree = Some(if let Some((atoms, mut existing)) = tree {
                existing.merge(eval, cpe_iterations).map_err(|e| eyre!(e))?;
                (atoms, existing)
            } else {
                (exprs.clone(), eval)
            });
        }

        tree.map(|(atoms, eval)| {
            (
                atoms,
                all_replacements,
                eval.map_coeff(&|r| Complex {
                    re: r.re.to_f64(),
                    im: r.im.to_f64(),
                }),
                result,
            )
        })
        .ok_or_else(|| eyre!("No expressions in evaluator payload"))
    } else {
        let replaced_exprs = exprs
            .iter()
            .map(|expr| expr.replace_multiple(&replacements))
            .collect::<Vec<_>>();

        Atom::evaluator_multiple(&replaced_exprs, params)
            .function_map(fn_map)
            .optimization_settings(optimization_settings)
            .build()
            .map(|eval| {
                (
                    exprs,
                    all_replacements,
                    eval.map_coeff(&|r| Complex {
                        re: r.re.to_f64(),
                        im: r.im.to_f64(),
                    }),
                    result,
                )
            })
            .map_err(|e| eyre!("{e}"))
    }
}

fn build_stack<A: ImportWithMap>(
    stack: StandaloneEvaluatorStackArchive<A>,
    params: &[Atom],
    fn_map_entries: &[SerializedFnMapEntry<A>],
    state_map: &StateMap,
    graph_name: &str,
    label: &str,
) -> Result<LoadedStandaloneEvaluatorStack> {
    let parsed_fn_map_entries = parse_fn_map_entries(fn_map_entries, state_map)?;
    let timed_build = |payload: StandaloneGenericEvaluatorArchive<A>,
                       iterate: bool,
                       component: &str|
     -> Result<LoadedGenericEvaluator> {
        let started = Instant::now();
        let evaluator = build_evaluator(
            payload,
            params,
            parsed_fn_map_entries.clone(),
            state_map,
            iterate,
        )?;
        println!(
            "[timing] build_evaluator {graph_name}::{label}::{component} took {:?}",
            started.elapsed()
        );
        Ok(evaluator)
    };

    Ok(LoadedStandaloneEvaluatorStack {
        single_parametric: timed_build(stack.single_parametric, false, "single_parametric")?,
        iterative: stack
            .iterative
            .map(|payload| timed_build(payload, true, "iterative"))
            .transpose()?,
        summed_function_map: stack
            .summed_function_map
            .map(|payload| timed_build(payload, false, "summed_function_map"))
            .transpose()?,
        summed: stack
            .summed
            .map(|payload| timed_build(payload, false, "summed"))
            .transpose()?,
    })
}

fn expected_threshold_multiplier_inputs<A>(
    layout: &StandaloneThresholdMultiplierLayoutArchive<A>,
) -> Vec<StandaloneThresholdMultiplierInput> {
    let mut inputs = (0..layout.model_parameter_count)
        .map(|index| StandaloneThresholdMultiplierInput::ModelParameter { index })
        .collect::<Vec<_>>();
    inputs.extend(
        (0..layout.additional_parameters.len())
            .map(|index| StandaloneThresholdMultiplierInput::AdditionalParameter { index }),
    );
    for position in 0..layout.external_count {
        for component in 0..4 {
            inputs.push(StandaloneThresholdMultiplierInput::ExternalMomentum {
                position,
                component,
            });
        }
    }
    for point in [
        StandaloneThresholdMultiplierPoint::Effective,
        StandaloneThresholdMultiplierPoint::Star,
    ] {
        for &edge in &layout.edges {
            for component in 1..4 {
                inputs.push(StandaloneThresholdMultiplierInput::EdgeMomentum {
                    point,
                    edge,
                    component,
                });
            }
        }
    }
    for point in [
        StandaloneThresholdMultiplierPoint::Effective,
        StandaloneThresholdMultiplierPoint::Star,
    ] {
        for esurface in 0..layout.esurfaces.len() {
            inputs.push(StandaloneThresholdMultiplierInput::Esurface { point, esurface });
        }
    }
    inputs
}

pub(crate) fn validate_threshold_multiplier_archive<A: PartialEq>(
    collection: &StandaloneThresholdMultiplierCollectionArchive<A>,
    expected_left: usize,
    expected_right: usize,
) -> Result<()> {
    let layout = &collection.layout;
    if layout.edges.windows(2).any(|pair| pair[0] >= pair[1]) {
        return Err(eyre!(
            "threshold-multiplier layout graph edges are not strictly ordered"
        ));
    }
    let edge_set = layout.edges.iter().copied().collect::<BTreeSet<_>>();
    for (index, esurface) in layout.esurfaces.iter().enumerate() {
        if esurface.edges.is_empty() || esurface.edges.windows(2).any(|pair| pair[0] >= pair[1]) {
            return Err(eyre!(
                "threshold-multiplier E-surface {index} has empty or non-canonical energy edges"
            ));
        }
        if esurface
            .external_shift
            .windows(2)
            .any(|pair| pair[0].0 >= pair[1].0)
            || esurface
                .external_shift
                .iter()
                .any(|(_, coefficient)| *coefficient == 0)
        {
            return Err(eyre!(
                "threshold-multiplier E-surface {index} has a non-canonical external shift"
            ));
        }
        if let Some(edge) = esurface
            .edges
            .iter()
            .chain(esurface.external_shift.iter().map(|(edge, _)| edge))
            .find(|edge| !edge_set.contains(edge))
        {
            return Err(eyre!(
                "threshold-multiplier E-surface {index} refers to missing graph edge {edge}"
            ));
        }
    }
    for pair in layout.esurfaces.windows(2) {
        if pair[0] >= pair[1] {
            return Err(eyre!(
                "threshold-multiplier E-surface catalog is not strictly ordered"
            ));
        }
    }

    let expected_inputs = expected_threshold_multiplier_inputs(layout);
    if layout.inputs != expected_inputs || layout.parameters.len() != expected_inputs.len() {
        return Err(eyre!(
            "threshold-multiplier binding layout is inconsistent: inputs={}, parameters={}, expected={}",
            layout.inputs.len(),
            layout.parameters.len(),
            expected_inputs.len(),
        ));
    }
    let additional_start = layout.model_parameter_count;
    let additional_end = additional_start + layout.additional_parameters.len();
    if layout.parameters.get(additional_start..additional_end)
        != Some(layout.additional_parameters.as_slice())
    {
        return Err(eyre!(
            "threshold-multiplier parameter list does not preserve its declared additional-parameter atoms and order"
        ));
    }
    if collection.left_variants.len() != expected_left
        || collection.right_variants.len() != expected_right
    {
        return Err(eyre!(
            "threshold-multiplier variant dimensions are {}x{}, expected {expected_left}x{expected_right}",
            collection.left_variants.len(),
            collection.right_variants.len(),
        ));
    }
    if collection.evaluators.is_empty() {
        return Err(eyre!(
            "empty threshold-multiplier archive must be represented by `None`"
        ));
    }

    let mut variant_ids = BTreeSet::new();
    let mut referenced_evaluators = vec![false; collection.evaluators.len()];
    for reference in collection
        .left_variants
        .iter()
        .chain(&collection.right_variants)
    {
        if !variant_ids.insert(reference.variant_id) {
            return Err(eyre!(
                "threshold-counterterm variant {} occurs more than once in one multiplier archive",
                reference.variant_id,
            ));
        }
        if let Some(evaluator_id) = reference.evaluator_id {
            let referenced = referenced_evaluators.get_mut(evaluator_id).ok_or_else(|| {
                eyre!(
                    "threshold-counterterm variant {} references missing multiplier evaluator {} (archive has {})",
                    reference.variant_id,
                    evaluator_id,
                    collection.evaluators.len(),
                )
            })?;
            *referenced = true;
        }
    }
    if let Some(orphan) = referenced_evaluators
        .iter()
        .position(|referenced| !referenced)
    {
        return Err(eyre!(
            "threshold-multiplier evaluator {orphan} is not referenced by any variant"
        ));
    }
    for (index, evaluator) in collection.evaluators.iter().enumerate() {
        if evaluator.exprs.len() != 1
            || evaluator.dual_shape.is_some()
            || !evaluator.additional_fn_map_entries.is_empty()
        {
            return Err(eyre!(
                "threshold-multiplier evaluator {index} must contain one scalar, non-dual expression without function-map entries"
            ));
        }
    }
    Ok(())
}

pub(crate) fn validate_threshold_counterterm_metadata_archive<A>(
    registry: &StandaloneThresholdCountertermMetadataRegistry,
    graph_name: &str,
    counterterms: &[StandaloneCountertermArchive<A>],
) -> Result<()> {
    if registry.graph_name != graph_name {
        return Err(eyre!(
            "threshold-counterterm metadata graph '{}' does not match archive graph '{}'",
            registry.graph_name,
            graph_name,
        ));
    }

    for (variant_id, variant) in registry.variants.iter().enumerate() {
        if variant.variant_id != variant_id {
            return Err(eyre!(
                "threshold-counterterm metadata variant {} is stored at index {}",
                variant.variant_id,
                variant_id,
            ));
        }
        let cut_group_id = variant.cut_group_id.ok_or_else(|| {
            eyre!(
                "cross-section threshold-counterterm variant {} has no cut group",
                variant_id,
            )
        })?;
        if cut_group_id >= counterterms.len() {
            return Err(eyre!(
                "threshold-counterterm variant {} refers to missing cut group {}",
                variant_id,
                cut_group_id,
            ));
        }
    }
    for (cut_group_id, counterterm) in counterterms.iter().enumerate() {
        let left_count = registry
            .variants
            .iter()
            .filter(|variant| {
                variant.cut_group_id == Some(cut_group_id)
                    && variant.side == StandaloneThresholdCountertermSide::Left
            })
            .count();
        let right_count = registry
            .variants
            .iter()
            .filter(|variant| {
                variant.cut_group_id == Some(cut_group_id)
                    && variant.side == StandaloneThresholdCountertermSide::Right
            })
            .count();
        if left_count != counterterm.left_thresholds_evaluator.len()
            || right_count != counterterm.right_thresholds_evaluator.len()
        {
            return Err(eyre!(
                "threshold-counterterm metadata cut group {} has dimensions {}x{}, archive has {}x{}",
                cut_group_id,
                left_count,
                right_count,
                counterterm.left_thresholds_evaluator.len(),
                counterterm.right_thresholds_evaluator.len(),
            ));
        }
    }

    let mut variant_evaluators = BTreeMap::<(usize, usize), usize>::new();
    for (evaluator_id, evaluator) in registry.evaluators.iter().enumerate() {
        if evaluator.evaluator_id != evaluator_id {
            return Err(eyre!(
                "threshold-counterterm metadata evaluator {} is stored at index {}",
                evaluator.evaluator_id,
                evaluator_id,
            ));
        }
        let cut_group_id = evaluator.cut_group_id.ok_or_else(|| {
            eyre!(
                "cross-section threshold-counterterm evaluator {} has no cut group",
                evaluator_id,
            )
        })?;
        let collection = counterterms
            .get(cut_group_id)
            .and_then(|counterterm| counterterm.threshold_multipliers.as_ref())
            .ok_or_else(|| {
                eyre!(
                    "threshold-counterterm evaluator {} refers to missing multiplier collection for cut group {}",
                    evaluator_id,
                    cut_group_id,
                )
            })?;
        if evaluator.collection_evaluator_id >= collection.evaluators.len() {
            return Err(eyre!(
                "threshold-counterterm evaluator {} refers to missing cut-local evaluator {}",
                evaluator_id,
                evaluator.collection_evaluator_id,
            ));
        }
        let mut archived_variant_ids = collection
            .left_variants
            .iter()
            .chain(&collection.right_variants)
            .filter_map(|reference| {
                (reference.evaluator_id == Some(evaluator.collection_evaluator_id))
                    .then_some(reference.variant_id)
            })
            .collect::<Vec<_>>();
        archived_variant_ids.sort_unstable();
        if evaluator.variant_ids != archived_variant_ids {
            return Err(eyre!(
                "threshold-counterterm evaluator {} variant references disagree with cut group {} multiplier collection",
                evaluator_id,
                cut_group_id,
            ));
        }
        for &variant_id in &evaluator.variant_ids {
            let variant = registry.variants.get(variant_id).ok_or_else(|| {
                eyre!(
                    "threshold-counterterm evaluator {} refers to missing variant {}",
                    evaluator_id,
                    variant_id,
                )
            })?;
            if variant.cut_group_id != Some(cut_group_id) || variant.multiplier.is_none() {
                return Err(eyre!(
                    "threshold-counterterm evaluator {} is incompatible with variant {}",
                    evaluator_id,
                    variant_id,
                ));
            }
            if variant_evaluators
                .insert((cut_group_id, variant_id), evaluator_id)
                .is_some()
            {
                return Err(eyre!(
                    "threshold-counterterm variant {} has multiple evaluators in cut group {}",
                    variant_id,
                    cut_group_id,
                ));
            }
        }
    }

    for variant in &registry.variants {
        let cut_group_id = variant.cut_group_id.unwrap();
        let expected_evaluator = variant_evaluators
            .get(&(cut_group_id, variant.variant_id))
            .map(|evaluator_id| registry.evaluators[*evaluator_id].collection_evaluator_id);
        if variant.multiplier.is_some() != expected_evaluator.is_some() {
            return Err(eyre!(
                "threshold-counterterm variant {} multiplier/evaluator metadata disagree",
                variant.variant_id,
            ));
        }
        if let Some(collection) = &counterterms[cut_group_id].threshold_multipliers {
            let references = match variant.side {
                StandaloneThresholdCountertermSide::Left => &collection.left_variants,
                StandaloneThresholdCountertermSide::Right => &collection.right_variants,
            };
            let archived_evaluator = references
                .iter()
                .find(|reference| reference.variant_id == variant.variant_id)
                .ok_or_else(|| {
                    eyre!(
                        "threshold-counterterm variant {} is absent from cut group {} multiplier references",
                        variant.variant_id,
                        cut_group_id,
                    )
                })?
                .evaluator_id;
            if archived_evaluator != expected_evaluator {
                return Err(eyre!(
                    "threshold-counterterm variant {} evaluator reference disagrees with cut group {} multiplier collection",
                    variant.variant_id,
                    cut_group_id,
                ));
            }
        }
    }

    let mut actual_components = BTreeSet::new();
    for (component_id, component) in registry.components.iter().enumerate() {
        if component.component_id != component_id {
            return Err(eyre!(
                "threshold-counterterm metadata component {} is stored at index {}",
                component.component_id,
                component_id,
            ));
        }
        let cut_group_id = component.cut_group_id.ok_or_else(|| {
            eyre!(
                "cross-section threshold-counterterm component {} has no cut group",
                component_id,
            )
        })?;
        let variant_count = component.kind.variant_count();
        if component.variant_ids.len() != variant_count
            || component.evaluator_ids.len() != variant_count
        {
            return Err(eyre!(
                "threshold-counterterm component {} has invalid variant/evaluator arity",
                component_id,
            ));
        }
        for (&variant_id, &evaluator_id) in
            component.variant_ids.iter().zip(&component.evaluator_ids)
        {
            let variant = registry.variants.get(variant_id).ok_or_else(|| {
                eyre!(
                    "threshold-counterterm component {} refers to missing variant {}",
                    component_id,
                    variant_id,
                )
            })?;
            if variant.cut_group_id != Some(cut_group_id)
                || evaluator_id != variant_evaluators.get(&(cut_group_id, variant_id)).copied()
            {
                return Err(eyre!(
                    "threshold-counterterm component {} has inconsistent variant/evaluator references",
                    component_id,
                ));
            }
        }
        if variant_count == 2
            && (registry.variants[component.variant_ids[0]].side
                != StandaloneThresholdCountertermSide::Left
                || registry.variants[component.variant_ids[1]].side
                    != StandaloneThresholdCountertermSide::Right)
        {
            return Err(eyre!(
                "iterated threshold-counterterm component {} must reference left then right variants",
                component_id,
            ));
        }
        let expected_sign = if variant_count == 1 { -1 } else { 1 };
        if component.sign != expected_sign {
            return Err(eyre!(
                "threshold-counterterm component {} has sign {}, expected {}",
                component_id,
                component.sign,
                expected_sign,
            ));
        }
        if !actual_components.insert((cut_group_id, component.kind, component.variant_ids.clone()))
        {
            return Err(eyre!(
                "duplicate threshold-counterterm component metadata at component {}",
                component_id,
            ));
        }
    }

    let mut expected_components = BTreeSet::new();
    for cut_group_id in 0..counterterms.len() {
        let left = registry
            .variants
            .iter()
            .filter(|variant| {
                variant.cut_group_id == Some(cut_group_id)
                    && variant.side == StandaloneThresholdCountertermSide::Left
            })
            .map(|variant| variant.variant_id)
            .collect::<Vec<_>>();
        let right = registry
            .variants
            .iter()
            .filter(|variant| {
                variant.cut_group_id == Some(cut_group_id)
                    && variant.side == StandaloneThresholdCountertermSide::Right
            })
            .map(|variant| variant.variant_id)
            .collect::<Vec<_>>();
        for &variant_id in left.iter().chain(&right) {
            expected_components.insert((
                cut_group_id,
                StandaloneThresholdCountertermComponentKind::Local,
                vec![variant_id],
            ));
            expected_components.insert((
                cut_group_id,
                StandaloneThresholdCountertermComponentKind::Integrated,
                vec![variant_id],
            ));
        }
        for &left_id in &left {
            for &right_id in &right {
                for kind in [
                    StandaloneThresholdCountertermComponentKind::LocalLocal,
                    StandaloneThresholdCountertermComponentKind::LocalIntegrated,
                    StandaloneThresholdCountertermComponentKind::IntegratedLocal,
                    StandaloneThresholdCountertermComponentKind::IntegratedIntegrated,
                ] {
                    expected_components.insert((cut_group_id, kind, vec![left_id, right_id]));
                }
            }
        }
    }
    if actual_components != expected_components {
        return Err(eyre!(
            "threshold-counterterm component registry does not contain the complete internal Cartesian expansion"
        ));
    }
    Ok(())
}

pub(crate) fn build_threshold_multiplier_collection<A: ImportWithMap + Clone + PartialEq>(
    collection: StandaloneThresholdMultiplierCollectionArchive<A>,
    expected_left: usize,
    expected_right: usize,
    state_map: &StateMap,
) -> Result<LoadedStandaloneThresholdMultiplierCollection> {
    validate_threshold_multiplier_archive(&collection, expected_left, expected_right)?;
    let parameters = collection
        .layout
        .parameters
        .iter()
        .map(|parameter| parameter.import_with_map(state_map))
        .collect::<Result<Vec<_>>>()?;
    let additional_parameters = collection
        .layout
        .additional_parameters
        .iter()
        .map(|parameter| parameter.import_with_map(state_map))
        .collect::<Result<Vec<_>>>()?;
    let evaluators = collection
        .evaluators
        .into_iter()
        .map(|evaluator| build_evaluator(evaluator, &parameters, Vec::new(), state_map, false))
        .collect::<Result<Vec<_>>>()?;

    Ok(LoadedStandaloneThresholdMultiplierCollection {
        layout: LoadedStandaloneThresholdMultiplierLayout {
            model_parameter_count: collection.layout.model_parameter_count,
            additional_parameters,
            external_count: collection.layout.external_count,
            edges: collection.layout.edges,
            esurfaces: collection.layout.esurfaces,
            inputs: collection.layout.inputs,
            parameters,
        },
        evaluators,
        left_variants: collection.left_variants,
        right_variants: collection.right_variants,
    })
}

