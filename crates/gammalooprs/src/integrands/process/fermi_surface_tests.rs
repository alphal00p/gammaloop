#[test]
fn fermi_surface_dotted_tadpole_localizes_delta_derivatives() -> eyre::Result<()> {
    test_initialise()?;
    let model = load_generic_model("sm");
    let graph: Graph = dot!(digraph dotted_fermion_tadpole {
        node [num=1];
        edge [num=1];
        A -> A [id=0, particle="d", mass=1];
    }, &model)?;
    let edge = EdgeIndex(0);
    let builder = ParamBuilder::new(
        &graph,
        &model,
        &graph.loop_momentum_basis,
        std::iter::empty::<Atom>(),
    );
    let mut params = graph.loop_mom_params(&graph.loop_momentum_basis);
    params.push(graph[edge].chemical_potential_atom().unwrap());
    let settings = EvaluatorSettings::default();
    let mu = 2.0_f64;
    let fermi_radius = (mu * mu - 1.0).sqrt();
    let density = 4.0 * PI * mu * fermi_radius * (-mu * mu).exp();
    let log_derivative = 1.0 / mu + mu / fermi_radius.powi(2) - 2.0 * mu;
    let second_log_derivative = -1.0 / mu.powi(2) - (mu * mu + 1.0) / fermi_radius.powi(4) - 2.0;
    let third_log_derivative = 2.0 / mu.powi(3) + 2.0 * mu * (mu * mu + 3.0) / fermi_radius.powi(6);
    let references = [
        density,
        -density * log_derivative,
        density * (log_derivative.powi(2) + second_log_derivative),
        -density
            * (log_derivative.powi(3)
                + 3.0 * log_derivative * second_log_derivative
                + third_log_derivative),
    ];

    // The first four derivative kernels are those generated by successively
    // dotted one-loop propagators. The Gaussian makes their distributional
    // action finite without any external kinematics or energy thresholds.
    for (derivative, reference) in (1..=4).zip(references) {
        for orientation in [-1, 1] {
            let weight = ThermalWeight {
                medium_mode: MediumMode::ZeroTemperatureEquilibrium,
                distributions: vec![ThermalDistributionFactor {
                    edge_id: edge,
                    sign: 1,
                    derivative_order: derivative,
                }],
                ..Default::default()
            };
            let probe = (-GS.ose(edge).pow(2)).exp();
            let source = (weight.to_atom() * probe)
                .replace(GS.sign(edge))
                .with(orientation);
            let (localized, _, _) = FermiSurfaceLocalizer::new(&graph)
                .localize(vec![AliasedAtom::from(source)], &builder)?;
            assert_eq!(localized.len(), 1);
            let mut evaluator = GenericEvaluator::new_from_raw_params(
                localized,
                &params,
                &builder.fn_map,
                builder.reps.clone(),
                settings.optimization_settings(),
                None,
                &settings,
            )?;

            for compiled in [false, true] {
                if compiled {
                    if derivative != 1 || orientation != 1 {
                        continue;
                    }
                    evaluator.activate_symjit(&CompilationOptionsSnapshot {
                        optimization_level: CompilationOptimizationLevel::O2,
                        ..Default::default()
                    })?;
                }
                // r = k_F x/(1-x) exactly cancels the auxiliary localization
                // profile in r² dr. The complete weighted value must therefore be
                // independent of x and of the sampled direction.
                for x in [0.07, 0.31, 0.5, 0.79, 0.94] {
                    let radius = fermi_radius * x / (1.0 - x);
                    let jacobian = 4.0 * PI * radius * radius * fermi_radius / (1.0 - x).powi(2);
                    for direction in [[1.0, 0.0, 0.0], [0.36, 0.48, 0.8]] {
                        let values = direction
                            .into_iter()
                            .map(|component| Complex::new_re(F(radius * component)))
                            .chain([Complex::new_re(F(mu * f64::from(orientation)))])
                            .collect::<Vec<_>>();
                        let result = <f64 as GenericEvaluatorFloat>::get_evaluator_single(
                            &mut evaluator,
                        )(&values);
                        assert!(result.im.0.abs() < 1.0e-13);
                        assert!(
                            (jacobian * result.re.0 - reference).abs() < 2.0e-10 * reference.abs(),
                            "N^({derivative}), x={x}: {} != {reference}",
                            jacobian * result.re.0,
                        );
                    }
                }

                for absent_mu in [-2.0, 0.5] {
                    let value =
                        <f64 as GenericEvaluatorFloat>::get_evaluator_single(&mut evaluator)(&[
                            Complex::new_re(F(0.3)),
                            Complex::new_re(F(0.4)),
                            Complex::new_re(F(0.5)),
                            Complex::new_re(F(absent_mu * f64::from(orientation))),
                        ]);
                    assert_eq!(value, Complex::new_re(F(0.0)));
                }
                let threshold =
                    <f64 as GenericEvaluatorFloat>::get_evaluator_single(&mut evaluator)(&[
                        Complex::new_re(F(0.3)),
                        Complex::new_re(F(0.4)),
                        Complex::new_re(F(0.5)),
                        Complex::new_re(F(f64::from(orientation))),
                    ]);
                assert!(
                    !threshold.re.0.is_finite() || !threshold.im.0.is_finite(),
                    "a degenerate shell must not silently return zero",
                );
            }
        }
    }
    Ok(())
}

#[test]
fn fermi_surface_dotted_tadpole_matches_finite_temperature_integrals() -> eyre::Result<()> {
    test_initialise()?;
    let model = load_generic_model("sm");
    let graph: Graph = dot!(digraph dotted_fermion_tadpole_convergence {
        node [num=1];
        edge [num=1];
        A -> A [id=0, particle="d", mass=1];
    }, &model)?;
    let edge = EdgeIndex(0);
    let builder = ParamBuilder::new(
        &graph,
        &model,
        &graph.loop_momentum_basis,
        std::iter::empty::<Atom>(),
    );
    let mut params = graph.loop_mom_params(&graph.loop_momentum_basis);
    params.push(graph[edge].chemical_potential_atom().unwrap());
    let settings = EvaluatorSettings::default();
    let mu = 2.0_f64;
    let fermi_radius = (mu * mu - 1.0).sqrt();

    for derivative in 1..=3 {
        let source = GS.thermal_weight_wrapper.call_args([function!(
            GS.thermal_distribution,
            0,
            derivative,
            0,
            1,
            1
        )]) * (-GS.ose(edge).pow(2)).exp();
        let (localized, _, _) = FermiSurfaceLocalizer::new(&graph)
            .localize(vec![AliasedAtom::from(source)], &builder)?;
        let mut evaluator = GenericEvaluator::new_from_raw_params(
            localized,
            &params,
            &builder.fn_map,
            builder.reps.clone(),
            settings.optimization_settings(),
            None,
            &settings,
        )?;
        let value = <f64 as GenericEvaluatorFloat>::get_evaluator_single(&mut evaluator)(&[
            Complex::new_re(F(fermi_radius)),
            Complex::new_re(F(0.0)),
            Complex::new_re(F(0.0)),
            Complex::new_re(F(mu)),
        ]);
        let localized_integral = 16.0 * PI * fermi_radius.powi(3) * value.re.0;

        let mut previous_error = f64::INFINITY;
        for beta in [20.0_f64, 40.0, 80.0] {
            // Composite midpoint quadrature resolves the narrowest thermal
            // layer by more than 50 points. The Gaussian tail beyond r=6
            // contributes less than the required comparison accuracy.
            let steps = 32_000;
            let step = 6.0 / steps as f64;
            let mut finite_temperature = 0.0;
            for i in 0..steps {
                let radius = (i as f64 + 0.5) * step;
                let energy = (radius * radius + 1.0).sqrt();
                let s = 1.0 / (1.0 + (-beta * (energy - mu)).exp());
                let kernel = match derivative {
                    1 => beta * s * (1.0 - s),
                    2 => beta.powi(2) * s * (1.0 - s) * (1.0 - 2.0 * s),
                    3 => beta.powi(3) * s * (1.0 - s) * (1.0 - 6.0 * s + 6.0 * s * s),
                    _ => unreachable!(),
                };
                finite_temperature +=
                    4.0 * PI * radius * radius * (-energy * energy).exp() * kernel * step;
            }
            let error = (finite_temperature - localized_integral).abs();
            assert!(
                error < previous_error * 0.4,
                "N^({derivative}), beta={beta}: error {error} did not decrease from {previous_error}",
            );
            previous_error = error;
        }
        assert!(previous_error < 0.006 * localized_integral.abs());
    }
    Ok(())
}

#[test]
fn fermi_surface_two_loop_curved_intersection_retains_contact() -> eyre::Result<()> {
    test_initialise()?;
    let model = load_generic_model("sm");
    let graph: Graph = dot!(digraph dotted_two_loop_fermi_intersection {
        node [num=1];
        edge [num=1];
        A -> B [id=0, particle="d", mass=0, lmb_id=0];
        B -> A [id=1, particle="u", mass=0];
        A -> B [id=2, particle="g", mass=0, lmb_id=1];
    }, &model)?;
    let q_edge = EdgeIndex(0);
    let r_edge = EdgeIndex(1);
    let spectator = EdgeIndex(2);
    let builder = ParamBuilder::new(
        &graph,
        &model,
        &graph.loop_momentum_basis,
        std::iter::empty::<Atom>(),
    );
    let localizer = FermiSurfaceLocalizer::new(&graph);
    let initial_support = [FermiDistribution {
        edge: q_edge,
        orientation: Atom::one(),
        order: 2,
    }];
    let basis = localizer.basis(&initial_support)?;
    assert!(basis.loop_edges.contains(&q_edge));
    assert!(basis.loop_edges.contains(&spectator));
    assert!(!basis.loop_edges.contains(&r_edge));
    let q_loop = LoopIndex::from(
        basis
            .loop_edges
            .iter()
            .position(|edge| *edge == q_edge)
            .unwrap(),
    );
    let spectator_loop = LoopIndex::from(
        basis
            .loop_edges
            .iter()
            .position(|edge| *edge == spectator)
            .unwrap(),
    );
    let sign = |value| -> f64 {
        match value {
            SignOrZero::Plus => 1.0,
            SignOrZero::Minus => -1.0,
            SignOrZero::Zero => 0.0,
        }
    };
    let alpha = sign(basis.edge_signatures[r_edge].internal[q_loop]);
    let beta = sign(basis.edge_signatures[r_edge].internal[spectator_loop]);
    assert_eq!(alpha.abs(), 1.0);
    assert_eq!(beta.abs(), 1.0);

    for derivative in [2, 3] {
        let weight = ThermalWeight {
            medium_mode: MediumMode::ZeroTemperatureEquilibrium,
            // The grouped numerator reduces to Theta(E_r-mu_r) at zero
            // temperature because the spectator is a gluon. Retaining this
            // difference of products exercises the production grouping boundary.
            numerators: vec![ThermalNumerator {
                positive_energies: vec![r_edge, spectator],
                negative_energies: vec![],
            }],
            distributions: vec![ThermalDistributionFactor {
                edge_id: q_edge,
                sign: 1,
                derivative_order: derivative,
            }],
        };
        let dot = Atom::add_many((0..3).map(|axis| {
            FermiSurfaceLocalizer::spatial(q_edge, axis)
                * FermiSurfaceLocalizer::spatial(r_edge, axis)
        }));
        let probe: Atom =
            (Atom::one() + dot) * (-GS.ose(q_edge).pow(2) - GS.ose(r_edge).pow(2)).exp();
        let source = [q_edge, r_edge, spectator]
            .into_iter()
            .fold(weight.to_atom() * probe, |atom, edge| {
                atom.replace(GS.sign(edge)).with(1)
            });
        let expanded = localizer.expand_functions(source, &builder, false)?;
        let (reduced, _) =
            localizer.reduce_derivatives(localizer.extract(expanded.as_view())?, &builder)?;
        assert_eq!(reduced.len(), 2, "one shell term and one intersection term");
        assert!(reduced.keys().any(|support| support.len() == 2));
        assert!(
            reduced
                .keys()
                .all(|support| support.iter().all(|factor| factor.order == 1))
        );

        let mut params = graph.loop_mom_params(&graph.loop_momentum_basis);
        params.push(graph[q_edge].chemical_potential_atom().unwrap());
        params.push(graph[r_edge].chemical_potential_atom().unwrap());
        let settings = EvaluatorSettings::default();
        let a = 1.5_f64;
        let b = 0.7_f64;
        let values_at = |radius: f64, cosine: f64| {
            let q = [0.0, 0.0, a];
            let r = [
                radius * (1.0 - cosine * cosine).sqrt(),
                0.0,
                radius * cosine,
            ];
            let p = std::array::from_fn::<_, 3, _>(|axis| (r[axis] - alpha * q[axis]) / beta);
            let mut values = Vec::new();
            for edge in &graph.loop_momentum_basis.loop_edges {
                let q_coefficient = sign(basis.edge_signatures[*edge].internal[q_loop]);
                let p_coefficient = sign(basis.edge_signatures[*edge].internal[spectator_loop]);
                values.extend((0..3).map(|axis| {
                    Complex::new_re(F(q_coefficient * q[axis] + p_coefficient * p[axis]))
                }));
            }
            values.extend([Complex::new_re(F(a)), Complex::new_re(F(b))]);
            values
        };

        let mut bulk_integral = 0.0;
        let mut contact_integral = 0.0;
        for (support, coefficient) in reduced {
            let localized = localizer.localize_support(&support, coefficient, &builder)?;
            let mut evaluator = GenericEvaluator::new_from_raw_params(
                [localized],
                &params,
                &builder.fn_map,
                builder.reps.clone(),
                settings.optimization_settings(),
                None,
                &settings,
            )?;
            let angular_nodes = [-1.0 / 3.0_f64.sqrt(), 1.0 / 3.0_f64.sqrt()];
            if support.len() == 2 {
                // Both shell vectors are already at their roots. Undo each
                // auxiliary density 1/(4 k_F) and integrate the physical shell
                // measures a² b² dOmega_q dOmega_r.
                for cosine in angular_nodes {
                    let value = <f64 as GenericEvaluatorFloat>::get_evaluator_single(
                        &mut evaluator,
                    )(&values_at(b, cosine));
                    assert!(value.im.0.abs() < 1.0e-13);
                    contact_integral += 128.0 * PI * PI * a.powi(3) * b.powi(3) * value.re.0;
                }
            } else {
                // Two-point Gauss quadrature exactly integrates the angular
                // polynomial. The radial cells avoid evaluating a step directly
                // on its boundary, and the omitted Gaussian tail is negligible.
                let cells = 512;
                let width = (6.0 - b) / cells as f64;
                for cell in 0..cells {
                    let center = b + (cell as f64 + 0.5) * width;
                    for radial_node in angular_nodes {
                        let radius = center + width * radial_node / 2.0;
                        for cosine in angular_nodes {
                            let value = <f64 as GenericEvaluatorFloat>::get_evaluator_single(
                                &mut evaluator,
                            )(&values_at(radius, cosine));
                            assert!(value.im.0.abs() < 1.0e-13);
                            bulk_integral += 32.0 * PI * PI * a.powi(3) * radius.powi(2) * width
                                / 2.0
                                * value.re.0;
                        }
                    }
                }
            }
        }

        // In coordinates (q,r), the odd q.r part integrates to zero. In the
        // original radial q flow it produces a nonzero contact, cancelled by a
        // bulk contribution. Omitting that contact therefore changes the answer.
        let shell_density_derivative = if derivative == 2 {
            8.0 * PI * a * (a * a - 1.0) * (-a * a).exp()
        } else {
            4.0 * PI * (2.0 - 10.0 * a * a + 4.0 * a.powi(4)) * (-a * a).exp()
        };
        let reference = shell_density_derivative
            * (2.0 * PI * b * (-b * b).exp() + PI.powf(1.5) * statrs::function::erf::erfc(b));
        let contact_reference = if derivative == 2 {
            -alpha * 16.0 * PI * PI / 3.0 * a.powi(3) * b.powi(3) * (-a * a - b * b).exp()
        } else {
            // Once the second shell is created, the remaining derivative
            // holds r fixed. With A=partial_a|r+2/a and B=alpha n_q.grad_r,
            // its contact coefficient is alpha cos(theta) (2 A+B) F.
            32.0 * PI * PI / 3.0
                * a.powi(2)
                * b.powi(3)
                * (-a * a - b * b).exp()
                * (alpha * (3.0 - 2.0 * a * a) - 1.0)
        };
        assert!(contact_reference.abs() > 1.0);
        assert!(
            (contact_integral - contact_reference).abs() < 2.0e-10,
            "N^({derivative}) contact: {contact_integral} != {contact_reference}",
        );
        assert!(
            (bulk_integral + contact_integral - reference).abs() < 2.0e-8,
            "N^({derivative}) full integral: {bulk_integral} + {contact_integral} != {reference}",
        );
        assert!((bulk_integral - reference).abs() > 1.0);
    }
    Ok(())
}

#[test]
fn fermi_surface_grouped_empty_remainder_cancels_dependent_support() -> eyre::Result<()> {
    test_initialise()?;
    let model = load_generic_model("sm");
    let graph: Graph = dot!(digraph grouped_two_loop_fermi_intersection {
        node [num=1];
        edge [num=1];
        A -> B [id=0, particle="d", mass=0, lmb_id=0];
        B -> A [id=1, particle="u", mass=0];
        A -> B [id=2, particle="s", mass=0, lmb_id=1];
    }, &model)?;
    let builder = ParamBuilder::new(
        &graph,
        &model,
        &graph.loop_momentum_basis,
        std::iter::empty::<Atom>(),
    );
    let edges = [EdgeIndex(0), EdgeIndex(1), EdgeIndex(2)];
    let weight = ThermalWeight {
        medium_mode: MediumMode::ZeroTemperatureEquilibrium,
        numerators: vec![ThermalNumerator {
            positive_energies: vec![edges[1], edges[2]],
            negative_energies: vec![],
        }],
        distributions: vec![ThermalDistributionFactor {
            edge_id: edges[0],
            sign: 1,
            derivative_order: 4,
        }],
    };
    let source = edges.into_iter().fold(
        weight.to_atom() * (-GS.ose(edges[0]).pow(2)).exp(),
        |atom, edge| atom.replace(GS.sign(edge)).with(1),
    );
    let localizer = FermiSurfaceLocalizer::new(&graph);
    let expanded = localizer.expand_functions(source, &builder, false)?;
    let (reduced, _) =
        localizer.reduce_derivatives(localizer.extract(expanded.as_view())?, &builder)?;

    // Both numerator factors have chemical potentials. After one has
    // produced a contact, differentiating the other must give P_empty=0.
    // Otherwise a spurious three-surface sector asks for an impossible
    // three-edge loop basis in this two-loop graph.
    let dependent_supports = reduced
        .iter()
        .filter(|(support, _)| support.len() > 2)
        .map(|(support, coefficient)| {
            format!(
                "{support:?}: {coefficient}; expanded zero: {}",
                coefficient.expand().is_zero()
            )
        })
        .collect::<Vec<_>>();
    assert!(
        dependent_supports.is_empty(),
        "{}",
        dependent_supports.join("\n")
    );
    let contact = reduced
        .keys()
        .find(|support| support.len() == 2 && support.iter().any(|factor| factor.edge == edges[1]))
        .expect("the first radial derivative must meet the r shell");
    let contact_basis = localizer.basis(contact)?;
    let q_loop = LoopIndex::from(
        contact_basis
            .loop_edges
            .iter()
            .position(|edge| *edge == edges[0])
            .unwrap(),
    );
    assert_ne!(
        contact_basis.edge_signatures[edges[2]].internal[q_loop],
        SignOrZero::Zero,
        "the remaining occupation must move in the subsequent constrained flow",
    );
    for (support, coefficient) in reduced {
        assert!(
            !localizer
                .localize_support(&support, coefficient, &builder)?
                .is_zero()
        );
    }
    Ok(())
}

#[test]
fn fermi_surface_second_derivative_preserves_soft_coulomb_contact() -> eyre::Result<()> {
    test_initialise()?;
    let model = load_generic_model("sm");
    let graph: Graph = dot!(digraph two_loop_soft_fermi_derivative {
        node [num=1];
        edge [num=1];
        A -> B [id=0, particle="d", mass=0, lmb_id=0];
        B -> A [id=1, particle="g", mass=0];
        A -> B [id=2, particle="u", mass=1, lmb_id=1];
    }, &model)?;
    let builder = &graph.param_builder;
    let source = function!(GS.thermal_distribution, 0, 3, 0, 1, 1)
        * (-GS.ose(EdgeIndex(0)).pow(2) - GS.ose(EdgeIndex(1)).pow(2)).exp()
        / GS.ose(EdgeIndex(1));
    let localizer = FermiSurfaceLocalizer::new(&graph);
    let expanded = localizer.expand_functions(source, builder, false)?;
    let (reduced, _) =
        localizer.reduce_derivatives(localizer.extract(expanded.as_view())?, builder)?;
    assert_eq!(reduced.len(), 1);
    let (support, coefficient) = reduced.first_key_value().unwrap();
    assert_eq!(support[0].edge, EdgeIndex(0));
    assert_eq!(support[0].order, 1);
    let params = graph.loop_mom_params(&graph.loop_momentum_basis);
    let mut evaluator = coefficient
        .evaluator(&params)
        .build()?
        .map_coeff(&|coefficient| coefficient.re.to_f64());

    // The same shell measure fixes the independent soft asymptote
    // r*C -> exp(-a²)*(4*a²-10+2/a²). These values remain meaningful;
    // coordinatewise derivatives otherwise lose this cancellation in binary64.
    let radius = 1.5_f64;
    let soft_limit =
        (-radius * radius).exp() * (4.0 * radius * radius - 10.0 + 2.0 / (radius * radius));
    for cosine in [0.0_f64, 0.6] {
        for soft_radius in [1.0e-8_f64, 1.0e-10] {
            let point = [
                0.0,
                0.0,
                radius,
                soft_radius * (1.0 - cosine * cosine).sqrt(),
                0.0,
                soft_radius * cosine - radius,
            ];
            let value = evaluator.evaluate_single(&point);
            // Use the actual routed radius, including rounded input coordinates.
            let routed_radius = (point[3].powi(2) + (point[5] + radius).powi(2)).sqrt();
            assert!(
                (routed_radius * value - soft_limit).abs() < 4.0 * soft_radius,
                "soft asymptote at r={soft_radius}, cos={cosine}: {} != {soft_limit}",
                routed_radius * value,
            );
        }
    }

    // With r=q+p, the unprocessed distribution is
    // delta''(|q|-a) exp(-q²-r²)/|r|. Integrating r first gives 2*pi,
    // leaving 8*pi² d²/da²[a² exp(-a²)]. This Coulomb coefficient also
    // occurs in the highest thermal derivative of a native dotted sunset.
    // Differentiating 1/|r| pointwise while holding p fixed misses its
    // distributional Hessian contact, despite the original integral being finite.
    for radius in [1.0_f64, 1.5, 2.0] {
        let reference = 8.0
            * PI.powi(2)
            * (-radius * radius).exp()
            * (2.0 - 10.0 * radius * radius + 4.0 * radius.powi(4));
        let mut previous_error = f64::INFINITY;
        for cells in [256, 512] {
            let step = 7.0 / cells as f64;
            let mut integral = 0.0;
            for cell in 0..cells {
                let soft_radius = (cell as f64 + 0.5) * step;
                // Rotations remove three angles; the remaining dependence is
                // quadratic in cos(q,r), integrated exactly by these two nodes.
                for cosine in [-1.0 / 3.0_f64.sqrt(), 1.0 / 3.0_f64.sqrt()] {
                    let value = evaluator.evaluate_single(&[
                        0.0,
                        0.0,
                        radius,
                        soft_radius * (1.0 - cosine * cosine).sqrt(),
                        0.0,
                        soft_radius * cosine - radius,
                    ]);
                    integral +=
                        8.0 * PI.powi(2) * radius.powi(2) * soft_radius.powi(2) * value * step;
                }
            }
            let error = (integral - reference).abs();
            assert!(
                error < 0.3 * previous_error,
                "soft pole at a={radius}, {cells} cells: {integral} != {reference}",
            );
            previous_error = error;
        }
        assert!(previous_error < 2.0e-5 * reference.abs());
    }
    Ok(())
}

#[test]
fn fermi_surface_three_shell_flow_preserves_soft_triangle() -> eyre::Result<()> {
    test_initialise()?;
    let model = load_generic_model("sm");
    let graph: Graph = dot!(digraph three_shell_soft_triangle {
        node [num=1];
        edge [num=1];
        A -> B [id=0, particle="d", mass=0, lmb_id=0];
        A -> B [id=1, particle="u", mass=0, lmb_id=1];
        B -> A [id=2, particle="s", mass=0, lmb_id=2];
        B -> A [id=3, particle="g", mass=0];
    }, &model)?;
    let support = (0..3)
        .map(|edge| FermiDistribution {
            edge: EdgeIndex(edge),
            orientation: Atom::one(),
            order: 1,
        })
        .collect::<Vec<_>>();
    let builder = &graph.param_builder;
    let localizer = FermiSurfaceLocalizer::new(&graph);
    let coefficient = localizer.energy(EdgeIndex(3), builder)?.pow(-1);
    let flow = localizer.normal_flow(&support, EdgeIndex(0), builder, &coefficient)?;
    assert!(!flow.domains.is_empty());
    let params = graph.loop_mom_params(&graph.loop_momentum_basis);
    let mut evaluators = flow
        .velocity
        .iter()
        .flatten()
        .map(|component| {
            component
                .evaluator(&params)
                .build()
                .map(|evaluator| evaluator.map_coeff(&|coefficient| coefficient.re.to_f64()))
        })
        .collect::<Result<Vec<_>, _>>()?;

    // At epsilon=0 the three unit Fermi momenta close a noncollinear
    // triangle, while r=q1+q2-q3 vanishes. Changing q1's energy must rotate
    // the other momenta to preserve both their energies and the soft locus.
    // An ordinary active-aligned loop basis cannot impose all four vectors.
    let mut previous_soft_speed = f64::INFINITY;
    for epsilon in [1.0e-2_f64, 1.0e-3, 1.0e-4, 0.0] {
        let point = [
            0.5,
            3.0_f64.sqrt() / 2.0,
            0.0,
            0.5,
            -3.0_f64.sqrt() / 2.0,
            0.0,
            1.0,
            0.0,
            epsilon,
        ];
        let velocity = evaluators
            .iter_mut()
            .map(|evaluator| evaluator.evaluate_single(&point))
            .collect::<Vec<_>>();
        assert!(velocity.iter().all(|component| component.is_finite()));
        for edge in 0..3 {
            let norm = (0..3)
                .map(|axis| point[3 * edge + axis].powi(2))
                .sum::<f64>()
                .sqrt();
            let normal = (0..3)
                .map(|axis| point[3 * edge + axis] * velocity[3 * edge + axis] / norm)
                .sum::<f64>();
            let expected = if edge == 0 { 1.0 } else { 0.0 };
            assert!((normal - expected).abs() < 2.0e-10);
        }
        let soft_speed = (0..3)
            .map(|axis| (velocity[axis] + velocity[3 + axis] - velocity[6 + axis]).powi(2))
            .sum::<f64>()
            .sqrt();
        if epsilon == 0.0 {
            assert!(soft_speed < 2.0e-10);
        } else {
            assert!(
                soft_speed < 0.02 * previous_soft_speed,
                "soft velocity must vanish quadratically: epsilon={epsilon}, speed={soft_speed}",
            );
            previous_soft_speed = soft_speed;
        }
    }
    Ok(())
}

#[test]
fn fermi_surface_constant_bridge_preserves_thermal_metadata() -> eyre::Result<()> {
    test_initialise()?;
    let model = load_generic_model("sm");
    let graph: Graph = dot!(digraph fermi_tadpoles_with_massive_bridge {
        node [num=1];
        edge [num=1];
        A -> A [id=0, particle="d", mass=2];
        B -> B [id=1, particle="d", mass=3];
        A -> B [id=2, particle="H", mass=1];
    }, &model)?;
    let builder = &graph.param_builder;
    let localizer = FermiSurfaceLocalizer::new(&graph);
    assert!(
        graph.loop_momentum_basis.edge_signatures[EdgeIndex(2)]
            .internal
            .iter()
            .all(|sign| sign.is_zero())
    );
    assert_eq!(localizer.energy(EdgeIndex(2), builder)?, Atom::one());
    let occupation = function!(GS.thermal_distribution, 1, 0, 0, 1, 1);
    let source = function!(GS.thermal_distribution, 0, 2, 0, 1, 1)
        * &occupation
        * FermiSurfaceLocalizer::spatial(EdgeIndex(0), 0).pow(2)
        * (-GS.ose(EdgeIndex(0)).pow(2) - GS.ose(EdgeIndex(1)).pow(2)).exp()
        / GS.ose(EdgeIndex(2));
    let expanded = localizer.expand_functions(source, builder, false)?;
    let (reduced, _) =
        localizer.reduce_derivatives(localizer.extract(expanded.as_view())?, builder)?;
    assert_eq!(reduced.len(), 1);
    let (support, coefficient) = reduced.first_key_value().unwrap();
    assert_eq!(support[0].edge, EdgeIndex(0));
    assert_eq!(support[0].order, 1);

    // For C=q_x² exp(-E_q²-E_p²), V=E*q/q² gives
    // -div(V*C)=C*(2E-1/E-3E/q²). A constant bridge must not capture
    // the component index 1, hiding the derivative of this numerator, or
    // change the independent spectator occupation's literal metadata.
    let params = graph.loop_mom_params(&graph.loop_momentum_basis);
    let mut evaluator = coefficient
        .replace(occupation)
        .with(1)
        .evaluator(&params)
        .build()?
        .map_coeff(&|coefficient| coefficient.re.to_f64());
    for point in [
        [0.75_f64, 0.0, 1.5, 0.0, 0.0, 0.5],
        [0.5, 1.0, 0.5, 1.0, 0.5, 0.5],
    ] {
        let q2 = point[..3].iter().map(|x| x * x).sum::<f64>();
        let p2 = point[3..].iter().map(|x| x * x).sum::<f64>();
        let energy = (q2 + 4.0).sqrt();
        let reference = point[0].powi(2)
            * (-q2 - p2 - 13.0).exp()
            * (2.0 * energy - 1.0 / energy - 3.0 * energy / q2);
        let actual = evaluator.evaluate_single(&point);
        assert!((actual - reference).abs() < 1.0e-12 * reference.abs());
    }
    Ok(())
}
