pub enum ThresholdCountertermSide {
    Amplitude,
    Left,
    Right,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Encode, Decode, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum ThresholdCountertermOrigin {
    Explicit,
    Autogenerated,
}

/// Physical association provenance retained without exposing internal Cartesian products.
#[derive(Clone, Debug, Encode, Decode)]
pub struct ResolvedThresholdCountertermAssociation {
    pub cut_id: Option<CutId>,
    pub cut_edges: Vec<EdgeIndex>,
    pub threshold_edges: Vec<EdgeIndex>,
    pub esurface_id: EsurfaceID,
    /// The association-local representation is retained because one raised semantic variant may
    /// aggregate equivalent subspaces expressed in different parent bases.
    pub subspace: SubspaceData,
    /// Whether omitting `parent_lmb` from a materialized default would select a different parent
    /// from the one used after graph-global cut-group rebasing.
    pub requires_explicit_parent_lmb: bool,
    pub eligible: bool,
    pub origin: ThresholdCountertermOrigin,
}

/// One independently generated threshold-counterterm variant after graph-local resolution.
#[derive(Clone, Debug, Encode, Decode)]
#[trait_decode(trait = GammaLoopContext)]
pub struct ResolvedThresholdCountertermVariant {
    pub name: String,
    pub center_group: Option<String>,
    pub cut_group_id: Option<CutGroupId>,
    pub associations: Vec<ResolvedThresholdCountertermAssociation>,
    pub side: ThresholdCountertermSide,
    pub threshold_esurface_ids: Vec<EsurfaceID>,
    pub raised_esurface_group: RaisedEsurfaceGroup,
    pub requested_subspace: Option<Vec<EdgeIndex>>,
    pub requested_parent_lmb: Option<Vec<EdgeIndex>>,
    pub resolved_parent_lmb: Vec<EdgeIndex>,
    pub subspace: SubspaceData,
    pub subspace_loop_count: usize,
    pub multiplier: Option<ThresholdCountertermMultiplier>,
}

/// One metadata-selected overlap family. Its common subspace is the union of all member
/// coordinates in one parent LMB; each member retains its own projected subspace and fixed
/// complement during the shared SOCP solve.
#[derive(Clone, Debug, Encode, Decode)]
#[trait_decode(trait = GammaLoopContext)]
pub struct ResolvedThresholdCountertermCenterGroup {
    pub name: String,
    pub subspace: SubspaceData,
    pub variant_ids: Vec<ThresholdCountertermVariantId>,
}

#[derive(Clone, Debug, Default, Encode, Decode)]
#[trait_decode(trait = GammaLoopContext)]
pub struct ResolvedCutGroupThresholdCounterterms {
    pub left: Vec<ThresholdCountertermVariantId>,
    pub right: Vec<ThresholdCountertermVariantId>,
}

impl ResolvedCutGroupThresholdCounterterms {
    pub(crate) fn iter_pairs(
        &self,
    ) -> impl Iterator<Item = (ThresholdCountertermVariantId, ThresholdCountertermVariantId)> + '_
    {
        self.left
            .iter()
            .copied()
            .flat_map(|left| self.right.iter().copied().map(move |right| (left, right)))
    }
}

/// Complete process-derived view. Pair products remain implicit in the left/right lists.
#[derive(Clone, Debug, Encode, Decode)]
#[trait_decode(trait = GammaLoopContext)]
pub struct ResolvedThresholdCounterterms {
    pub legacy_equivalent: bool,
    pub variants: TiVec<ThresholdCountertermVariantId, ResolvedThresholdCountertermVariant>,
    pub cross_section_cut_groups: TiVec<CutGroupId, ResolvedCutGroupThresholdCounterterms>,
    pub center_groups: Vec<ResolvedThresholdCountertermCenterGroup>,
}

/// Whether one resolved variant has symbolic content and can be reached by the generated
/// orientation subset. The two flags deliberately remain independent: an existing semantic slot
/// may be generated but inactive for a selected-orientation integrand.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ThresholdCountertermVariantStatus {
    pub generated: bool,
    pub active: bool,
}

/// A cut-local evaluator and the variants that reference it before graph-local IDs are assigned.
///
/// Multiplier collections deduplicate canonical scalar expressions within one input layout. This
/// neutral registration type lets the process metadata layer retain that exact deduplication
/// without depending on evaluator implementation details.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ThresholdCountertermEvaluatorRegistration {
    pub cut_group_id: Option<usize>,
    pub collection_evaluator_id: usize,
    pub expression: String,
    pub variant_ids: Vec<usize>,
}

