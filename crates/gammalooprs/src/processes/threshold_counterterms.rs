/// One canonical multiplier evaluator. IDs are contiguous within the graph, while the original
/// cut-local ID is retained to make standalone-archive validation direct.
#[derive(Clone, Debug, PartialEq, Eq, Encode, Decode, Serialize, Deserialize, JsonSchema)]
pub struct ThresholdCountertermEvaluatorMetadata {
    pub evaluator_id: usize,
    pub cut_group_id: Option<usize>,
    pub collection_evaluator_id: usize,
    pub expression: String,
    pub variant_ids: Vec<usize>,
}

/// Algebraic L/I component generated internally from the compact per-variant graph directives.
#[derive(
    Clone,
    Copy,
    Debug,
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    Encode,
    Decode,
    Serialize,
    Deserialize,
    JsonSchema,
)]
#[serde(rename_all = "snake_case")]
pub enum ThresholdCountertermComponentKind {
    Local,
    Integrated,
    LocalLocal,
    LocalIntegrated,
    IntegratedLocal,
    IntegratedIntegrated,
}

impl ThresholdCountertermComponentKind {
    pub fn variant_count(self) -> usize {
        match self {
            Self::Local | Self::Integrated => 1,
            Self::LocalLocal
            | Self::LocalIntegrated
            | Self::IntegratedLocal
            | Self::IntegratedIntegrated => 2,
        }
    }
}

/// Stable graph-local metadata for one expanded component.
///
/// `sign` is `-1` for a single-sided/amplitude counterterm and `+1` for an iterated LU term. The
/// event's bare and weighted values already include this sign.
#[derive(Clone, Debug, PartialEq, Eq, Encode, Decode, Serialize, Deserialize, JsonSchema)]
pub struct ThresholdCountertermComponentMetadata {
    pub component_id: usize,
    pub cut_group_id: Option<usize>,
    pub kind: ThresholdCountertermComponentKind,
    pub variant_ids: Vec<usize>,
    pub evaluator_ids: Vec<Option<usize>>,
    pub sign: i8,
}

/// Static counterterm metadata owned by one graph term in an integrand.
///
/// Events identify this registry through their existing graph ID and a component ID, so selecting
/// a subset of graphs never renumbers metadata inside a graph.
#[derive(Clone, Debug, PartialEq, Eq, Encode, Decode, Serialize, Deserialize, JsonSchema)]
pub struct ThresholdCountertermMetadataRegistry {
    pub graph_name: String,
    pub variants: Vec<ThresholdCountertermVariantMetadata>,
    pub evaluators: Vec<ThresholdCountertermEvaluatorMetadata>,
    pub components: Vec<ThresholdCountertermComponentMetadata>,
}

impl ThresholdCountertermMetadataRegistry {
    pub(crate) fn build(
        graph_name: impl Into<String>,
        resolved: &ResolvedThresholdCounterterms,
        all_lmbs: &TiVec<LmbIndex, LoopMomentumBasis>,
        variant_statuses: &[ThresholdCountertermVariantStatus],
        mut evaluator_registrations: Vec<ThresholdCountertermEvaluatorRegistration>,
    ) -> Result<Self> {
        if variant_statuses.len() != resolved.variants.len() {
            return Err(eyre!(
                "threshold-counterterm metadata has {} variant statuses for {} resolved variants",
                variant_statuses.len(),
                resolved.variants.len(),
            ));
        }

        let variants: Vec<_> = resolved
            .variants
            .iter_enumerated()
            .zip(variant_statuses)
            .map(
                |((variant_id, variant), status)| ThresholdCountertermVariantMetadata {
                    variant_id: variant_id.0,
                    name: variant.name.clone(),
                    center_group: variant.center_group.clone(),
                    cut_group_id: variant.cut_group_id.map(|id| id.0),
                    associations: variant
                        .associations
                        .iter()
                        .map(|association| ThresholdCountertermAssociationMetadata {
                            cut_id: association.cut_id.map(|id| id.0),
                            cut_edges: association.cut_edges.iter().map(|edge| edge.0).collect(),
                            threshold_edges: association
                                .threshold_edges
                                .iter()
                                .map(|edge| edge.0)
                                .collect(),
                            esurface_id: association.esurface_id.0,
                            eligible: association.eligible,
                            origin: association.origin,
                        })
                        .collect(),
                    side: variant.side,
                    threshold_esurface_ids: variant
                        .threshold_esurface_ids
                        .iter()
                        .map(|id| id.0)
                        .collect(),
                    requested_subspace: variant
                        .requested_subspace
                        .as_ref()
                        .map(|edges| edges.iter().map(|edge| edge.0).collect()),
                    resolved_subspace: variant
                        .subspace
                        .iter_basis_edges(all_lmbs)
                        .map(|edge| edge.0)
                        .collect(),
                    requested_parent_lmb: variant
                        .requested_parent_lmb
                        .as_ref()
                        .map(|edges| edges.iter().map(|edge| edge.0).collect()),
                    resolved_parent_lmb: variant
                        .resolved_parent_lmb
                        .iter()
                        .map(|edge| edge.0)
                        .collect(),
                    subspace_loop_count: variant.subspace_loop_count,
                    multiplier: variant.multiplier.as_ref().map(|multiplier| {
                        ThresholdCountertermMultiplierMetadata {
                            expression: multiplier.expression.clone(),
                            symmetrize: multiplier.symmetrize,
                            opaque_derivatives: multiplier.opaque_derivatives,
                        }
                    }),
                    generated: status.generated,
                    active: status.active,
                },
            )
            .collect();

        evaluator_registrations.sort_by_key(|registration| {
            (
                registration.cut_group_id,
                registration.collection_evaluator_id,
            )
        });
        let mut seen_local_evaluators = BTreeSet::new();
        let mut next_local_evaluator = BTreeMap::<Option<usize>, usize>::new();
        let mut variant_evaluators = BTreeMap::<(Option<usize>, usize), usize>::new();
        let mut evaluators = Vec::with_capacity(evaluator_registrations.len());
        for mut registration in evaluator_registrations {
            let local_key = (
                registration.cut_group_id,
                registration.collection_evaluator_id,
            );
            if !seen_local_evaluators.insert(local_key) {
                return Err(eyre!(
                    "duplicate threshold-multiplier evaluator {} in cut group {:?}",
                    registration.collection_evaluator_id,
                    registration.cut_group_id,
                ));
            }
            let next = next_local_evaluator
                .entry(registration.cut_group_id)
                .or_default();
            if registration.collection_evaluator_id != *next {
                return Err(eyre!(
                    "threshold-multiplier evaluator IDs in cut group {:?} are not contiguous: expected {}, got {}",
                    registration.cut_group_id,
                    *next,
                    registration.collection_evaluator_id,
                ));
            }
            *next += 1;

            registration.variant_ids.sort_unstable();
            if registration
                .variant_ids
                .windows(2)
                .any(|ids| ids[0] == ids[1])
            {
                return Err(eyre!(
                    "threshold-multiplier evaluator {} in cut group {:?} lists a variant more than once",
                    registration.collection_evaluator_id,
                    registration.cut_group_id,
                ));
            }
            let evaluator_id = evaluators.len();
            for &variant_id in &registration.variant_ids {
                let variant = variants.get(variant_id).ok_or_else(|| {
                    eyre!(
                        "threshold-multiplier evaluator {} refers to missing variant {}",
                        registration.collection_evaluator_id,
                        variant_id,
                    )
                })?;
                if variant.cut_group_id != registration.cut_group_id {
                    return Err(eyre!(
                        "threshold-multiplier evaluator {} cut group {:?} disagrees with variant {} cut group {:?}",
                        registration.collection_evaluator_id,
                        registration.cut_group_id,
                        variant_id,
                        variant.cut_group_id,
                    ));
                }
                if variant.multiplier.is_none() {
                    return Err(eyre!(
                        "identity threshold-counterterm variant {} unexpectedly references multiplier evaluator {}",
                        variant_id,
                        registration.collection_evaluator_id,
                    ));
                }
                if variant_evaluators
                    .insert((registration.cut_group_id, variant_id), evaluator_id)
                    .is_some()
                {
                    return Err(eyre!(
                        "threshold-counterterm variant {} has more than one evaluator in cut group {:?}",
                        variant_id,
                        registration.cut_group_id,
                    ));
                }
            }
            evaluators.push(ThresholdCountertermEvaluatorMetadata {
                evaluator_id,
                cut_group_id: registration.cut_group_id,
                collection_evaluator_id: registration.collection_evaluator_id,
                expression: registration.expression,
                variant_ids: registration.variant_ids,
            });
        }

        for variant in &variants {
            let has_evaluator =
                variant_evaluators.contains_key(&(variant.cut_group_id, variant.variant_id));
            if variant.multiplier.is_some() != has_evaluator {
                return Err(eyre!(
                    "threshold-counterterm variant {} multiplier/evaluator metadata disagree",
                    variant.variant_id,
                ));
            }
        }

        let evaluator_ids = |cut_group_id: Option<usize>, variant_ids: &[usize]| {
            variant_ids
                .iter()
                .map(|variant_id| {
                    variant_evaluators
                        .get(&(cut_group_id, *variant_id))
                        .copied()
                })
                .collect()
        };
        let mut components = Vec::new();
        let mut push_component = |cut_group_id, kind, variant_ids: Vec<usize>, sign| {
            let component_id = components.len();
            let component_evaluator_ids = evaluator_ids(cut_group_id, &variant_ids);
            components.push(ThresholdCountertermComponentMetadata {
                component_id,
                cut_group_id,
                kind,
                variant_ids,
                evaluator_ids: component_evaluator_ids,
                sign,
            });
        };

        let is_amplitude = variants
            .iter()
            .all(|variant| variant.side == ThresholdCountertermSide::Amplitude);
        if is_amplitude {
            for variant in &variants {
                push_component(
                    None,
                    ThresholdCountertermComponentKind::Local,
                    vec![variant.variant_id],
                    -1,
                );
                push_component(
                    None,
                    ThresholdCountertermComponentKind::Integrated,
                    vec![variant.variant_id],
                    -1,
                );
            }
        } else {
            if variants
                .iter()
                .any(|variant| variant.side == ThresholdCountertermSide::Amplitude)
            {
                return Err(eyre!(
                    "threshold-counterterm metadata cannot mix amplitude and LU variants"
                ));
            }
            for (cut_group_id, group) in resolved.cross_section_cut_groups.iter_enumerated() {
                let cut_group = Some(cut_group_id.0);
                for variant_id in group.left.iter().chain(&group.right) {
                    push_component(
                        cut_group,
                        ThresholdCountertermComponentKind::Local,
                        vec![variant_id.0],
                        -1,
                    );
                    push_component(
                        cut_group,
                        ThresholdCountertermComponentKind::Integrated,
                        vec![variant_id.0],
                        -1,
                    );
                }
                for (left, right) in group.iter_pairs() {
                    let pair = vec![left.0, right.0];
                    for kind in [
                        ThresholdCountertermComponentKind::LocalLocal,
                        ThresholdCountertermComponentKind::LocalIntegrated,
                        ThresholdCountertermComponentKind::IntegratedLocal,
                        ThresholdCountertermComponentKind::IntegratedIntegrated,
                    ] {
                        push_component(cut_group, kind, pair.clone(), 1);
                    }
                }
            }
        }

        let registry = Self {
            graph_name: graph_name.into(),
            variants,
            evaluators,
            components,
        };
        registry.validate()?;
        Ok(registry)
    }

    /// Resolve the stable component slot generated for one expanded threshold-counterterm term.
    pub(crate) fn component_id(
        &self,
        cut_group_id: Option<CutGroupId>,
        kind: ThresholdCountertermComponentKind,
        variant_ids: &[ThresholdCountertermVariantId],
    ) -> Result<usize> {
        self.components
            .iter()
            .find(|component| {
                component.cut_group_id == cut_group_id.map(|id| id.0)
                    && component.kind == kind
                    && component.variant_ids.len() == variant_ids.len()
                    && component
                        .variant_ids
                        .iter()
                        .zip(variant_ids)
                        .all(|(stored, requested)| *stored == requested.0)
            })
            .map(|component| component.component_id)
            .ok_or_else(|| {
                eyre!(
                    "threshold-counterterm metadata has no {:?} component for cut group {:?} and variants {:?}",
                    kind,
                    cut_group_id.map(|id| id.0),
                    variant_ids.iter().map(|id| id.0).collect::<Vec<_>>(),
                )
            })
    }

    /// Return runtime threshold IDs in the same order as the generated LU side collection.
    ///
    /// This lookup is needed when an explicit normalized legacy document owns metadata but keeps
    /// the homogeneous overlap path (`variant_subspaces = None`). Local components appear once per
    /// variant and are emitted left-before-right in exactly the runtime collection order.
    pub(crate) fn lu_variant_ids(
        &self,
        cut_group_id: CutGroupId,
        side: ThresholdCountertermSide,
    ) -> Result<Vec<ThresholdCountertermVariantId>> {
        if side == ThresholdCountertermSide::Amplitude {
            return Err(eyre!(
                "amplitude threshold variants do not belong to LU cut group {}",
                cut_group_id.0,
            ));
        }

        Ok(self
            .components
            .iter()
            .filter(|component| {
                component.cut_group_id == Some(cut_group_id.0)
                    && component.kind == ThresholdCountertermComponentKind::Local
            })
            .filter_map(|component| {
                let variant_id = *component.variant_ids.first()?;
                (self.variants.get(variant_id)?.side == side)
                    .then_some(ThresholdCountertermVariantId(variant_id))
            })
            .collect())
    }

    pub fn validate(&self) -> Result<()> {
        for (variant_id, variant) in self.variants.iter().enumerate() {
            if variant.variant_id != variant_id {
                return Err(eyre!(
                    "threshold-counterterm variant metadata ID {} is stored at index {}",
                    variant.variant_id,
                    variant_id,
                ));
            }
        }
        for (evaluator_id, evaluator) in self.evaluators.iter().enumerate() {
            if evaluator.evaluator_id != evaluator_id {
                return Err(eyre!(
                    "threshold-counterterm evaluator metadata ID {} is stored at index {}",
                    evaluator.evaluator_id,
                    evaluator_id,
                ));
            }
            if evaluator
                .variant_ids
                .iter()
                .any(|variant_id| *variant_id >= self.variants.len())
            {
                return Err(eyre!(
                    "threshold-counterterm evaluator {} refers to a missing variant",
                    evaluator_id,
                ));
            }
        }
        for (component_id, component) in self.components.iter().enumerate() {
            if component.component_id != component_id {
                return Err(eyre!(
                    "threshold-counterterm component metadata ID {} is stored at index {}",
                    component.component_id,
                    component_id,
                ));
            }
            let expected_variants = component.kind.variant_count();
            if component.variant_ids.len() != expected_variants
                || component.evaluator_ids.len() != expected_variants
            {
                return Err(eyre!(
                    "threshold-counterterm component {} kind {:?} requires {} aligned variant/evaluator references",
                    component_id,
                    component.kind,
                    expected_variants,
                ));
            }
            for (&variant_id, &evaluator_id) in
                component.variant_ids.iter().zip(&component.evaluator_ids)
            {
                let variant = self.variants.get(variant_id).ok_or_else(|| {
                    eyre!(
                        "threshold-counterterm component {} refers to missing variant {}",
                        component_id,
                        variant_id,
                    )
                })?;
                if variant.cut_group_id != component.cut_group_id {
                    return Err(eyre!(
                        "threshold-counterterm component {} and variant {} have different cut groups",
                        component_id,
                        variant_id,
                    ));
                }
                match evaluator_id {
                    Some(evaluator_id) => {
                        let evaluator = self.evaluators.get(evaluator_id).ok_or_else(|| {
                            eyre!(
                                "threshold-counterterm component {} refers to missing evaluator {}",
                                component_id,
                                evaluator_id,
                            )
                        })?;
                        if evaluator.cut_group_id != component.cut_group_id
                            || !evaluator.variant_ids.contains(&variant_id)
                        {
                            return Err(eyre!(
                                "threshold-counterterm component {} evaluator {} is not registered for variant {}",
                                component_id,
                                evaluator_id,
                                variant_id,
                            ));
                        }
                    }
                    None if variant.multiplier.is_none() => {}
                    None => {
                        return Err(eyre!(
                            "threshold-counterterm component {} omits the evaluator for multiplier variant {}",
                            component_id,
                            variant_id,
                        ));
                    }
                }
            }
            let expected_sign = if expected_variants == 1 { -1 } else { 1 };
            if component.sign != expected_sign {
                return Err(eyre!(
                    "threshold-counterterm component {} has sign {}, expected {}",
                    component_id,
                    component.sign,
                    expected_sign,
                ));
            }
        }
        Ok(())
    }
}

impl ResolvedThresholdCounterterms {
    /// Add eligible synthesized legacy defaults to the compact graph document.
    ///
    /// Explicit and dormant declarations are retained verbatim at the semantic TOML level. The
    /// generated completion contains no inferred side, pair, or L/I component records.
    pub(crate) fn materialized_spec(
        &self,
        raw: &ThresholdCountertermSpec,
        all_lmbs: &TiVec<LmbIndex, LoopMomentumBasis>,
    ) -> ThresholdCountertermSpec {
        let mut materialized = raw.clone();

        for variant in &self.variants {
            for association in variant.associations.iter().filter(|association| {
                association.eligible
                    && association.origin == ThresholdCountertermOrigin::Autogenerated
            }) {
                let resolved_subspace = association
                    .subspace
                    .iter_basis_edges(all_lmbs)
                    .collect::<Vec<_>>();
                let resolved_parent_lmb = association.requires_explicit_parent_lmb.then(|| {
                    association
                        .subspace
                        .get_lmb(all_lmbs)
                        .loop_edges
                        .iter()
                        .copied()
                        .collect()
                });
                let cut = if let Some(index) = materialized
                    .cuts
                    .iter()
                    .position(|cut| cut.edges == association.cut_edges)
                {
                    &mut materialized.cuts[index]
                } else {
                    materialized.cuts.push(ThresholdCountertermCut {
                        edges: association.cut_edges.clone(),
                        thresholds: Vec::new(),
                    });
                    materialized.cuts.last_mut().unwrap()
                };

                let threshold = if let Some(index) = cut
                    .thresholds
                    .iter()
                    .position(|threshold| threshold.edges == association.threshold_edges)
                {
                    &mut cut.thresholds[index]
                } else {
                    cut.thresholds.push(ThresholdCountertermThreshold {
                        edges: association.threshold_edges.clone(),
                        counterterms: Vec::new(),
                    });
                    cut.thresholds.last_mut().unwrap()
                };

                if threshold.counterterms.is_empty() {
                    threshold.counterterms.push(ThresholdCountertermVariant {
                        name: Some("default".to_string()),
                        center_group: None,
                        subspace: Some(resolved_subspace),
                        parent_lmb: resolved_parent_lmb,
                        disable: false,
                        multiplier: None,
                    });
                }
            }
        }

        for cut in &mut materialized.cuts {
            cut.thresholds
                .sort_by(|left, right| left.edges.cmp(&right.edges));
        }
        materialized
            .cuts
            .sort_by(|left, right| left.edges.cmp(&right.edges));
        materialized
    }
}

