    #[test]
    fn materialized_raised_defaults_round_trip_association_local_embeddings() {
        test_initialise().unwrap();
        let graph: Graph = dot!(digraph raised_materialized_threshold_defaults {
            ext [style=invis]
            edge [num=1 mass=0]
            node [num=1]
            ext->v1:0 [id=0]
            v1->v2 [id=1]
            v2->v1 [id=2]
            v1->v2 [id=3]
            ext->v2:1 [id=4]
        })
        .unwrap();
        let all_lmbs = graph.generate_loop_momentum_bases();
        let containing_subgraph = graph.full_filter();
        let subspaces = all_lmbs
            .iter_enumerated()
            .filter_map(|(lmb_index, _)| {
                SubspaceData::new_with_user_selected_lmb(
                    containing_subgraph.clone(),
                    lmb_index,
                    &graph,
                    &all_lmbs,
                )
                .ok()
            })
            .collect::<Vec<_>>();
        let (implicit_subspace, rebased_subspace) = subspaces
            .iter()
            .enumerate()
            .flat_map(|(left_index, left)| {
                subspaces
                    .iter()
                    .skip(left_index + 1)
                    .map(move |right| (left, right))
            })
            .find(|(left, right)| {
                left.parent_lmb_index() != right.parent_lmb_index()
                    && left.has_equivalent_embedding(right, &all_lmbs)
            })
            .expect("the two-loop fixture must admit equivalent distinct parent LMBs");
        assert!(!implicit_subspace.has_same_embedding(rebased_subspace));

        let association = |threshold_edges: Vec<EdgeIndex>,
                           esurface_id: usize,
                           subspace: &SubspaceData,
                           requires_explicit_parent_lmb| {
            ResolvedThresholdCountertermAssociation {
                cut_id: None,
                cut_edges: Vec::new(),
                threshold_edges,
                esurface_id: crate::cff::esurface::EsurfaceID::from(esurface_id),
                subspace: subspace.clone(),
                requires_explicit_parent_lmb,
                eligible: true,
                origin: ThresholdCountertermOrigin::Autogenerated,
            }
        };
        let associations = vec![
            association(
                vec![EdgeIndex::from(1), EdgeIndex::from(2)],
                0,
                implicit_subspace,
                false,
            ),
            association(
                vec![EdgeIndex::from(2), EdgeIndex::from(3)],
                1,
                rebased_subspace,
                true,
            ),
        ];
        let resolved = ResolvedThresholdCounterterms {
            legacy_equivalent: true,
            variants: TiVec::from(vec![ResolvedThresholdCountertermVariant {
                name: "default".to_string(),
                center_group: None,
                cut_group_id: None,
                associations: associations.clone(),
                side: ThresholdCountertermSide::Amplitude,
                threshold_esurface_ids: vec![
                    crate::cff::esurface::EsurfaceID::from(0),
                    crate::cff::esurface::EsurfaceID::from(1),
                ],
                raised_esurface_group: crate::cff::esurface::RaisedEsurfaceGroup {
                    esurface_ids: vec![
                        crate::cff::esurface::EsurfaceID::from(0),
                        crate::cff::esurface::EsurfaceID::from(1),
                    ],
                    max_occurence: 2,
                },
                requested_subspace: None,
                requested_parent_lmb: None,
                resolved_parent_lmb: implicit_subspace
                    .get_lmb(&all_lmbs)
                    .loop_edges
                    .iter()
                    .copied()
                    .collect(),
                subspace: implicit_subspace.clone(),
                subspace_loop_count: implicit_subspace.loopcount(),
                multiplier: None,
            }]),
            cross_section_cut_groups: TiVec::new(),
            center_groups: Vec::new(),
        };

        let materialized =
            resolved.materialized_spec(&ThresholdCountertermSpec::default(), &all_lmbs);
        let reparsed = ThresholdCountertermSpec::parse_toml(
            &materialized
                .to_toml()
                .expect("materialized defaults must serialize"),
        )
        .expect("materialized defaults must parse");
        assert_eq!(reparsed.cuts.len(), 1);
        assert_eq!(reparsed.cuts[0].thresholds.len(), 2);

        for (threshold, association) in reparsed.cuts[0].thresholds.iter().zip(&associations) {
            let counterterm = &threshold.counterterms[0];
            let parent_lmb_index = counterterm
                .parent_lmb
                .as_ref()
                .map(|parent| {
                    all_lmbs
                        .iter_enumerated()
                        .find_map(|(lmb_index, lmb)| {
                            lmb.loop_edges.iter().eq(parent.iter()).then_some(lmb_index)
                        })
                        .expect("serialized parent LMB must be generated")
                })
                .unwrap_or_else(|| implicit_subspace.parent_lmb_index());
            let round_tripped = SubspaceData::new_from_parent_basis_edges(
                counterterm.subspace.as_deref().unwrap(),
                &containing_subgraph,
                parent_lmb_index,
                &graph,
                &all_lmbs,
            )
            .expect("materialized association must reconstruct");
            assert!(round_tripped.has_same_embedding(&association.subspace));
            assert!(round_tripped.has_equivalent_embedding(implicit_subspace, &all_lmbs));
        }

        assert!(
            reparsed.cuts[0].thresholds[0].counterterms[0]
                .parent_lmb
                .is_none()
        );
        assert_eq!(
            reparsed.cuts[0].thresholds[1].counterterms[0].parent_lmb,
            Some(
                rebased_subspace
                    .get_lmb(&all_lmbs)
                    .loop_edges
                    .iter()
                    .copied()
                    .collect()
            ),
        );
    }

