#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub(crate) struct Local4dCts(Atom);
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub(crate) struct Full4dCts(Atom);

impl Full4dCts {
    pub(crate) fn atom(&self) -> &Atom {
        &self.0
    }

    /// Insert completed child poles into a parent UV limit. The loop-measure
    /// marker carries precisely the integrations already consumed by these
    /// children, as in the ordinary forest's `IntegratedCts::pole_atom`.
    pub(crate) fn from_counterterm_product(poles: Atom, consumed_loops: usize) -> Self {
        Self(poles * Atom::var(GS.integrated_loop_scale).pow(4 * consumed_loops as i64))
    }

    /// Pole-part subtraction inserts only completed poles; MUV keeps the local
    /// counterterm together with its integrated finite contribution.
    pub(crate) fn recursion_input(
        local: &Local4dCts,
        integrated: &IntegratedCts,
        scheme: ApproximationType,
        is_root: bool,
    ) -> Result<Self> {
        match scheme {
            ApproximationType::MUV => Ok(Self(&local.0 + integrated.finite_counterterm_atom())),
            ApproximationType::PolePart if !is_root => Ok(Self(integrated.pole_atom())),
            ApproximationType::PolePart => Ok(Self(&local.0 + integrated.pole_atom())),
            scheme => Err(eyre!("No recursive counterterm projection for {scheme}")),
        }
    }

    /// A disconnected local value already contains every component's recursive
    /// projection, so it must not be projected again when used by an outer limit.
    pub(crate) fn from_factorized_local(local: &Local4dCts) -> Self {
        Self(local.0.clone())
    }
}

impl Neg for Local4dCts {
    type Output = Local4dCts;
    fn neg(self) -> Self::Output {
        Local4dCts(-&self.0)
    }
}

impl Local4dCts {
    pub(crate) fn atom(&self) -> &Atom {
        &self.0
    }

    pub(crate) fn from_full_product(factors: impl IntoIterator<Item = Full4dCts>) -> Self {
        Self(
            factors
                .into_iter()
                .fold(Atom::one(), |product, factor| product * factor.0),
        )
    }
}

impl Rooted for Local4dCts {
    fn root() -> Self {
        Self(Atom::one())
    }
}

pub struct Local4d;

impl Graph {
    pub(crate) fn uv_rescaled(
        &self,
        replacement_subgraph: &SuBitGraph,
        n_loops: usize,
        lmb: &LoopMomentumBasis,
        atom: &Atom,
    ) -> Atom {
        let _stage = StageSpan::new("gamma.local.uv_rescale");
        let momentum_stage = StageSpan::new("gamma.local.rescale_momenta");
        // only apply replacements for edges in the reduced graph
        let mom_reps = self.uv_wrapped_replacement(replacement_subgraph, lmb, &[W_.x___]);
        let mut atomarg = atom.replace_multiple(&mom_reps);

        // Keep one top-down pass per loop label: nested momentum/index metadata
        // can contain other loop labels, which later passes must still rescale.
        for edge in &lmb.loop_edges {
            let edge = Atom::num(usize::from(*edge));
            atomarg = atomarg.replace_map(|part, _, out| {
                if let AtomView::Fun(momentum) = part
                    && momentum.get_symbol() == GS.emr_mom
                    && momentum.get_nargs() > 0
                    && momentum.get(0) == edge.as_view()
                {
                    **out = part.to_owned() / GS.rescale;
                }
            });
        }
        drop(momentum_stage);

        // Free `mUVexp` occurrences are left untouched here: with the
        // inverse loop-momentum expansion, soft dependence is generated by
        // the shifted hard momenta and denominator expansion rather than by
        // an explicit soft rescaling pass.

        // Free `mUV` occurrences come from previously integrated CT coefficients.
        // They are hard vacuum scales in the parent UV expansion and therefore
        // carry the same weight as the parent loop momentum. The denominator
        // rewrite below introduces the unscaled vacuum mass for the parent
        // propagator basis.
        // The stored scale restores consumed loop measures independently of mUV.
        // These independent leaf substitutions commute, including inside metadata.
        let mass_stage = StageSpan::new("gamma.local.rescale_masses");
        let scaled_mass = Atom::var(GS.m_uv_vacuum) / GS.rescale;
        let consumed_scale = Atom::var(GS.integrated_loop_scale) * GS.rescale;
        atomarg = atomarg.replace_map(|part, _, out| {
            if let AtomView::Var(variable) = part {
                if variable.get_symbol() == GS.m_uv_vacuum {
                    **out = scaled_mass.clone();
                } else if variable.get_symbol() == GS.integrated_loop_scale {
                    **out = consumed_scale.clone();
                }
            }
        });
        drop(mass_stage);

        let denominator_stage = StageSpan::new("gamma.local.deform_denominators");
        let tsquare = Atom::var(GS.rescale).pow(2);
        let m_uv_expansion_sq = Atom::var(GS.m_uv_expansion).pow(2);
        let m_uv_vacuum_sq = Atom::var(GS.m_uv_vacuum).pow(2);

        debug_tags!(#uv, #integrated, #inspect;
            log.res = atomarg,
            "Rescaled momenta expanded"
        );
        // Keep the two passes separate: a non-four-argument outer den can contain
        // a four-argument inner den that the deformation pass must first visit.
        // Both callbacks are pure; bound reuse of identical RHSs to this call.
        atomarg = atomarg
            .replace(GS.den(W_.a_, W_.mom_, W_.mass_, W_.prop_))
            .rhs_cache_size(128)
            .with_map(move |m| {
                let edge = m.get(W_.a_).unwrap().to_atom();
                let momentum = m.get(W_.mom_).unwrap().to_atom();
                let mass = m.get(W_.mass_).unwrap().to_atom();
                let propagator = m.get(W_.prop_).unwrap().to_atom();

                let (mass, propagator) = if mass == m_uv_expansion_sq {
                    // The MUV deformation was already introduced by an inner UV limit.
                    // Rescale it without adding the vacuum mass a second time.
                    (mass, propagator * &tsquare)
                } else {
                    (
                        mass * &tsquare + &m_uv_expansion_sq,
                        propagator * &tsquare + &m_uv_expansion_sq * &tsquare - &m_uv_vacuum_sq,
                    )
                };

                GS.den(edge, momentum, mass, propagator) / &tsquare
            })
            .replace(function!(GS.den, W_.a_, W_.mom_, W_.a___))
            .rhs_cache_size(128)
            .with_map(move |m| {
                let mut f = symbolica::atom::FunctionBuilder::new(GS.den);
                f = f.add_arg(m.get(W_.a_).unwrap().to_atom());
                f = f.add_arg(
                    (m.get(W_.mom_).unwrap().to_atom() * GS.rescale)
                        .expand()
                        .replace(GS.rescale)
                        .with(Atom::Zero),
                );
                f = f.add_arg(m.get(W_.a___).unwrap().to_atom());
                f.finish()
            });

        atomarg *= Atom::var(GS.rescale).pow(-4 * n_loops as i64);
        drop(denominator_stage);
        atomarg
    }
}

/// Add the numerator of the reduced subgraph, (without given), to the integrand,
/// with 4d -> d-dim on minkowski indices, and apply the UV rescaling.
///
/// The Feynman rules stay factorized: the rescaling expresses every momentum
/// in the loop-momentum basis of the UV limit and scales its loop momenta, but
/// contracts and expands nothing.
#[debug_instrument(
        current = %current.log_display(),
        given = %given.log_display(),
    )]
fn grow<S: super::ForestNodeLike>(
    integrand: &Full4dCts,
    ctx: &UVCtx<'_>,
    current: &S,
    given: &S,
    lmb: &LoopMomentumBasis,
) -> Result<Atom> {
    let _stage = StageSpan::new("gamma.local.grow");
    let reduced = current.reduced_subgraph(given);
    let graph = ctx.graph;
    let n_loops = graph.n_loops(current.subgraph());

    let numerator_stage = StageSpan::new("gamma.local.feynman_numerator");
    let mut t_arg = ctx
        .graph
        .numerator(&reduced, given.subgraph())
        .to_d_dim(GS.dim)
        .get_single_atom()
        .unwrap();
    drop(numerator_stage);

    let denominator_stage = StageSpan::new("gamma.local.feynman_denominator");
    t_arg /= graph.denominator(&reduced, ctx.model, |_| 1);
    let input = integrand.atom() * t_arg;
    drop(denominator_stage);

    let rescaled = graph.uv_rescaled(&reduced, n_loops, lmb, &input);
    debug_tags!(#uv, #integrated, #rescaled; log.res = rescaled, reduced = %reduced.string_label(), "Rescaled factorized integrand");
    Ok(rescaled)
}

fn local_cooking() -> CookSettings {
    CookSettings::indices()
        .with_mode(CookMode::ReversibleEncoding)
        .with_representation_payloads(true, true)
}

/// Fill in and contract a tensor product to dot products, keeping
/// factorization, with gamma-matrix and epsilon-tensor simplification.
fn contract_to_dots(expression: &Atom) -> Result<Atom> {
    let cooking = local_cooking();
    let contracted = SymbolicTensor::infer_indexed(cooking.try_cook(expression.as_view())?)?
        .simplify_algebra(&AlgebraSettings {
            gamma: Some(GammaSimplifySettings::default()),
            epsilon: true,
            contract: AlgebraContraction::Dots,
            ..Default::default()
        })?;
    Ok(cooking.uncook(contracted.expression().as_view()))
}

/// Upper bound on the number of truncated tensor products before the
/// expansion falls back to contracting the complete product.
const MAX_TRUNCATED_NETWORKS: usize = 4096;

/// An integer exponent of the rescaling parameter, if it is one.
fn integer_exponent(exponent: &Rational) -> Option<i64> {
    exponent
        .is_integer()
        .then(|| exponent.numerator().to_i64())
        .flatten()
}

/// Truncate the Taylor expansion in the rescaling parameter before the tensor
/// contraction.
///
/// The UV limit keeps the terms of `rescaled` through order zero. Each factor
/// of the product contributes at least its own leading order, so a factor
/// needs only its orders up to its leading order plus the overall depth
/// `-sum(leading orders)`. Every open-index factor is expanded to that depth
/// and only the products of total order at most zero are contracted, one at a
/// time. The contraction of the complete product instead builds all orders,
/// most of which the truncation discards.
///
/// Returns `None` when the expansion is not an integer power series or would
/// need more than [`MAX_TRUNCATED_NETWORKS`] products.
fn contract_truncated(rescaled: &Atom) -> Result<Option<Atom>> {
    let _stage = StageSpan::new("gamma.local.truncated_contraction");
    let factors: Vec<Atom> = match rescaled.as_view() {
        AtomView::Mul(product) => product.iter().map(|factor| factor.to_owned()).collect(),
        _ => vec![rescaled.clone()],
    };
    let cooking = local_cooking();
    let mut leading_orders = Vec::with_capacity(factors.len());
    for factor in &factors {
        let series = factor
            .series(GS.rescale, Atom::Zero, SeriesDepth::relative(1))
            .map_err(|error| eyre!("leading order of a local UV factor: {error}"))?;
        if series.is_zero() {
            return Ok(Some(Atom::Zero));
        }
        let Some(order) = integer_exponent(&series.get_trailing_exponent()) else {
            return Ok(None);
        };
        leading_orders.push(order);
    }
    let depth = -leading_orders.iter().sum::<i64>();
    if depth < 0 {
        return Ok(Some(Atom::Zero));
    }

    let mut scalars = Atom::num(1);
    let mut networks = vec![(0, Atom::num(1))];
    for (factor, leading) in factors.iter().zip(&leading_orders) {
        let open = !SymbolicTensor::infer(cooking.try_cook(factor.as_view())?)?
            .structure()
            .logical_slots()
            .is_empty();
        if !open {
            // Scalars, including the denominators, join the final series.
            scalars *= factor;
            continue;
        }
        if !factor.as_view().contains_symbol(GS.rescale) {
            for (_, network) in &mut networks {
                *network *= factor;
            }
            continue;
        }
        let series = factor
            .series(GS.rescale, Atom::Zero, leading + depth)
            .map_err(|error| eyre!("expansion of a local UV factor: {error}"))?;
        let mut orders = Vec::new();
        for (exponent, coefficient) in series.terms() {
            if coefficient.is_zero() {
                continue;
            }
            let Some(exponent) = integer_exponent(&exponent) else {
                return Ok(None);
            };
            orders.push((
                exponent - leading,
                coefficient * Atom::var(GS.rescale).pow(exponent),
            ));
        }
        let mut next = Vec::new();
        for (order, network) in &networks {
            for (relative, term) in &orders {
                if order + relative <= depth {
                    next.push((order + relative, network * term));
                }
            }
        }
        if next.len() > MAX_TRUNCATED_NETWORKS {
            return Ok(None);
        }
        networks = next;
    }

    let mut contracted = Atom::Zero;
    for (_, network) in &networks {
        contracted += contract_to_dots(network)?;
    }
    Ok(Some(scalars * contracted))
}

#[debug_instrument(
        current = %current.log_display(),
        given = %given.log_display(),
    )]
fn t<S: super::ForestNodeLike>(
    rescaled: &Atom,
    ctx: &UVCtx<'_>,
    current: &S,
    given: &S,
) -> Result<Local4dCts> {
    let _stage = StageSpan::new("gamma.local.taylor");
    let _ = (ctx, current, given);

    let contraction_stage = StageSpan::new("gamma.local.contraction");
    let contracted = match contract_truncated(rescaled)? {
        Some(contracted) => contracted,
        None => contract_to_dots(rescaled)?,
    };
    drop(contraction_stage);

    let series_stage = StageSpan::new("gamma.local.taylor_series");
    let series = contracted
        .series(GS.rescale, Atom::Zero, 0)
        .unwrap()
        .to_atom();
    drop(series_stage);
    debug_tags!(#uv,#integrated, #series;log.res = series, "Series expanded");

    let substitution_stage = StageSpan::new("gamma.local.evaluate_scale");
    let evalutated = series.replace(GS.rescale).with(Atom::num(1));
    drop(substitution_stage);
    debug_tags!(#uv,#integrated,#series;log.res = evalutated, "Evaluated at t = 1");

    let algebra_stage = StageSpan::new("gamma.local.gamma_metric_algebra");
    let cooking = local_cooking();
    let simplified = SymbolicTensor::infer_indexed(cooking.try_cook(evalutated.as_view())?)?
        .simplify_algebra(&AlgebraSettings {
            gamma: Some(GammaSimplifySettings::default()),
            epsilon: true,
            contract: AlgebraContraction::Dots,
            ..Default::default()
        })?
        .to_dots()?;
    let dotted = cooking.uncook(simplified.expression().as_view());
    drop(algebra_stage);
    debug_tags!(#uv, #integrated, #vakint, #profile, #trace, #dots;
        log.expr = dotted,
        "Shared tensor and Dirac simplification of the local UV Taylor coefficient"
    );

    Ok(Local4dCts(dotted))
}

/// A loop-momentum basis of the current subgraph that keeps the child loops
/// as a subset, so integrating the child commutes with the outer Taylor
/// expansion.
fn uv_lmb<S: ForestNodeLike>(
    ctx: &UVCtx<'_>,
    current: &S,
    given: &S,
) -> Result<LoopMomentumBasis> {
    let graph = ctx.graph;
    let is_compatible = |candidate: &LoopMomentumBasis| {
        given
            .lmb()
            .loop_edges
            .iter()
            .all(|edge| candidate.loop_edges.contains(edge))
            && candidate
                .loop_edges
                .iter()
                .filter(|edge| given.subgraph().includes(&graph[*edge].1))
                .count()
                == given.lmb().loop_edges.len()
    };
    if given.subgraph().is_empty() || is_compatible(current.lmb()) {
        Ok(current.lmb().clone())
    } else {
        graph
            .generate_loop_momentum_bases_of(current.subgraph())
            .into_iter()
            .find(is_compatible)
            .ok_or_else(|| eyre!("no loop momentum basis compatible with nested UV subgraph"))
    }
}

pub(crate) fn uv_limit<S: ForestNodeLike, M: ForestNodeLike>(
    integrand: &Full4dCts,
    ctx: &UVCtx<'_>,
    current: &S,
    given: &S,
    marker_current: &M,
    marker_given: &M,
) -> Result<Local4dCts> {
    let _stage = StageSpan::new("gamma.local.uv_limit");
    match current.renormalization_scheme() {
        ApproximationType::MUV | ApproximationType::PolePart => {
            let lmb = uv_lmb(ctx, current, given)?;
            let grown = grow(integrand, ctx, current, given, &lmb)?;
            let result = -t(&grown, ctx, current, given)?;
            Ok(Local4dCts(UvMarker::new(ctx.settings).apply(
                UvOperation::Approx,
                marker_current.subgraph(),
                marker_given.subgraph(),
                result.atom(),
            )))
        }
        atype => Err(eyre!("Not yet implemented {:?}", atype)),
    }
}

