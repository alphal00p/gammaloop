    #[test]
    #[ignore = "manual rescaling microbenchmark; run in release for performance comparisons"]
    fn uv_rescaled_dressed_two_loop_gluon_microbenchmark() -> Result<()> {
        test_initialise()?;
        let model = load_generic_model("sm");
        let options = GenerationOptions::default()
            .with_loop_count(2, 2)?
            .max_vertices(4)
            .allow_self_loops(false)
            .projector(Atom::one())
            .numerator_grouping(NumeratorGrouping::None)
            .with_graph_filter(GenerationFilter::VertexAllow(vec![VertexSelector::Name(
                "V_36".into(),
            )]))
            .with_graph_filter(GenerationFilter::LoopOneParticleIrreducible)
            .threads(1);
        let generated = Process::new([21_i64], [21_i64])
            .generate_diagrams(Arc::new(model.clone()), &options)?;
        let graph = generated
            .diagrams
            .into_iter()
            .next()
            .ok_or_else(|| eyre!("missing two-loop gluon fixture"))?
            .to_gamma_loop_graph(None, true)?;
        let subgraph = graph.full_filter();
        let lmb = graph.lmb_of(&subgraph);
        let input = graph
            .numerator(&subgraph, &graph.empty_subgraph())
            .to_d_dim(GS.dim)
            .get_single_atom()
            .unwrap()
            / graph.denominator(&subgraph, &model, |_| 1);
        // Graph generation, dressing, and equality checking are outside timings.
        for expanded in [false, true] {
            let input = if expanded {
                input.expand()
            } else {
                input.clone()
            };
            let expected = graph.uv_rescaled_sequential(&subgraph, 2, &lmb, &input);
            assert_eq!(graph.uv_rescaled(&subgraph, 2, &lmb, &input), expected);
            let mut sequential = Vec::new();
            let mut optimized = Vec::new();
            for iteration in 0..6 {
                // Alternate order to reduce warm-cache bias.
                for old in if iteration % 2 == 0 {
                    [true, false]
                } else {
                    [false, true]
                } {
                    let started = Instant::now();
                    let output = if old {
                        graph.uv_rescaled_sequential(&subgraph, 2, &lmb, black_box(&input))
                    } else {
                        graph.uv_rescaled(&subgraph, 2, &lmb, black_box(&input))
                    };
                    let elapsed = started.elapsed();
                    let _ = black_box(output);
                    if old {
                        sequential.push(elapsed);
                    } else {
                        optimized.push(elapsed);
                    }
                }
            }
            sequential.sort();
            optimized.sort();
            debug_tags!(#uv, #profile, #rescaling;
                expanded, debug_assertions = cfg!(debug_assertions),
                sequential_median_seconds = sequential[3].as_secs_f64(),
                optimized_median_seconds = optimized[3].as_secs_f64(),
                speedup = sequential[3].as_secs_f64() / optimized[3].as_secs_f64(),
                "Dressed two-loop gluon rescaling microbenchmark"
            );
        }
        Ok(())
    }
