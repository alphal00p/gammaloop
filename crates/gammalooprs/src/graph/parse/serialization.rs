impl Graph {
    pub fn to_dot_graph_with_settings(
        &self,
        settings: &DotExportSettings,
    ) -> eyre::Result<DotGraph> {
        let mut dotgraph = if settings.split_xs_by_initial_states {
            self.to_split_dotgraph_with_autogenerated_fields(settings.include_autogenerated_fields)
        } else {
            self.to_dot_graph_with_autogenerated_fields(settings.include_autogenerated_fields)
        };

        if settings.output_full_numerator {
            let num = self
                .numerator(&self.full_filter(), &self.empty_subgraph())
                .get_single_atom()
                .unwrap()
                * &self.global_prefactor.num
                * &self.global_prefactor.projector
                * &self.overall_factor;
            let cooking = CookSettings::indices().with_mode(CookMode::ReversibleEncoding);
            let num = SymbolicTensor::infer(cooking.try_cook(num.as_view())?)?
                .simplify_algebra(&idenso::tensor::AlgebraSettings {
                    color: settings
                        .do_color_algebra
                        .then(|| ColorSimplifySettings::default().with_cof_dimension_invariants()),
                    gamma: settings
                        .do_gamma_algebra
                        .then(GammaSimplifySettings::default),
                    epsilon: settings.do_gamma_algebra,
                    ..Default::default()
                })?
                .contract(idenso::tensor::ContractSettings {
                    collect_chains: false,
                    collect_traces: false,
                    ..Default::default()
                })?;

            if settings.do_gamma_algebra {
                crate::debug_tags!(#generation, #graph, #inspect, #dump;
                    stage = "graph_serialization_after_simplify_gamma",
                    log.after_gamma = num.expression(),
                    "Graph serialization after gamma simplification"
                );
            }

            let num = cooking.uncook(num.expression().as_view());
            dotgraph.global_data.statements.insert(
                "full_num".into(),
                num.printer(SpensoPrintSettings::typst_options())
                    .to_string(),
            );
        }

        if !settings.split_xs_by_initial_states
            && (!self.finalized_cuts.is_empty()
                || !self.finalized_topology_threshold_candidates.is_empty())
        {
            return self.to_canonical_dot_graph(dotgraph);
        }
        Ok(dotgraph)
    }

    /// Transport finalized physics into the native artifact, without applying
    /// rules, enumerating cuts, or changing its symbolic or momentum frame.
    fn to_canonical_dot_graph(&self, runtime: DotGraph) -> eyre::Result<DotGraph> {
        let endpoint = |hedge: linnet::half_edge::involution::Hedge| DiagramHalfEdge {
            edge: EdgeId(self.underlying[&hedge].0),
            endpoint: if self.underlying.flow(hedge) == Flow::Source {
                DiagramEndpoint::Source
            } else {
                DiagramEndpoint::Target
            },
        };
        let mut builder = FeynmanDiagram::builder(self.model.clone(), self.name.clone())
            .overall_factor(self.overall_factor.clone())
            .numerator_prefactor(self.global_prefactor.num.clone())
            .projector(self.global_prefactor.projector.clone())
            .half_edge_order(
                self.underlying
                    .iter_hedges()
                    .map(|(h, _)| endpoint(h))
                    .collect(),
            )
            .edge_orientations(
                self.underlying
                    .iter_edges()
                    .map(|(_, _, e)| e.orientation)
                    .collect(),
            );
        for (id, _, vertex) in self.underlying.iter_nodes() {
            let added = builder.add_vertex(DiagramVertex {
                name: vertex.name.value.clone(),
                interaction: vertex.vertex_rule,
                numerator: vertex.num.value.clone(),
            });
            eyre::ensure!(
                added.0 == id.0,
                "canonical export requires stable vertex IDs"
            );
        }
        let mut external_index = 0;
        for (pair, id, data) in self.underlying.iter_edges() {
            let particle = data.data.particle().ok_or_else(|| {
                eyre::eyre!("canonical cross-section export requires a model particle on edge {id}")
            })?;
            let mut edge = DiagramEdge::new(particle, data.orientation != Orientation::Undirected);
            edge.numerator = data.data.num.value.clone();
            edge.is_dummy = data.data.is_dummy;
            let (source, target, source_slot, target_slot, state) = match pair {
                HedgePair::Paired { source, sink } => (
                    Some(VertexId(self.underlying.node_id(source).0)),
                    Some(VertexId(self.underlying.node_id(sink).0)),
                    VertexSlot(self.underlying[source].ufo_order.value.into()),
                    VertexSlot(self.underlying[sink].ufo_order.value.into()),
                    self.initial_state_cut
                        .left
                        .includes(&sink)
                        .then_some(ExternalState::Incoming),
                ),
                HedgePair::Unpaired { hedge, flow } => {
                    let node = Some(VertexId(self.underlying.node_id(hedge).0));
                    let slot = VertexSlot(self.underlying[hedge].ufo_order.value.into());
                    if flow == Flow::Source {
                        (
                            node,
                            None,
                            slot,
                            VertexSlot(0),
                            Some(ExternalState::Outgoing),
                        )
                    } else {
                        (
                            None,
                            node,
                            VertexSlot(0),
                            slot,
                            Some(ExternalState::Incoming),
                        )
                    }
                }
                HedgePair::Split { .. } => eyre::bail!("canonical export requires whole edges"),
            };
            if let Some(state) = state {
                edge.external = Some(ExternalLeg {
                    name: data.data.name.value.clone(),
                    index: external_index,
                    state,
                    connection: external_index,
                });
                external_index += 1;
            }
            let added =
                builder.add_edge_with_slots(source, target, edge, source_slot, target_slot)?;
            eyre::ensure!(added.0 == id.0, "canonical export requires stable edge IDs");
        }
        let mut diagram = builder.build()?.with_loop_momentum_edges(
            &self
                .loop_momentum_basis
                .loop_edges
                .iter()
                .map(|e| EdgeId(e.0))
                .collect::<Vec<_>>(),
        )?;
        for (edge, signature) in &self.loop_momentum_basis.edge_signatures {
            let native = &diagram.loop_momentum_basis().edge_signatures[&EdgeId(edge.0)];
            eyre::ensure!(
                signature.internal.iter().copied().eq(native.loops.iter())
                    && signature
                        .external
                        .iter()
                        .copied()
                        .eq(native.external.iter()),
                "canonical export changed routing of edge {edge}"
            );
        }
        let partition = |side: &linnet::half_edge::subgraph::SuBitGraph| {
            side.included_iter().map(endpoint).collect::<Vec<_>>()
        };
        diagram = diagram
            .with_cut_partitions(
                self.finalized_cuts
                    .iter()
                    .map(|cut| (partition(&cut.left), partition(&cut.right)))
                    .collect(),
            )?
            .with_topology_threshold_partitions(
                self.finalized_topology_threshold_candidates
                    .iter()
                    .map(|cut| (partition(&cut.left), partition(&cut.right)))
                    .collect(),
            )?;
        let mut canonical: DotGraph =
            DotGraph::from_string(&diagram.to_dot()?).map_err(|error| eyre::eyre!("{error}"))?;
        // Parse the rendered metadata once so quoted runtime strings enter the
        // native serializer as values, preserving real newlines in directives.
        let runtime: DotGraph =
            DotGraph::from_string(&runtime.debug_dot()).map_err(|error| eyre::eyre!("{error}"))?;
        for name in [
            "group_id",
            "is_group_master",
            "threshold_counterterms",
            "params",
            "full_num",
        ] {
            if let Some(value) = runtime.global_data.statements.get(name) {
                canonical
                    .global_data
                    .statements
                    .insert(name.into(), value.clone());
            }
        }
        for (_, id, data) in runtime.iter_edges() {
            for name in [
                "name",
                "dod",
                "mass",
                "momtrop_edge_power",
                "vakint_edge_power",
            ] {
                if let Some(value) = data.data.statements.get(name) {
                    canonical.graph[EdgeIndex(id.0)]
                        .statements
                        .insert(name.into(), value.clone());
                }
            }
        }
        for (id, _, vertex) in runtime.iter_nodes() {
            if let Some(dod) = vertex.statements.get("dod") {
                canonical.graph[id]
                    .statements
                    .insert("dod".into(), dod.clone());
            }
        }
        Ok(canonical)
    }

    pub fn to_split_dotgraph(&self) -> DotGraph {
        self.to_split_dotgraph_with_autogenerated_fields(false)
    }

    fn to_split_dotgraph_with_autogenerated_fields(
        &self,
        include_autogenerated_fields: bool,
    ) -> DotGraph {
        let global_data = self.global_data(include_autogenerated_fields);
        let initial_state_edges = self.get_edges_in_initial_state_cut();

        let mut graph: HedgeGraph<DotEdgeData, DotVertexData, DotHedgeData> =
            if self.initial_state_cut.is_empty() {
                self.underlying.map_data_ref(
                    |_, _, v| v.to_dot_data(include_autogenerated_fields),
                    |_, _, p, e| {
                        if let HedgePair::Unpaired { flow, .. } = p {
                            e.map(|e| {
                                let mut dot = e.to_dot_data(include_autogenerated_fields);
                                match flow {
                                    Flow::Source => {
                                        dot.add_statement("pos", "x:@-left!".to_string());
                                    }
                                    Flow::Sink => {
                                        dot.add_statement("pos", "x:@+right!".to_string());
                                    }
                                }
                                dot
                            })
                        } else {
                            e.map(|e| e.to_dot_data(include_autogenerated_fields))
                        }
                    },
                    |_, d| d.into(),
                )
            } else {
                self.initial_state_cut
                    .clone()
                    .to_owned_graph_ref(&self.underlying)
                    .map(
                        |_, _, v| v.to_dot_data(include_autogenerated_fields),
                        |_, _, p, _, e| {
                            e.map(|e| {
                                let mut dot =
                                    e.edge_data().to_dot_data(include_autogenerated_fields);

                                if initial_state_edges.contains(&e.index) {
                                    match e.orientation() {
                                        Orientation::Default => {
                                            dot.add_statement("is_cut", self.inv(p.any_hedge()));
                                            dot.add_statement(
                                                "pos",
                                                format!("x:@-left!,y:@edge{}!", e.index),
                                            );
                                        }
                                        Orientation::Reversed => {
                                            dot.add_statement("is_cut", p.any_hedge());
                                            dot.add_statement(
                                                "pos",
                                                format!("x:@+right!,y:@edge{}!", e.index),
                                            );
                                        }
                                        Orientation::Undirected => {}
                                    }
                                    dot.add_statement("initial_state_connection", true);
                                }
                                dot
                            })
                        },
                        |_, d| d.into(),
                    )
            };

        // self.normal_emr_replacement(subgraph, lmb, rep_args, filter_pair)
        for (_, i, _) in self.iter_edges() {
            let loop_expr = self
                .loop_momentum_basis
                .loop_atom(i, GS.loop_mom, &[W_.a___], false);
            let external_expr =
                self.loop_momentum_basis
                    .ext_atom(i, GS.external_mom, &[W_.a___], false);

            graph[i].add_statement("lmb_rep", (loop_expr + external_expr).to_quoted());
        }

        for (l, i) in self.loop_momentum_basis.loop_edges.iter_enumerated() {
            graph[i].0.add_statement("lmb_id", l);
        }

        DotGraph { global_data, graph }
    }

    fn to_dot_graph_with_autogenerated_fields(
        &self,
        include_autogenerated_fields: bool,
    ) -> DotGraph {
        let global_data = self.global_data(include_autogenerated_fields);

        let mut graph: HedgeGraph<DotEdgeData, DotVertexData, DotHedgeData> =
            self.underlying.map_data_ref(
                |_, _, v| v.to_dot_data(include_autogenerated_fields),
                |_, _, _, e| e.map(|e| e.to_dot_data(include_autogenerated_fields)),
                |_, d| d.into(),
            );

        for (_, i, _) in self.iter_edges() {
            let loop_expr = self
                .loop_momentum_basis
                .loop_atom(i, GS.loop_mom, &[W_.a___], false);
            let external_expr =
                self.loop_momentum_basis
                    .ext_atom(i, GS.external_mom, &[W_.a___], false);

            graph[i].add_statement("lmb_rep", (loop_expr + external_expr).to_quoted());
        }

        for i in self.initial_state_cut.left.included_iter() {
            let eid = graph[&i];
            graph[eid].add_statement("is_cut", i);
            graph[eid].add_statement("initial_state_connection", true);
        }

        for (l, i) in self.loop_momentum_basis.loop_edges.iter_enumerated() {
            graph[i].0.add_statement("lmb_id", l);
        }

        DotGraph { global_data, graph }
    }
}

impl From<&Graph> for DotGraph {
    fn from(value: &Graph) -> Self {
        value.to_dot_graph_with_autogenerated_fields(false)
    }
}

impl From<&ParseGraph> for DotGraph {
    fn from(value: &ParseGraph) -> Self {
        let global_data = value.global_data();
        let graph: HedgeGraph<DotEdgeData, DotVertexData, DotHedgeData> = value.graph.map_data_ref(
            |_, _, v| v.into(),
            |_, _, _, e| e.map(|e| e.into()),
            |_, d| d.into(),
        );

        DotGraph { global_data, graph }
    }
}

impl ParseGraph {
    #[allow(dead_code)]
    fn to_simple_dot(&self) -> DotGraph {
        let global_data = self.global_data();
        let graph: HedgeGraph<DotEdgeData, DotVertexData, DotHedgeData> = self.graph.map_data_ref(
            |_, _, v| v.into(),
            |_, _, _, e| e.map(|e| e.into()),
            |_, d| d.into(),
        );

        DotGraph { global_data, graph }
    }
}

