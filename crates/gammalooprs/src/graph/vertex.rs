#[derive(Debug, Clone, bincode_trait_derive::Encode, bincode_trait_derive::Decode)]
#[trait_decode(trait = GammaLoopContext)]
pub struct Vertex {
    // #[bincode(with_serde)]
    pub name: Autogen<String>,
    pub vertex_rule: Option<VertexRuleId>,
    pub num: Autogen<SymbolicTensor<IndexedStructure>>,
    // pub num_spin: ParamTensor<OrderedStructure<Euclidean, Aind>>,
    // pub num_color: ParamTensor<OrderedStructure<Euclidean, Aind>>,
    pub dod: Autogen<i32>,
}

impl Vertex {
    pub(crate) fn get_num(&self) -> SymbolicTensor<IndexedStructure> {
        self.num.value.clone()
    }

    /// Vertex rules are written by model name rather than by their position
    /// in the model, so that import validates the binding.
    pub(crate) fn to_dot_data(
        &self,
        model: &Model,
        include_autogenerated_fields: bool,
    ) -> DotVertexData {
        let mut v = DotVertexData::empty();
        if include_autogenerated_fields || !self.name.autogenerated {
            v.name = Some(self.name.value.clone());
        }
        if let Some(vertex_rule) = self.vertex_rule {
            v.add_statement("int_id", vertex_rule.resolve(model).name.as_str());
        }
        if include_autogenerated_fields || !self.dod.autogenerated {
            v.add_statement("dod", self.dod.value);
        }
        if include_autogenerated_fields || !self.num.autogenerated {
            let (expression, interface) = NumeratorInterface::export(&self.num.value);
            v.add_statement("num", expression.to_quoted());
            if let Some(interface) = interface {
                v.add_statement("num_interface", interface.to_json());
            }
        }
        if include_autogenerated_fields {
            if self.name.autogenerated {
                v.add_statement("name_autogen", true);
            }
            if self.dod.autogenerated {
                v.add_statement("dod_autogen", true);
            }
            if self.num.autogenerated {
                v.add_statement("num_autogen", true);
            }
        }
        v
    }
}

impl Vertex {}

#[derive(Debug, Clone)]
pub struct ParseVertex {
    pub name: Option<String>,

    // pub strict: bool,
    pub vertex_rule: Option<VertexRuleId>,
    pub num: Option<Atom>,
    pub(crate) num_interface: Option<NumeratorInterface>,
    pub dod: Option<i32>,
}

impl ParseVertex {
    pub(crate) fn to_dot_data(&self, model: &Model) -> DotVertexData {
        let mut v = DotVertexData::empty();
        if let Some(name) = &self.name {
            v.name = Some(name.clone());
        }
        if let Some(vertex_rule) = self.vertex_rule {
            v.add_statement("int_id", vertex_rule.resolve(model).name.as_str());
        }
        if let Some(dod) = self.dod {
            v.add_statement("dod", dod);
        }
        if let Some(num) = &self.num {
            v.add_statement("num", num.to_quoted());
        }
        if let Some(interface) = &self.num_interface {
            v.add_statement("num_interface", interface.to_json());
        }
        v
    }

    pub fn with_num(mut self, num: Atom) -> Self {
        self.num = Some(num);
        self.num_interface = None;
        self
    }

    pub fn with_label(mut self, label: String) -> Self {
        self.name = Some(label);
        self
    }
}

impl From<VertexRuleId> for ParseVertex {
    fn from(vertex_rule: VertexRuleId) -> Self {
        ParseVertex {
            name: None,

            // strict: false,
            vertex_rule: Some(vertex_rule),
            dod: None,
            num: None,
            num_interface: None,
        }
    }
}

pub trait ParticleEdge {
    fn particle(&self) -> Option<ParticleId>;
    fn is_dummy(&self) -> bool;
}

impl ParseVertex {
    pub(crate) fn parse<'a>(
        model: &'a Model,
        parse_data: &'a ParseData,
    ) -> impl FnMut(
        &'a HedgeGraph<ParseEdge, &'a DotVertexData, ParseHedgeData>,
        BitVecNeighborIter<'a>,
        &'a &'a DotVertexData,
    ) -> Result<Self> {
        move |g, n, v| {
            let name = v.name().map(|id| id.to_string());
            let num_interface = v
                .get::<_, String>("num_interface")
                .transpose()?
                .map(|value| NumeratorInterface::parse_with_model(&value, model))
                .transpose()?;

            let dod = v
                .get::<_, String>("dod")
                .transpose()
                .with_context(|| "Error parsing vertex dod".to_string())?
                .map(|a| a.strip_parse())
                .transpose()?;

            let vertex_rule = consistent_dot_identity(
                "vertex rule",
                [
                    v.get::<_, usize>("vertex_rule_id").map(|id| -> Result<_> {
                        Ok(("vertex_rule_id", model.vertex_rule_id_at(id?)?))
                    }),
                    v.get::<_, String>("int_id").map(|rule| -> Result<_> {
                        let rule: String = rule?.strip_parse()?;
                        Ok(("int_id", model.vertex_rule_id(&rule)?))
                    }),
                ],
                |rule| format!("'{}'", rule.resolve(model).name),
            )
            .with_context(|| {
                format!(
                    "Error parsing the vertex rule of vertex {} in graph {}",
                    name.as_deref().unwrap_or("<unnamed>"),
                    parse_data.name
                )
            })?;
            let num = v
                .get::<_, String>("num")
                .map(|num| -> Result<Atom> {
                    let num = num?;
                    string_utils::parse_expression(&num, model).with_context(|| {
                        format!(
                            "Error parsing vertex num {num} of graph {}",
                            parse_data.name
                        )
                    })
                })
                .transpose()?;

            if num.is_some() || vertex_rule.is_some() {
                Ok(ParseVertex {
                    dod,
                    name,

                    vertex_rule,
                    num,
                    num_interface,
                })
            } else {
                let node_id = n
                    .clone()
                    .next()
                    .map(|h| g.node_id(h))
                    .unwrap_or(NodeIndex(0));
                let mut particles = extract_oriented_particles_from_vertex_hedges(g, n, model);
                particles.sort_unstable();

                let rules = model.vertex_rules_for_particles(&particles);
                if !rules.is_empty() {
                    if rules.len() == 1 {
                        Ok(ParseVertex {
                            dod,
                            name,

                            vertex_rule: Some(rules[0]),
                            num: None,
                            num_interface,
                        })
                    } else {
                        Err(eyre!("Multiple vertex rules for {:?}", particles))
                    }
                } else {
                    let particles = particles
                        .iter()
                        .map(|particle| particle.resolve(model).name.as_str())
                        .collect_vec();
                    Err(eyre!(
                        "Failed to find vertex rule for particles: {:?} for node {node_id} in graph {}",
                        particles,
                        parse_data.name,
                    ))
                }
            }
        }
    }
}
