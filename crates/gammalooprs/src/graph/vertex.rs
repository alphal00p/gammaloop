use linnet::parser::DotVertexData;

use symbolica::atom::Atom;

use crate::{
    GammaLoopContext,
    model::{Model, VertexRuleId},
};

use super::{Autogen, parse::ToQuoted};

#[derive(Debug, Clone, bincode_trait_derive::Encode, bincode_trait_derive::Decode)]
#[trait_decode(trait = GammaLoopContext)]
pub struct Vertex {
    // #[bincode(with_serde)]
    pub name: Autogen<String>,
    pub vertex_rule: Option<VertexRuleId>,
    pub num: Autogen<Atom>,
    // pub num_spin: ParamTensor<OrderedStructure<Euclidean, Aind>>,
    // pub num_color: ParamTensor<OrderedStructure<Euclidean, Aind>>,
    pub dod: Autogen<i32>,
}

impl Vertex {
    pub(crate) fn get_num(&self) -> Atom {
        self.num.value.clone()
    }

    /// Compact DOT attributes, naming the interaction so that FeynKit can import them again.
    pub(crate) fn to_dot_data(
        &self,
        model: &Model,
        include_autogenerated_fields: bool,
    ) -> DotVertexData {
        let mut v = DotVertexData::empty();
        if include_autogenerated_fields || !self.name.autogenerated {
            v.name = Some(self.name.value.clone());
        }
        if let Some(vertex_rule) = self.vertex_rule {
            v.add_statement("int_id", &model.vertex_rules()[vertex_rule.index()].name);
        }
        if include_autogenerated_fields || !self.dod.autogenerated {
            v.add_statement("dod", self.dod.value);
        }
        if include_autogenerated_fields || !self.num.autogenerated {
            v.add_statement("num", self.num.value.to_quoted());
        }
        if include_autogenerated_fields {
            if self.name.autogenerated {
                v.add_statement("name_autogen", true);
            }
            if self.dod.autogenerated {
                v.add_statement("dod_autogen", true);
            }
            if self.num.autogenerated {
                v.add_statement("num_autogen", true);
            }
        }
        v
    }
}

#[derive(Debug, Clone)]
pub struct ParseVertex {
    pub name: Option<String>,
    pub vertex_rule: Option<VertexRuleId>,
    pub num: Option<Atom>,
    pub dod: Option<i32>,
}
