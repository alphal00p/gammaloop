/// The user's external head `p(i)` and the sign `σ` of `external = σ·p(i)`.
pub(crate) fn external_head(external: &Atom) -> Result<(Atom, i64), VakintError> {
    let invalid = || {
        VakintError::InvalidIntegralFormat(format!(
            "p-integral: the external momentum must be ±p(i), not {external}"
        ))
    };
    match external.as_view() {
        AtomView::Fun(head) if head.get_symbol() == S.p && head.get_nargs() == 1 => {
            Ok((external.clone(), 1))
        }
        AtomView::Mul(_) => {
            let head = -external;
            match head.as_view() {
                AtomView::Fun(f) if f.get_symbol() == S.p && f.get_nargs() == 1 => Ok((head, -1)),
                _ => Err(invalid()),
            }
        }
        _ => Err(invalid()),
    }
}

/// The p-integral part of a matching witness.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct PropagatorWitness {
    /// Index into [`P_FAMILIES`].
    pub family: usize,
    /// The user's external momentum head `p(i)`.
    pub external: Atom,
    /// The canonical `p(1)` is `sign * external`.
    pub sign: i8,
    /// The matched power of every canonical line, in canonical order
    /// (0 for pinched lines, all >= 0): the `powers` of the backend contract.
    pub powers: Vec<i64>,
}

impl PropagatorWitness {
    pub(crate) fn family(&self) -> &'static PFamilyData {
        &P_FAMILIES[self.family]
    }

    /// The canonical `p(1)` written in the user head, `sign·p(i)`: the
    /// `external` argument of the backend contract.
    pub(crate) fn canonical_external(&self) -> Atom {
        Atom::num(self.sign as i64) * &self.external
    }
}

/// The input of a p-integral backend (`reduce_p`, section 5), read off a
/// matched term: independent of [`ReplacementRules`] beyond this accessor.
#[allow(dead_code)]
#[derive(Clone, Debug)]
pub(crate) struct PropagatorRequest<'a> {
    pub family: &'static PFamilyData,
    /// Canonical line order; 0 = pinched, all >= 0.
    pub powers: &'a [i64],
    /// A scalar polynomial in the canonical `k(j)` and the user head.
    pub canonical_numerator: AtomView<'a>,
    /// The canonical `p(1)` written in the user head, `σ·p(i)`.
    pub external: Atom,
}

impl ReplacementRules {
    /// The backend input of a matched p-integral term whose numerator has
    /// been canonicalized; `None` for a vacuum match.
    pub(crate) fn propagator_request<'a>(
        &'a self,
        canonical_numerator: AtomView<'a>,
    ) -> Option<PropagatorRequest<'a>> {
        self.propagator.as_ref().map(|witness| PropagatorRequest {
            family: witness.family(),
            powers: &witness.powers,
            canonical_numerator,
            external: witness.canonical_external(),
        })
    }
}

