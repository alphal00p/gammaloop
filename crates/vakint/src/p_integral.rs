    fn lines(family: &PFamilyData) -> Vec<(i64, i64, Atom)> {
        // Install vakint's tensor-tagged momentum symbols before parsing.
        crate::Vakint::initialize_vakint_symbols();
        let expression = vk_parse!(family.lines).unwrap();
        let count = 3 * family.loops - 1;
        (1..=count)
            .map(|id| {
                let prop = get_prop_with_id(expression.as_view(), id)
                    .unwrap_or_else(|| panic!("{}: missing line {id}", family.name));
                let node =
                    |name: &str| get_integer_from_atom(prop[&vk_symbol!(name)].as_view()).unwrap();
                assert!(
                    prop[&vk_symbol!("mUVsq_")].is_zero(),
                    "{}: massive line",
                    family.name
                );
                (node("nl_"), node("nr_"), prop[&vk_symbol!("q_")].clone())
            })
            .collect()
    }

    /// Integer coefficients of `k(1..=L)` and `p(1)` in a linear momentum.
    fn coefficients(momentum: AtomView, loops: usize) -> Vec<i64> {
        let heads = (1..=loops)
            .map(|i| function!(S.k, Atom::num(i as i64)))
            .chain([function!(S.p, Atom::num(1))])
            .collect::<Vec<_>>();
        heads
            .iter()
            .map(|head| {
                let mut value = momentum.to_owned();
                for other in &heads {
                    let image = if other == head {
                        Atom::num(1)
                    } else {
                        Atom::Zero
                    };
                    value = value.replace(other.to_pattern()).with(image.to_pattern());
                }
                get_integer_from_atom(value.expand().as_view()).unwrap()
            })
            .collect()
    }

    /// `(Σ a_i k_i + b q)²` on the coordinates `k_i·k_j (i <= j)`, `k_i·q`.
    fn quadric(coefficients: &[i64]) -> Vec<i128> {
        let (loops, q) = (coefficients.len() - 1, coefficients[coefficients.len() - 1]);
        let mut row = Vec::new();
        for i in 0..loops {
            for j in i..loops {
                let factor = if i == j { 1 } else { 2 };
                row.push(factor * (coefficients[i] * coefficients[j]) as i128);
            }
        }
        row.extend((0..loops).map(|i| 2 * (coefficients[i] * q) as i128));
        row
    }

    fn rank(mut rows: Vec<Vec<i128>>) -> usize {
        let columns = rows.first().map_or(0, Vec::len);
        let mut rank = 0;
        for column in 0..columns {
            let Some(pivot) = (rank..rows.len()).find(|&row| rows[row][column] != 0) else {
                continue;
            };
            rows.swap(rank, pivot);
            let pivot_row = rows[rank].clone();
            for (index, row) in rows.iter_mut().enumerate() {
                if index != rank && row[column] != 0 {
                    let (a, b) = (pivot_row[column], row[column]);
                    for (entry, pivot_entry) in row.iter_mut().zip(&pivot_row) {
                        *entry = a * *entry - b * pivot_entry;
                    }
                }
            }
            rank += 1;
        }
        rank
    }

