    #[test]
    fn canonical_routings_carry_q_from_vertex_one_to_vertex_two() {
        for family in &P_FAMILIES {
            let mut balance = BTreeMap::<i64, Atom>::new();
            for (id, (from, to, momentum)) in lines(family).into_iter().enumerate() {
                if id < family.loops {
                    assert_eq!(
                        momentum,
                        function!(S.k, Atom::num(id as i64 + 1)),
                        "{}: line {} must carry k({})",
                        family.name,
                        id + 1,
                        id + 1
                    );
                }
                *balance.entry(from).or_default() += &momentum;
                *balance.entry(to).or_default() -= &momentum;
            }
            let q = function!(S.p, Atom::num(1));
            for (vertex, flow) in balance {
                let expected = match vertex {
                    1 => q.clone(),
                    2 => -q.clone(),
                    _ => Atom::Zero,
                };
                assert!(
                    (flow - expected).expand().is_zero(),
                    "{}: vertex {vertex}",
                    family.name
                );
            }
        }
    }

    #[test]
    fn lines_and_isps_span_every_scalar_product() {
        for family in &P_FAMILIES {
            let loops = family.loops;
            let mut rows = lines(family)
                .iter()
                .map(|(_, _, momentum)| quadric(&coefficients(momentum.as_view(), loops)))
                .collect::<Vec<_>>();
            rows.extend(
                family
                    .isps
                    .iter()
                    .map(|isp| quadric(&coefficients(vk_parse!(*isp).unwrap().as_view(), loops))),
            );
            let coordinates = loops * (loops + 1) / 2 + loops;
            assert_eq!(rows.len(), coordinates, "{}", family.name);
            assert_eq!(rank(rows), coordinates, "{}", family.name);
        }
    }
