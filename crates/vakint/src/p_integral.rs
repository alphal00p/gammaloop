/// What a `topo(...)` integral denotes, inferred from its content alone.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum IntegralKind {
    /// No propagator momentum contains an external momentum `p(i)`.
    Vacuum,
    /// Massless and single-scale: one external momentum `p(i)` enters the
    /// graph at one vertex and leaves it at another.
    Propagator,
}

/// One canonical p-integral family: the cut of one edge orbit of an
