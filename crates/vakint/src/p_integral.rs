/// What a `topo(...)` integral denotes, inferred from its content alone.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum IntegralKind {
    /// No propagator momentum contains an external momentum `p(i)`.
    Vacuum,
    /// Massless and single-scale: one external momentum `p(i)` enters the
    /// graph at one vertex and leaves it at another.
    Propagator,
}

/// One canonical p-integral family: the cut of one edge orbit of an
/// (L+1)-loop cubic vacuum graph without one- or two-edge cuts.
///
/// `lines` is the canonical long form. The external momentum `p(1)` enters at
/// vertex 1 and leaves at vertex 2, line `i <= L` carries `k(i)` alone, and
/// the lines carrying `p(1)` form one path from vertex 1 to vertex 2. The
/// squares of `isps` complete the `L(L+1)/2 + L` scalar products; the family
/// denominators are the lines followed by the ISPs, in this order.
#[allow(dead_code)]
pub(crate) struct PFamilyData {
    /// Head of the short form `topo(NAME(±p(i), a_1, ..., a_N))`.
    pub name: &'static str,
    pub loops: usize,
    /// Forcer's internal top-level topology, where it has one.
    pub forcer_topology: Option<&'static str>,
    pub vacuum_parent: &'static str,
    pub lines: &'static str,
    pub isps: &'static [&'static str],
}

