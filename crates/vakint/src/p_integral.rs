///
/// The vakint value is
/// `[F·i·π^(d/2)·ε·G(1,1)]^L · (Q²)^scale_power · (Q²/μ²)^(-Lε) · (μ²)^(-Lε) · reduced`
/// with `Q² = -dot(p(i),p(i))`, the configured per-loop normalization `F`,
/// `G(1,1) = Γ(ε)Γ(1-ε)²/Γ(2-2ε)` and `reduced` exact in `ε`, written in the
/// common p-master basis (`PMaster(name)` and products of `PG(x1,x2)`).
#[allow(dead_code)]
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct ReducedPropagatorValue {
    pub scale_power: i64,
    pub reduced: Atom,
}

/// Options of the Forcer backend (`EvaluationMethod::Forcer`).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ForcerOptions {
    /// How masters are represented, exactly as for RustRed: identical modes
    /// make both backends' results directly comparable.
    pub master_mode: RustRedMasterMode,
}

impl std::fmt::Display for ForcerOptions {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "master_mode={}", self.master_mode)
    }
}

/// A [`P_FAMILIES`] entry with its canonical lines parsed.
#[derive(Debug)]
pub(crate) struct PFamily {
    pub index: usize,
    pub data: &'static PFamilyData,
    /// The canonical lines in id order (`power` is a placeholder 1).
    pub lines: Vec<PLine>,
}

/// The parsed registry, in [`P_FAMILIES`] order.
pub(crate) fn families() -> &'static [PFamily] {
    static FAMILIES: OnceLock<Vec<PFamily>> = OnceLock::new();
    FAMILIES.get_or_init(|| {
        crate::Vakint::initialize_vakint_symbols();
        P_FAMILIES
            .iter()
            .enumerate()
            .map(|(index, data)| {
                let expression = vk_parse!(data.lines).expect("registry long forms parse");
                let lines = (1..)
                    .map_while(|id| {
                        get_prop_with_id(expression.as_view(), id).map(|prop| (id, prop))
                    })
                    .map(|(id, prop)| {
                        let node = |name: &str| {
                            get_integer_from_atom(prop[&vk_symbol!(name)].as_view())
                                .expect("registry vertices are integers")
                        };
                        PLine {
                            id: id as i64,
                            ends: (node("nl_"), node("nr_")),
                            momentum: prop[&vk_symbol!("q_")].clone(),
                            power: 1,
                        }
                    })
                    .collect();
                PFamily { index, data, lines }
            })
            .collect()
    })
}

impl PFamily {
    /// `NAME(p(1), pow(1), ..., pow(N))`.
    fn short_expression(&self) -> Atom {
        let mut short =
            symbolica::atom::FunctionBuilder::new(vk_symbol!(self.data.name)).add_arg(S.p.call(1));
        for line in &self.lines {
            short = short.add_arg(S.pow.call(line.id));
        }
        short.finish()
    }
}

/// Section 1: an integral is a p-integral iff some prop momentum contains an
/// external head `p(_)` or its short-form head is a p-family name. The Atom
/// stays self-describing: vacuum matching rejects `p` in prop momenta.
pub fn infer_kind(integral: AtomView) -> Result<IntegralKind, VakintError> {
    Ok(if input::mentions_external_momentum(integral) {
        IntegralKind::Propagator
    } else {
        IntegralKind::Vacuum
    })
}

impl Integral {
    /// The registry entry of one p-family: its long form with `pow(n)` slots,
    /// mass `0` and `p(1)` (section 2). It is only ever reached through the
    /// p-integral catalogue, never through the vacuum pattern matchers.
    pub(crate) fn new_propagator(family: &PFamilyData) -> Result<Integral, VakintError> {
        let parsed = families()
            .iter()
            .find(|parsed| parsed.data.name == family.name)
            .ok_or_else(|| invalid(format!("{} is not a registered family", family.name)))?;
        let canonical = vk_parse!(family.lines).map_err(VakintError::SymbolicaError)?;
        let n_props = parsed.lines.len();
        let unmatchable = FullPattern {
            pattern: vk_parse!("topo(props_)").unwrap().to_pattern(),
            conditions: Default::default(),
            match_settings: Default::default(),
        };
        Ok(Integral {
            name: family.name.into(),
            n_loops: family.loops,
            n_props,
            generic_pattern: unmatchable.clone(),
            graph: Graph::new_from_atom(canonical.as_view(), n_props)?,
            canonical_expression: Some(canonical),
            parent_routing: None,
            short_expression: Some(parsed.short_expression()),
            short_expression_pattern: None,
            alphaloop_expression: None,
            applicable_evaluation_methods: EvaluationOrder(vec![
                EvaluationMethod::RustRed(Default::default()),
                EvaluationMethod::Forcer(Default::default()),
            ]),
            node_pairs: Default::default(),
            unoriented_generic_pattern: unmatchable,
        })
    }
}

/// `k(n) -> k(n,idx___)` and `p(n) -> p(n,idx___)` in a momentum image.
fn with_index_tails(momentum: AtomView) -> Atom {
    crate::with_k_index_tail(momentum)
        .replace(vk_parse!("p(n_)").unwrap().to_pattern())
        .when(symbolica::id::Condition::from((
            vk_symbol!("n_"),
            crate::number_condition(),
        )))
        .allow_new_wildcards_on_rhs(true)
        .with(vk_parse!("p(n_,idx___)").unwrap().to_pattern())
}

/// The replacement rules of a matched p-integral (section 2, "Matching").
pub(crate) fn replacement_rules(
    topology: &Topology,
    matched: PMatch,
    external: &Atom,
) -> Result<ReplacementRules, VakintError> {
    let mut rules = ReplacementRules {
        canonical_topology: topology.clone(),
        ..Default::default()
    };
    for (slot, power) in matched.powers.iter().enumerate() {
        rules
            .canonical_expression_substitutions
            .insert(S.pow.call(slot + 1), Atom::num(*power));
    }
    rules
        .canonical_expression_substitutions
        .insert(S.p.call(1), Atom::num(matched.sign as i64) * external);
    for (canonical, input) in &matched.edges {
        rules
            .edge_ids_canonical_to_input_map
            .insert(*canonical as usize, *input as usize);
    }
    for (head, image) in &matched.images {
        rules.numerator_substitutions.insert(
            crate::with_index_tail(head.as_view())?,
            with_index_tails(image.as_view()),
        );
    }
    rules.propagator = Some(PropagatorWitness {
        family: matched.family,
        external: external.clone(),
        sign: matched.sign,
        powers: matched.powers,
    });
    Ok(rules)
}

/// A p-integral numerator as a polynomial in scalar products of the loop
/// momenta and `external` (section 1, item 7). Loop-momentum-free factors may
/// contain other vectors; an open loop index or a loop momentum contracted
/// with another external vector is a tensor p-integral and is rejected.
pub(crate) fn scalar_numerator(numerator: AtomView, external: &Atom) -> Result<Atom, VakintError> {
    let scalar = crate::Vakint::convert_to_dot_notation(numerator);
    let mut tensor = None;
    scalar.visitor(&mut |view| {
        if tensor.is_some() {
            return false;
        }
        let AtomView::Fun(function) = view else {
            return true;
        };
        if function.get_symbol() == S.dot {
            if view.contains_symbol(S.k) {
                let mut foreign = None;
                view.visitor(&mut |part| {
                    if let AtomView::Fun(vector) = part
                        && vector.get_symbol() == S.p
                        && part != external.as_view()
                    {
                        foreign = Some(part.to_owned());
                    }
                    foreign.is_none()
                });
                if let Some(foreign) = foreign {
                    tensor = Some(format!(
                        "a loop momentum is contracted with {foreign} in {view}"
                    ));
                }
            }
            return false;
        }
        if function.get_symbol() == S.k {
            tensor = Some(if function.get_nargs() == 1 {
                format!("loop momentum {view} outside a scalar product")
            } else {
                format!("open loop index in {view}")
            });
            return false;
        }
        true
    });
    match tensor {
        Some(detail) => Err(VakintError::InvalidNumerator(format!(
            "p-integral: tensor p-integrals are not supported yet: {detail}"
        ))),
        None => Ok(scalar),
    }
}

impl VakintTerm {
    /// Normalize a p-integral term exactly (section 1, items 5 and 6): the
    /// integral becomes its normalized long form and the numerator absorbs
    /// tree factors and negative powers. Returns `false` for a scaleless
    /// term (including a vacuum integral whose every mass is literally 0),
    /// whose numerator is then set to zero. Other vacuum terms are unchanged.
    pub(crate) fn normalize_propagator(&mut self) -> Result<bool, VakintError> {
        if infer_kind(self.integral.as_view())? != IntegralKind::Propagator {
            // The same scaleless rule makes a massless vacuum integral zero.
            if input::is_massless_vacuum(self.integral.as_view()) {
                self.numerator = Atom::Zero;
                return Ok(false);
            }
            return Ok(true);
        }
        match PGraph::parse(self.integral.as_view())?.normalize()? {
            Normalized::Zero => {
                self.numerator = Atom::Zero;
                Ok(false)
            }
            Normalized::Graph { graph, factor } => {
                self.integral = graph.to_atom();
                if factor != Atom::one() {
                    self.numerator = &self.numerator * factor;
                }
                Ok(true)
            }
        }
    }

    /// The external head of a p-integral term, `None` for a vacuum term.
    pub(crate) fn propagator_external(&self) -> Result<Option<Atom>, VakintError> {
        if infer_kind(self.integral.as_view())? != IntegralKind::Propagator {
            return Ok(None);
        }
        Ok(Some(PGraph::parse(self.integral.as_view())?.external))
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use symbolica::atom::{AtomCore, AtomView};
    use symbolica::function;

    use super::*;
    use crate::symbols::S;
    use crate::utils::vakint_macros::{vk_parse, vk_symbol};
    use crate::{get_integer_from_atom, get_prop_with_id};

    fn lines(family: &PFamilyData) -> Vec<(i64, i64, Atom)> {
        // Install vakint's tensor-tagged momentum symbols before parsing.
        crate::Vakint::initialize_vakint_symbols();
        let expression = vk_parse!(family.lines).unwrap();
        let count = 3 * family.loops - 1;
        (1..=count)
            .map(|id| {
                let prop = get_prop_with_id(expression.as_view(), id)
                    .unwrap_or_else(|| panic!("{}: missing line {id}", family.name));
                let node =
                    |name: &str| get_integer_from_atom(prop[&vk_symbol!(name)].as_view()).unwrap();
                assert!(
                    prop[&vk_symbol!("mUVsq_")].is_zero(),
                    "{}: massive line",
                    family.name
                );
                (node("nl_"), node("nr_"), prop[&vk_symbol!("q_")].clone())
            })
            .collect()
    }

    /// Integer coefficients of `k(1..=L)` and `p(1)` in a linear momentum.
    fn coefficients(momentum: AtomView, loops: usize) -> Vec<i64> {
        let heads = (1..=loops)
            .map(|i| function!(S.k, Atom::num(i as i64)))
            .chain([function!(S.p, Atom::num(1))])
            .collect::<Vec<_>>();
        heads
            .iter()
            .map(|head| {
                let mut value = momentum.to_owned();
                for other in &heads {
                    let image = if other == head {
                        Atom::num(1)
                    } else {
                        Atom::Zero
                    };
                    value = value.replace(other.to_pattern()).with(image.to_pattern());
                }
                get_integer_from_atom(value.expand().as_view()).unwrap()
            })
            .collect()
    }

    /// `(Σ a_i k_i + b q)²` on the coordinates `k_i·k_j (i <= j)`, `k_i·q`.
    fn quadric(coefficients: &[i64]) -> Vec<i128> {
        let (loops, q) = (coefficients.len() - 1, coefficients[coefficients.len() - 1]);
        let mut row = Vec::new();
        for i in 0..loops {
            for j in i..loops {
                let factor = if i == j { 1 } else { 2 };
                row.push(factor * (coefficients[i] * coefficients[j]) as i128);
            }
        }
        row.extend((0..loops).map(|i| 2 * (coefficients[i] * q) as i128));
        row
    }

    fn rank(mut rows: Vec<Vec<i128>>) -> usize {
        let columns = rows.first().map_or(0, Vec::len);
        let mut rank = 0;
        for column in 0..columns {
            let Some(pivot) = (rank..rows.len()).find(|&row| rows[row][column] != 0) else {
                continue;
            };
            rows.swap(rank, pivot);
            let pivot_row = rows[rank].clone();
            for (index, row) in rows.iter_mut().enumerate() {
                if index != rank && row[column] != 0 {
                    let (a, b) = (pivot_row[column], row[column]);
                    for (entry, pivot_entry) in row.iter_mut().zip(&pivot_row) {
                        *entry = a * *entry - b * pivot_entry;
                    }
                }
            }
            rank += 1;
        }
        rank
    }

    #[test]
    fn registry_has_one_one_three_eleven_families() {
        let per_loop = P_FAMILIES
            .iter()
            .fold(BTreeMap::new(), |mut counts, family| {
                *counts.entry(family.loops).or_insert(0) += 1;
                counts
            });
        assert_eq!(per_loop, BTreeMap::from([(1, 1), (2, 1), (3, 3), (4, 11)]));
        let mut names = P_FAMILIES
            .iter()
            .map(|family| family.name)
            .collect::<Vec<_>>();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), P_FAMILIES.len());
        assert!(
            P_FAMILIES
                .iter()
                .all(|family| P_INTEGRAL_LOOP_COUNTS.contains(&family.loops))
        );
    }

    #[test]
    fn canonical_routings_carry_q_from_vertex_one_to_vertex_two() {
        for family in &P_FAMILIES {
            let mut balance = BTreeMap::<i64, Atom>::new();
            for (id, (from, to, momentum)) in lines(family).into_iter().enumerate() {
                if id < family.loops {
                    assert_eq!(
                        momentum,
                        function!(S.k, Atom::num(id as i64 + 1)),
                        "{}: line {} must carry k({})",
                        family.name,
                        id + 1,
                        id + 1
                    );
                }
                *balance.entry(from).or_default() += &momentum;
                *balance.entry(to).or_default() -= &momentum;
            }
            let q = function!(S.p, Atom::num(1));
            for (vertex, flow) in balance {
                let expected = match vertex {
                    1 => q.clone(),
                    2 => -q.clone(),
                    _ => Atom::Zero,
                };
                assert!(
                    (flow - expected).expand().is_zero(),
                    "{}: vertex {vertex}",
                    family.name
                );
            }
        }
    }

    #[test]
    fn lines_and_isps_span_every_scalar_product() {
        for family in &P_FAMILIES {
            let loops = family.loops;
            let mut rows = lines(family)
                .iter()
                .map(|(_, _, momentum)| quadric(&coefficients(momentum.as_view(), loops)))
                .collect::<Vec<_>>();
            rows.extend(
                family
                    .isps
                    .iter()
                    .map(|isp| quadric(&coefficients(vk_parse!(*isp).unwrap().as_view(), loops))),
            );
            let coordinates = loops * (loops + 1) / 2 + loops;
            assert_eq!(rows.len(), coordinates, "{}", family.name);
            assert_eq!(rank(rows), coordinates, "{}", family.name);
        }
    }
}
