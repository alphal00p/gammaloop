"""Theory cards and the prose of the gamma5 documentation site.

The texts are kept as readable source files in this directory and turned into rich text (R of ``DATA_FORMAT.md``)
by :func:`gdocs.mathview.prose`. Every statement in them is taken from the report *One-loop renormalisation of the
Standard Model with a non-anticommuting gamma5* or from the output of the automation package ``hepkit_renorm``.

Source files
============

``cards_*.txt``  theory cards (``data/theory.json``): the 26 keys of ``DATA_FORMAT.md`` section 7 and the method
                 cards ``method-overview``, ``method-bmhv``, ``method-st``, ``method-beyond``;
``groups.txt``   summaries of the groups of Green's functions (merged into ``data/classes.json``);
``site.txt``     title, subtitle and status of the manifest, and the introductions of the two phases;
``report_sections.json``  number, title and first page of every labelled heading of the report (generated by
                 :func:`index_report` from the Typst sources; the build only reads it).
``report_equations.json``  number and page of every labelled, numbered displayed equation of the report, as printed
                 in ``report/one_loop_gamma5.pdf`` (generated by ``typst query`` on the report with the metadata
                 query of :data:`EQUATION_QUERY`; checked against the PDF text, every number appears on its page).

Format of a source file. Lines starting with ``%%`` are comments. A block starts with ``=== <kind> <key>``
(``kind`` is ``card``, ``group`` or ``text``), followed by header lines ``name: value`` (``title``, ``report``) up to
a line ``---``, followed by the body. The body is a sequence of paragraphs separated by blank lines:

* a paragraph that consists of a single ``[[ ... ]]`` span is a displayed formula, ``<p class="eq">``;
* a paragraph that starts with ``<`` (``<ul>``, ``<ol>``) is kept as it is;
* every other paragraph becomes ``<p>...</p>``.

Mathematics is written in ``[[ ... ]]`` spans in the site notation of :mod:`gdocs.mathview`. Cross references:
``{eq:LABEL}`` gives ``<a data-report-page="P">Eq. (N)</a>`` (``{eq:LABEL|text}`` with own text; any label of
``report_equations.json``, with or without the ``eq:`` prefix), ``{sec:LABEL}`` gives ``<a data-report-page="P">Section N</a>`` (``{sec:LABEL|text}`` with own text; the label is
any label of ``report_sections.json``, written with or without the ``sec:`` prefix), ``{card:KEY|text}`` a link to
another card, ``{class:CLASS_ID|text}`` a link to a class of Green's functions, ``{term:PHASE:ID|text}`` a link to
an operator. The header ``report:`` lists report labels separated by spaces.

Interface
=========

``build_theory(site_dir) -> dict``            writes ``data/theory.json`` (all cards) and returns it.
``merge_class_groups(site_dir) -> dict``      sets ``title``, ``report`` and ``summary`` of every group of
                                              ``data/classes.json`` that has a summary here; other keys untouched.
``manifest_texts() -> dict``                  ``{"title", "subtitle", "status", "types", "conventions"}`` for
                                              ``data/manifest.json`` (``types``: R per type of term).
``phase_intro(phase) -> str``                 the ``intro`` (R) of ``data/<phase>.json``, phase ``unbroken``/``broken``.
``cards() / groups() / texts()``              the parsed sources (rich text already rendered).
``report_ref(label) -> {"label", "page"}``    a report reference of DATA_FORMAT section 2.
``eq_ref(label) -> {"label", "page"}``        the same for an equation: ``{"label": "Eq. (76)", "page": 26}``.
``eq_anchor(label, text=None) -> str``        rich-text anchor ``<a data-report-page="26">Eq. (76)</a>``.
``check(site_dir) -> list[str]``              consistency problems (missing keys, unknown references, word counts).
``index_report(report_dir, headings_txt)``    regenerates ``report_sections.json`` from the Typst sources.

Command line: ``python -m gdocs.theory [--site DIR] [--no-classes] [--check]`` (needs ``SYMBOLICA_LICENSE``).
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

HERE = Path(__file__).resolve().parent
SITE = HERE.parents[2] / "site"

#: the card keys of DATA_FORMAT.md section 7, in the order of the page
CARD_KEYS = (
    "gauge-kinetic", "gauge-self", "gauge-fixing", "ghost", "fermion-kinetic", "fermion-gauge", "yukawa",
    "higgs-kinetic", "higgs-potential", "brst-sources", "breaking", "ct-fields", "ct-couplings", "ct-evanescent",
    "st-gauge", "st-fermion", "st-source", "st-scalar", "normalisation", "anomaly", "broken-shift", "broken-masses",
    "broken-mixing", "broken-tadpole", "broken-st", "broken-interactions",
)
#: additional cards of the Theory view
METHOD_KEYS = ("method-overview", "method-bmhv", "method-st", "method-beyond")
#: the report's eighteen groups of Green's functions and the extra group of the automation
GROUP_KEYS = (
    "g0_VV", "g0_VVV", "g0_VVVV", "g0_FF", "g0_FFV", "g0_SS", "g0_SSV_SSVV", "g0_SSSS", "g0_FFS", "g0_ghost_sources",
    "g1_cV", "g1_cVV", "g1_cVVV_cVVVV", "g1_cFF", "g1_cFFV", "g1_cSS_cSSV", "g1_cFFS", "g1_ccRF",
)
TEXT_KEYS = ("title", "subtitle", "status", "intro-unbroken", "intro-broken")
PLAIN_TEXTS = ("title", "subtitle")  # plain strings, not rich text

_BLOCK = re.compile(r"^=== (card|group|text) ([A-Za-z0-9_.:-]+)\s*$")
_REF = re.compile(r"\{(eq|sec|card|class|term):([^{}|]+?)(?:\|([^{}]*))?\}")
_SPAN_ONLY = re.compile(r"^\[\[(?:(?!\]\]).)*\]\]$", re.S)


# ================================================================================================ report index
@lru_cache(maxsize=1)
def report_sections() -> dict:
    return json.loads((HERE / "report_sections.json").read_text(encoding="utf-8"))["sections"]


def _section(label: str) -> dict:
    secs = report_sections()
    for key in (label, "sec:" + label):
        if key in secs:
            return secs[key]
    raise KeyError(f"unknown report label {label!r}")


def report_ref(label: str) -> dict:
    """``{"label": "Section 4.1.1", "page": 43}`` for a report label such as ``sec:g0_VV``."""
    s = _section(label)
    return {"label": f"Section {s['number']}", "page": s["page"]}


#: Typst code appended (in a copy of the report directory) to obtain report_equations.json:
#:   typst query eqquery.typ "<eqnums>" --field value --one
EQUATION_QUERY = (
    '#include "one_loop_gamma5.typ"\n'
    '#context [#metadata(query(math.equation.where(block: true)).filter(e => e.has("label") and e.numbering != none)'
    '.map(e => (str(e.label), counter(math.equation).at(e.location()).first(), e.location().page()))) <eqnums>]\n')


@lru_cache(maxsize=1)
def report_equations() -> dict:
    return json.loads((HERE / "report_equations.json").read_text(encoding="utf-8"))


def eq_ref(label: str) -> dict:
    """``{"label": "Eq. (76)", "page": 26}`` for an equation label such as ``eq:Delta1`` or ``Delta1``."""
    e = report_equations().get(label.removeprefix("eq:"))
    if e is None:
        raise KeyError(f"unknown report equation {label!r}")
    return {"label": f"Eq. ({e['number']})", "page": e["page"]}


def eq_anchor(label: str, text: str | None = None) -> str:
    """Rich-text link to a report equation: ``<a data-report-page="26">Eq. (76)</a>``."""
    r = eq_ref(label)
    return f'<a data-report-page="{r["page"]}" title="Report, page {r["page"]}">{text or r["label"]}</a>'


def index_report(report_dir: Path, headings_txt: Path, out: Path | None = None) -> dict:
    """Number every heading of the report's Typst sources in include order (heading numbering ``1.1``) and attach
    the first page of every labelled heading from ``report_headings.txt``. Writes ``report_sections.json``."""
    head = re.compile(r"^(=+)\s+(.*?)\s*(?:<([^>]+)>)?\s*$")
    inc = re.compile(r'^\s*#include\s+"([^"]+)"')
    count = [0] * 6
    found: list[tuple[str, int, str, str | None]] = []

    def walk(path: Path) -> None:
        for line in path.read_text(encoding="utf-8").splitlines():
            m = inc.match(line)
            if m:
                walk((path.parent / m.group(1)).resolve())
                continue
            m = head.match(line)
            if m:
                lvl = len(m.group(1))
                count[lvl - 1] += 1
                for k in range(lvl, 6):
                    count[k] = 0
                found.append((".".join(str(c) for c in count[:lvl]), lvl, m.group(2), m.group(3)))

    walk(Path(report_dir) / "one_loop_gamma5.typ")
    pages = {}
    for line in Path(headings_txt).read_text(encoding="utf-8").splitlines():
        m = re.match(r"\s*page\s+(\d+)\s+level\s+(\d+)\s+<([^>]+)>", line)
        if m:
            pages[m.group(3)] = int(m.group(1))
    sections = {}
    for num, lvl, title, label in found:
        if label is None:
            continue
        if label not in pages:
            raise ValueError(f"label {label} has no page in {headings_txt}")
        sections[label] = {"number": num, "level": lvl, "title": _plain_title(title), "page": pages[label]}
    missing = set(pages) - set(sections)
    if missing:
        raise ValueError(f"labels of {headings_txt} not found in the sources: {sorted(missing)}")
    doc = {"source": "report sources (Typst), heading numbering 1.1; pages of report/one_loop_gamma5.pdf",
           "sections": sections}
    target = out or HERE / "report_sections.json"
    target.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    report_sections.cache_clear()
    return doc


def _plain_title(t: str) -> str:
    rep = {"$gh": "$ω", "#bop": "𝐛", "$Dbrk_1$": "Δ₁", "--": "–", "$overline(\"MS\")$": "MS-bar",
           "_alpha": "α", "_beta": "β"}
    for a, b in rep.items():
        t = t.replace(a, b)
    t = re.sub(r"\$([^$]*)\$", lambda m: m.group(1).replace(" ", ""), t)
    return (t.replace("omega", "ω").replace("overline(Psi)", "Ψ̄").replace("overline(R)", "R̄").replace("Psi", "Ψ")
            .replace("^dagger", "†").replace("eta", "η").replace("delta", "δ").replace("Delta", "Δ")
            .replace("bop", "𝐛").replace("^((1))", "⁽¹⁾")
            .replace('_"ST"', "_ST").replace("X_1", "X₁"))


# ================================================================================================ source files
def _source_files() -> list[Path]:
    return [p for p in sorted(HERE.glob("cards_*.txt")) + [HERE / "groups.txt", HERE / "site.txt"] if p.exists()]


@lru_cache(maxsize=1)
def _raw_blocks() -> dict:
    """``{(kind, key): {"title", "report", "body", "file"}}`` with the body as source text."""
    blocks: dict = {}
    for path in _source_files():
        cur = None
        in_head = False
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if line.startswith("%%"):
                continue
            m = _BLOCK.match(line)
            if m:
                key = (m.group(1), m.group(2))
                if key in blocks:
                    raise ValueError(f"{path.name}:{n}: duplicate block {key}")
                cur = blocks[key] = {"title": None, "report": [], "lines": [], "file": f"{path.name}:{n}"}
                in_head = True
                continue
            if cur is None:
                if line.strip():
                    raise ValueError(f"{path.name}:{n}: text outside a block")
                continue
            if in_head:
                if line.strip() == "---":
                    in_head = False
                elif line.strip():
                    name, _, value = line.partition(":")
                    name = name.strip()
                    if name == "title":
                        cur["title"] = value.strip()
                    elif name == "report":
                        cur["report"] = value.split()
                    else:
                        raise ValueError(f"{path.name}:{n}: unknown header {name!r}")
                continue
            cur["lines"].append(line)
    for b in blocks.values():
        b["body"] = "\n".join(b.pop("lines")).strip()
    return blocks


def _refs(text: str) -> str:
    """Replace the ``{sec:..}``, ``{card:..}``, ``{class:..}``, ``{term:..}`` shorthands outside math spans."""
    out = []
    for i, part in enumerate(re.split(r"(\[\[(?:(?!\]\]).)*\]\])", text, flags=re.S)):
        if i % 2:
            out.append(part)
            continue
        out.append(_REF.sub(_ref_anchor, part))
    return "".join(out)


def _ref_anchor(m: re.Match) -> str:
    kind, target, text = m.group(1), m.group(2).strip(), m.group(3)
    if kind == "eq":
        return eq_anchor(target, text)
    if kind == "sec":
        s = _section(target)
        return f'<a data-report-page="{s["page"]}">{text or "Section " + s["number"]}</a>'
    if text is None:
        raise ValueError(f"reference {m.group(0)} needs a text")
    attr = {"card": "data-theory", "class": "data-class", "term": "data-term"}[kind]
    if kind == "card" and target not in CARD_KEYS + METHOD_KEYS:
        raise ValueError(f"reference to an unknown card {target!r}")
    return f'<a {attr}="{target}">{text}</a>'


def render(body: str) -> str:
    """Source body -> rich text R (paragraphs, displayed formulae, references, math spans)."""
    from gdocs import mathview as mv

    paras = [p.strip() for p in re.split(r"\n\s*\n", body) if p.strip()]
    html = []
    for p in paras:
        p = " ".join(line.strip() for line in p.splitlines())
        if _SPAN_ONLY.match(p):
            html.append(f'<p class="eq">{p}</p>')
        elif re.match(r"<(p|ul|ol)\b", p):
            # a block written in HTML; a paragraph that merely starts with an inline tag (<strong>, <em>, <a>,
            # <code>) is wrapped like any other
            html.append(p)
        else:
            html.append(f"<p>{p}</p>")
    return mv.prose(_refs("".join(html)))


def _rendered(kind: str) -> dict:
    out = {}
    for (k, key), b in _raw_blocks().items():
        if k != kind:
            continue
        try:
            body = b["body"] if (kind == "text" and key in PLAIN_TEXTS) else render(b["body"])
        except ValueError as err:
            raise ValueError(f"{b['file']} ({kind} {key}): {err}") from None
        out[key] = {"title": b["title"], "body": body, "report": [report_ref(x) for x in b["report"]]}
    return out


@lru_cache(maxsize=1)
def cards() -> dict:
    """All theory cards, ``{key: {"title", "body", "report"}}``, in page order."""
    c = _rendered("card")
    order = list(METHOD_KEYS) + list(CARD_KEYS)
    return {k: c[k] for k in order if k in c} | {k: v for k, v in c.items() if k not in order}


@lru_cache(maxsize=1)
def groups() -> dict:
    return _rendered("group")


@lru_cache(maxsize=1)
def texts() -> dict:
    return _rendered("text")


# ================================================================================================ interface
def build_theory(site_dir: Path | str = SITE) -> dict:
    """Write ``data/theory.json`` with every card (replaces the mock file)."""
    data = {"cards": cards()}
    path = Path(site_dir) / "data" / "theory.json"
    path.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    return data


def merge_class_groups(site_dir: Path | str = SITE) -> dict:
    """Set ``title``, ``report`` and ``summary`` of the groups of ``data/classes.json`` from ``groups.txt``. Other
    keys of the file and of the groups are kept; groups without an entry here are left as they are."""
    path = Path(site_dir) / "data" / "classes.json"
    doc = json.loads(path.read_text(encoding="utf-8"))
    g = groups()
    for grp in doc.get("groups", []):
        e = g.get(grp.get("key"))
        if not e:
            continue
        if e["title"]:
            grp["title"] = e["title"]
        if e["report"]:
            grp["report"] = e["report"]
        grp["summary"] = e["body"]
    path.write_text(json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    return doc


def manifest_texts() -> dict:
    """``{"title", "subtitle", "status"}`` of ``data/manifest.json`` (title and subtitle are plain strings)."""
    t = texts()
    return {"title": t["title"]["body"], "subtitle": t["subtitle"]["body"], "status": t["status"]["body"],
            "types": {k: t[f"type-{k}"]["body"] for k in ("tree", "pole", "evanescent", "finite", "breaking")},
            "conventions": t["conventions"]["body"]}


def phase_intro(phase: str) -> str:
    """The ``intro`` (rich text) of the phase file ``unbroken`` or ``broken``."""
    if phase not in ("unbroken", "broken"):
        raise ValueError(f"unknown phase {phase!r}")
    return texts()[f"intro-{phase}"]["body"]


def _words(html: str) -> int:
    text = re.sub(r"<math.*?</math>", " X ", html, flags=re.S)
    return len(re.sub(r"<[^>]+>", " ", text).split())


def check(site_dir: Path | str = SITE) -> list[str]:
    """Consistency problems of the sources: missing keys, word counts outside the agreed range, report pages that
    disagree with ``site/resources/report_headings.txt``."""
    problems = []
    c = cards()
    for k in CARD_KEYS + METHOD_KEYS:
        if k not in c:
            problems.append(f"card {k} missing")
    for k in GROUP_KEYS:
        if k not in groups():
            problems.append(f"group {k} missing")
    for k in TEXT_KEYS:
        if k not in texts():
            problems.append(f"text {k} missing")
    for k in CARD_KEYS:
        if k in c:
            w = _words(c[k]["body"])
            n = c[k]["body"].count("<p")
            if not 150 <= w <= 330:
                problems.append(f"card {k}: {w} words")
            if not 2 <= n <= 7:
                problems.append(f"card {k}: {n} paragraphs")
            if not c[k]["report"]:
                problems.append(f"card {k}: no report reference")
    headings = Path(site_dir) / "resources" / "report_headings.txt"
    if headings.exists():
        pages = {m.group(2): int(m.group(1)) for m in
                 re.finditer(r"page\s+(\d+)\s+level\s+\d+\s+<([^>]+)>", headings.read_text(encoding="utf-8"))}
        for label, s in report_sections().items():
            if pages.get(label) != s["page"]:
                problems.append(f"report label {label}: page {s['page']} here, {pages.get(label)} in {headings.name}")
    return problems
