//! Shared performance producer, linked to each measured revision's public API.
//! No evaluator decoding or alternate numerical implementation belongs here.
use eyre::{ensure, Result};
use gammaloop_api::state::State;
use gammalooprs::{
    integrands::{
        evaluation::{PreciseEvaluationResult, StabilityStatus},
        process::{MomentumSpaceEvaluationInput, ProcessIntegrand},
    },
    momentum::{SignOrZero, ThreeMomentum},
    processes::process::ProcessCollection,
    settings::runtime::Precision,
    utils::{FloatLike, VarFloat, F},
};
use serde_json::{json, Value};
use std::{fs, path::PathBuf, time::Instant};

/// Independent expected phase of this fixture, checked on the saved source and
/// resolved physical model, never on generated scalar bodies or their values.
/// Six i*slash propagators, two -i*g propagators and six imaginary couplings
/// give a real 4D source: its two closed vector traces and color traces are real,
/// and the explicit metric removes external polarization phases. Real U/S/US
/// Taylor operations preserve this. Each local forest has child loop ranks plus
/// cograph rank equal to three, hence the same i^3 energy-contour phase. Integrated
/// and threshold terms are excluded because their phases need separate proofs.
/// The raw 3D density has energy dimension 6 - 2*8 + 3 = -7; the caller uses unit
/// direct-sample weight/Jacobian and no channel, orientation or cut selection.
fn paper_real_zero_certificate(
    graph: &gammalooprs::graph::Graph,
    model: &gammalooprs::model::Model,
    generation: &gammalooprs::settings::global::GenerationSettings,
    settings: &gammalooprs::settings::RuntimeSettings,
) -> Result<Value> {
    use gammalooprs::{
        graph::edge::PossibleParticle,
        model::CouplingName,
        settings::global::MediumMode,
        uv::settings::{FinalIntegrandDimension, RenormalizationPrescriptionSettings},
    };
    use symbolica::{atom::Atom, parse};

    ensure!(
        graph.global_prefactor.projector
            == parse!(
                "spenso::g(spenso::mink(4,gammalooprs::hedge(0)),spenso::mink(4,gammalooprs::hedge(1)))"
            )
            && graph.global_prefactor.num == Atom::one()
            && graph.overall_factor == Atom::one()
            && graph.polarizations.is_empty()
            && graph
                .param_builder
                .pairs
                .additional_params
                .params
                .is_empty()
            && graph
                .initial_state_cut
                .iter_edges(&graph.underlying)
                .next()
                .is_none(),
        "paper phase certificate requires the original real metric projector and no source overrides"
    );
    ensure!(
        graph.underlying.n_edges() == 10 && graph.loop_momentum_basis.loop_edges.len() == 3,
        "paper phase certificate requires the original three-loop source"
    );
    // Bind the actual particle owners, not graph/rule names or output hashes.
    for (_, id, edge) in graph.underlying.iter_edges() {
        let edge = edge.data;
        let PossibleParticle::Particle(particle) = &edge.particle else {
            return Err(eyre::eyre!("paper source has a particle/mass override"));
        };
        let expected = match id.0 {
            0 | 1 => ("a", 22, 3, 1),
            6 | 7 => ("g", 21, 3, 8),
            _ => ("d", 1, 2, 3),
        };
        ensure!(
            (
                particle.name.as_str(),
                particle.pdg_code,
                particle.spin,
                particle.color
            ) == expected
                && edge.num.autogenerated
                && !edge.is_dummy
                && edge
                    .extra_data
                    .vakint_edge_power
                    .is_none_or(|power| power == 1),
            "paper source species, numerator or propagator power changed"
        );
        for parameter in [particle.mass.0, particle.width.0] {
            let value = model
                .get_symbol_value(parameter)
                .ok_or_else(|| eyre::eyre!("missing source mass/width value"))?;
            ensure!(
                value.re.0 == 0.0 && value.im.0 == 0.0,
                "paper phase certificate requires massless, zero-width source particles"
            );
        }
    }
    let mut incidence = Vec::new();
    for (_, hedges, vertex) in graph.underlying.iter_nodes() {
        let mut edges = hedges
            .into_iter()
            .map(|h| graph.underlying[&h].0)
            .collect::<Vec<_>>();
        edges.sort_unstable();
        let photon = matches!(edges.as_slice(), [0, 2, 5] | [1, 3, 4]);
        let rule = vertex
            .vertex_rule
            .as_ref()
            .ok_or_else(|| eyre::eyre!("missing source vertex rule"))?;
        let coupling = model.get_coupling(if photon { "GC_1" } else { "GC_11" });
        // VertexRule::eq compares names only; inspect the actual tensor/coupling
        // structures so a same-name axial or complex-color replacement fails.
        ensure!(
            vertex.num.autogenerated
                && rule
                    .particles
                    .iter()
                    .map(|p| (p.name.as_str(), p.pdg_code, p.spin, p.color))
                    .collect::<Vec<_>>()
                    == vec![
                        ("d~", -1, 2, -3),
                        ("d", 1, 2, 3),
                        if photon {
                            ("a", 22, 3, 1)
                        } else {
                            ("g", 21, 3, 8)
                        }
                    ]
                && rule.lorentz_structures.len() == 1
                && rule.lorentz_structures[0].spins == [2, 2, 3]
                && rule.lorentz_structures[0].structure
                    == parse!(
                        "UFO::{}::Gamma(UFO::{}::idx(1,3),UFO::{}::idx(1,1),UFO::{}::idx(1,2))"
                    )
                && rule.color_structures.color_structure
                    == vec![if photon {
                        parse!("UFO::{}::Identity(1,2)")
                    } else {
                        parse!("UFO::{}::T(3,2,1)")
                    }]
                && rule.couplings == vec![vec![Some(CouplingName(coupling.name))]],
            "paper phase certificate requires the original closed vector/color traces"
        );
        // This is also Model::get_symbol_value's coupling owner and the value
        // copied by ParamBuilder::update_model_values during runtime warmup.
        let value = coupling
            .value
            .ok_or_else(|| eyre::eyre!("missing source coupling value"))?;
        ensure!(
            value.re == 0.0 && value.im.is_finite(),
            "source coupling is not finite and imaginary"
        );
        incidence.push(edges);
    }
    incidence.sort();
    ensure!(
        incidence
            == [
                vec![0, 2, 5],
                vec![1, 3, 4],
                vec![2, 3, 7],
                vec![4, 5, 6],
                vec![6, 8, 9],
                vec![7, 8, 9]
            ],
        "paper phase certificate requires the original two closed fermion loops"
    );
    for (name, numerator) in [
        (
            "d",
            Atom::i() * parse!("UFO::{}::PSlash(UFO::{}::idx(1,2),UFO::{}::idx(1,1))"),
        ),
        (
            "g",
            -Atom::i() * parse!("UFO::{}::Metric(UFO::{}::idx(1,1),UFO::{}::idx(1,2))"),
        ),
    ] {
        let index = model
            .particle_name_to_propagator_position
            .get(name)
            .ok_or_else(|| eyre::eyre!("missing source propagator selection"))?;
        let propagator = &model.propagators[*index];
        ensure!(
            propagator.numerator == numerator
                && propagator.denominator == parse!("UFO::{}::P(UFO::{}::idx(1,1))^2"),
            "paper phase certificate requires i*slash and -i*metric quadratic propagators"
        );
    }
    let expected: RenormalizationPrescriptionSettings = serde_json::from_value(
        json!({"overrides": [
            {"prescription": "IR", "ct_identifier": {"external_pdg_set": [-21,21], "internal_pdg_set": [1]}},
            {"prescription": "IR", "ct_identifier": {"external_pdg_set": [-22,22], "internal_pdg_set": [1,21]}}
        ]}),
    )?;
    let uv = &generation.uv;
    let generated = serde_json::to_value(generation)?;
    ensure!(
        uv.softct
            && generation.medium.mode == MediumMode::Vacuum
            && !generation.medium.vacuum_subtraction
            && uv.subtract_uv
            && uv.local_uv_cts_from_expanded_4d_integrands
            && uv.final_integrand == FinalIntegrandDimension::ThreeD
            && !uv.generate_integrated
            && !uv.add_marker
            && uv.renormalization_prescription == expected
            && !generation.threshold_subtraction.enable_thresholds
            && generation.explicit_orientation_sum_only
            && generation.orientation_pattern == Default::default()
            && generation.force_cuts.is_empty()
            && generated
                .get("three_dimensional_representations")
                .is_none_or(|value| value == &json!(["cff"])),
        "paper phase certificate requires the original complete local-only vacuum CFF/from4D H sum"
    );
    ensure!(
        settings.kinematics.e_cm == 300.0
            && serde_json::to_value(&settings.kinematics.externals)?["data"]["momenta"]
                == json!([[300.0, 0.0, 0.0, 0.0], "dependent"])
            && [
                settings.general.m_uv,
                settings.general.mu_r,
                settings.general.renormalization_localization_scale,
                settings.general.numerator_sampling_scale
            ]
            .iter()
            .all(|value| value.is_finite() && *value > 0.0)
            && settings.general.additional_param_values.is_empty(),
        "paper phase certificate requires the original real external scale and real positive scalar scales"
    );
    Ok(json!({"id": "paper-b1-local-4d-real-v1", "component": 0,
        "precision_bits": 1000, "energy_dimension": -7, "e_cm": 300}))
}

fn main() -> Result<()> {
    let args = std::env::args().skip(1).collect::<Vec<_>>();
    ensure!(
        args.len() == 3,
        "usage: precise_sample STATE CERTIFICATE OUTPUT"
    );
    let output = PathBuf::from(&args[2]);
    ensure!(!output.exists(), "refusing to overwrite a measurement");
    let certificate: Value = serde_json::from_slice(&fs::read(&args[1])?)?;
    let name = certificate["process"]
        .as_str()
        .ok_or_else(|| eyre::eyre!("missing process"))?;
    let canonical_edges: Vec<usize> =
        serde_json::from_value(certificate["canonical_loop_edges"].clone())?;
    let canonical_bits: Vec<[u64; 3]> =
        serde_json::from_value(certificate["canonical_point_bits"].clone())?;
    ensure!(
        canonical_edges.len() == 3 && canonical_bits.len() == 3,
        "expected three canonical loop momenta"
    );
    ensure!(
        certificate["precision_bits"] == 1000 && certificate["graph_id"] == 0,
        "unexpected precision or graph"
    );
    gammalooprs::initialisation::initialise()?;
    let started = Instant::now();
    let mut state = State::load(PathBuf::from(&args[0]), None, None)?;
    let load_seconds = started.elapsed().as_secs_f64();
    let process_id = state
        .process_list
        .processes
        .iter()
        .position(
            |p| matches!(&p.collection, ProcessCollection::Amplitudes(a) if a.contains_key(name)),
        )
        .ok_or_else(|| eyre::eyre!("missing amplitude"))?;
    let started = Instant::now();
    let model = state.resolve_model_for_integrand(process_id, name)?;
    state
        .process_list
        .get_integrand_mut(process_id, name)?
        .warm_up(&model)?;
    let model_warmup_seconds = started.elapsed().as_secs_f64();
    let ProcessCollection::Amplitudes(amplitudes) =
        &state.process_list.processes[process_id].collection
    else {
        unreachable!()
    };
    let amplitude = &amplitudes[name];
    ensure!(amplitude.graphs.len() == 1, "expected exactly one graph");
    let ProcessIntegrand::Amplitude(integrand) = amplitude
        .integrand
        .as_ref()
        .ok_or_else(|| eyre::eyre!("missing integrand"))?
    else {
        unreachable!()
    };
    ensure!(
        integrand.data.graph_terms.len() == 1 && integrand.data.explicit_orientation_sum_only,
        "expected complete residue sum"
    );
    ensure!(
        !integrand.settings.general.enable_cache,
        "point cache must be disabled"
    );
    let graph = &amplitude.graphs[0].graph;
    let runtime = &graph.loop_momentum_basis;
    ensure!(
        integrand.data.graph_terms[0].graph.loop_momentum_basis == *runtime,
        "generation and evaluation routing differ"
    );
    let runtime_json = serde_json::to_value(runtime)?;
    let runtime_edges: Vec<usize> = serde_json::from_value(runtime_json["loop_edges"].clone())?;
    let permutation = runtime_edges
        .iter()
        .map(|edge| {
            canonical_edges
                .iter()
                .position(|other| other == edge)
                .ok_or_else(|| eyre::eyre!("runtime edge absent from canonical basis"))
        })
        .collect::<Result<Vec<_>>>()?;
    let mut sorted = permutation.clone();
    sorted.sort_unstable();
    ensure!(
        sorted == [0, 1, 2] && runtime_json["ext_edges"] == certificate["external_edges"],
        "physical LMB is not a permutation of the canonical loop edges"
    );
    let canonical_signatures = certificate["edge_signatures"]
        .as_array()
        .ok_or_else(|| eyre::eyre!("missing canonical routing"))?;
    let runtime_signatures = runtime_json["edge_signatures"]
        .as_array()
        .ok_or_else(|| eyre::eyre!("missing runtime routing"))?;
    ensure!(
        canonical_signatures.len() == runtime_signatures.len(),
        "edge count changed"
    );
    for (from, to) in canonical_signatures.iter().zip(runtime_signatures) {
        let from_internal = from["internal"]
            .as_array()
            .ok_or_else(|| eyre::eyre!("missing signed routing"))?;
        let to_internal = to["internal"]
            .as_array()
            .ok_or_else(|| eyre::eyre!("missing runtime signed routing"))?;
        ensure!(
            from["external"] == to["external"]
                && from_internal.len() == 3
                && to_internal.len() == 3
                && permutation
                    .iter()
                    .zip(to_internal)
                    .all(|(j, sign)| &from_internal[*j] == sign),
            "signed routing is not the certified slot permutation"
        );
    }
    // The selected edge's canonical momentum must be a positive unit axis,
    // without an external shift. Only bit-preserving slot copies are allowed.
    for (i, edge) in runtime.loop_edges.iter().enumerate() {
        let signature = &runtime.edge_signatures[*edge];
        ensure!(
            signature.external.iter().all(|s| *s == SignOrZero::Zero)
                && signature.internal.iter().enumerate().all(|(j, sign)| *sign
                    == if j == i {
                        SignOrZero::Plus
                    } else {
                        SignOrZero::Zero
                    }),
            "mapping would require arithmetic or external shifts"
        );
    }
    let generation = &state.process_list.processes[process_id]
        .settings_history
        .as_ref()
        .ok_or_else(|| eyre::eyre!("missing generation provenance"))?
        .generation;
    let certified_real_zero =
        paper_real_zero_certificate(graph, &model, generation, &integrand.settings)?;
    let point_bits = permutation
        .iter()
        .map(|i| canonical_bits[*i])
        .collect::<Vec<_>>();
    let point = point_bits
        .iter()
        .map(|p| p.map(f64::from_bits))
        .collect::<Vec<_>>();
    let input = MomentumSpaceEvaluationInput {
        loop_momenta: point
            .iter()
            .map(|p| ThreeMomentum {
                px: F(p[0]),
                py: F(p[1]),
                pz: F(p[2]),
            })
            .collect(),
        integrator_weight: F(1.0),
        graph_id: Some(0),
        group_id: None,
        orientation: None,
        channel_id: None,
    };
    let integrand = state.process_list.get_integrand_mut(process_id, name)?;
    let mut evaluations = Vec::new();
    // One genuine numerical warmup and one timed sample in every fresh process.
    // Both use the ordinary public precise evaluator and identical settings.
    for _ in 0..2 {
        let started = Instant::now();
        let PreciseEvaluationResult::Arb(result) =
            integrand.evaluate_momentum_configuration_precise(&model, &input, true)?
        else {
            return Err(eyre::eyre!("forced Arb returned a different precision"));
        };
        let physical_seconds = started.elapsed().as_secs_f64();
        let _: &F<VarFloat<1000>> = &result.integrand_result.re;
        ensure!(
            !result.integrand_result.re.0.is_nan()
                && !result.integrand_result.re.0.is_infinite()
                && !result.integrand_result.im.0.is_nan()
                && !result.integrand_result.im.0.is_infinite(),
            "nonfinite precise result"
        );
        let attempts = &result.evaluation_metadata.stability_results;
        ensure!(
            attempts.len() == 1
                && attempts[0].precision == Precision::Arb
                && matches!(attempts[0].status, StabilityStatus::Stable(2)),
            "unexpected precision, retries or stability probes"
        );
        evaluations.push(json!({
            "output": [result.integrand_result.re.0, result.integrand_result.im.0],
            "evaluator_seconds": result.evaluation_metadata.evaluator_evaluation_time.as_secs_f64(),
            "physical_seconds": physical_seconds,
            "attempts": attempts,
        }));
    }
    fs::write(
        output,
        serde_json::to_vec_pretty(&json!({
            "commit": env!("PERFORMANCE_REVISION"), "process_id": process_id, "integrand": name,
            "certified_real_zero": certified_real_zero,
            "precision_bits": 1000, "point_bits": point_bits, "canonical_point_bits": canonical_bits, "canonical_permutation": permutation,
            "load_seconds": load_seconds, "model_warmup_seconds": model_warmup_seconds,
            "warmup_samples": 1, "measured_samples": 1, "evaluations": evaluations,
        }))?,
    )?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use gammaloop_api::commands::import::model::ImportModel;
    use gammalooprs::{graph::parse::from_dot::IntoGraph, model::CouplingName};
    use std::sync::Arc;
    use symbolica::atom::Atom;

    #[test]
    fn paper_phase_certificate_checks_source_and_ignores_unrelated_model_parameters() -> Result<()>
    {
        gammalooprs::initialisation::initialise()?;
        let mut state = State::new_test();
        // Match the benchmark's restricted model, including massless propagators.
        ImportModel {
            path: "sm-default".into(),
            simplify_model: true,
        }
        .run(&mut state)?;
        let model = state.model;
        let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
        let graph: gammalooprs::graph::Graph = fs::read_to_string(
            root.join("tests/resources/graphs/paper_figure_b1_double_triangle_soft_ir.dot"),
        )?
        .into_graph(&model)?;
        let card: toml::Value = toml::from_str(&fs::read_to_string(
            root.join("tests/resources/run_cards/paper_figure_b1_double_triangle_soft_ir.toml"),
        )?)?;
        let mut generation: gammalooprs::settings::global::GenerationSettings = card
            ["cli_settings"]["global"]["generation"]
            .clone()
            .try_into()?;
        generation.orientation_pattern = Default::default();
        generation.explicit_orientation_sum_only = true;
        generation.uv.local_uv_cts_from_expanded_4d_integrands = true;
        let settings: gammalooprs::settings::RuntimeSettings =
            card["default_runtime_settings"].clone().try_into()?;
        let expected = paper_real_zero_certificate(&graph, &model, &generation, &settings)?;
        assert_eq!(expected["energy_dimension"], -7);

        let mut unrelated = model.clone();
        unrelated
            .get_parameter_mut("MT")?
            .value
            .as_mut()
            .unwrap()
            .re = F(181.0);
        assert_eq!(
            paper_real_zero_certificate(&graph, &unrelated, &generation, &settings)?,
            expected
        );
        let mut complex = model.clone();
        let coupling = CouplingName(complex.get_coupling("GC_1").name);
        complex
            .couplings
            .get_mut(&coupling)
            .unwrap()
            .value
            .as_mut()
            .unwrap()
            .re = 0.01;
        assert!(paper_real_zero_certificate(&graph, &complex, &generation, &settings).is_err());
        let mut massive = model.clone();
        massive
            .get_parameter_mut("ZERO")?
            .value
            .as_mut()
            .unwrap()
            .re = F(1.0);
        assert!(paper_real_zero_certificate(&graph, &massive, &generation, &settings).is_err());
        let mut wrong_propagator = model.clone();
        let gluon = wrong_propagator.particle_name_to_propagator_position["g"];
        wrong_propagator
            .particle_name_to_propagator_position
            .insert("d".into(), gluon);
        assert!(
            paper_real_zero_certificate(&graph, &wrong_propagator, &generation, &settings).is_err()
        );

        let mut renamed = graph.clone();
        let gammalooprs::graph::edge::PossibleParticle::Particle(particle) =
            &mut renamed.underlying[linnet::half_edge::involution::EdgeIndex(2)].particle
        else {
            unreachable!()
        };
        Arc::make_mut(&mut particle.0).name = "different_propagator_owner".into();
        assert!(paper_real_zero_certificate(&renamed, &model, &generation, &settings).is_err());

        for change in 0..5 {
            let mut altered = graph.clone();
            match change {
                0 => altered.global_prefactor.projector *= Atom::i(),
                1 => altered.global_prefactor.num = Atom::i(),
                _ => {
                    let vertex = altered.underlying.iter_nodes().next().unwrap().0;
                    let vertex = &mut altered.underlying[vertex];
                    if change == 2 {
                        vertex.num.autogenerated = false;
                    } else {
                        let rule = Arc::make_mut(&mut vertex.vertex_rule.as_mut().unwrap().0);
                        if change == 3 {
                            Arc::make_mut(&mut rule.lorentz_structures[0]).structure *= Atom::i();
                        } else {
                            rule.color_structures.color_structure[0] *= Atom::i();
                        }
                    }
                }
            }
            assert!(
                paper_real_zero_certificate(&altered, &model, &generation, &settings).is_err(),
                "source alteration {change}"
            );
        }
        for change in 0..7 {
            let mut altered = generation.clone();
            match change {
                0 => altered.uv.generate_integrated = true,
                1 => altered.threshold_subtraction.enable_thresholds = true,
                2 => altered.uv.add_marker = true,
                3 => altered.uv.local_uv_cts_from_expanded_4d_integrands = false,
                4 => {
                    altered.medium.mode =
                        gammalooprs::settings::global::MediumMode::ThermodynamicEquilibrium
                }
                5 => {
                    altered.medium.mode =
                        gammalooprs::settings::global::MediumMode::ZeroTemperatureEquilibrium
                }
                _ => altered.medium.vacuum_subtraction = true,
            }
            assert!(
                paper_real_zero_certificate(&graph, &model, &altered, &settings).is_err(),
                "operator alteration {change}"
            );
        }
        let mut wrong_units = settings.clone();
        wrong_units.kinematics.e_cm = 1.0;
        assert!(paper_real_zero_certificate(&graph, &model, &generation, &wrong_units).is_err());
        Ok(())
    }
}
