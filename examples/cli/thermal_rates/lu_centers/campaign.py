"""Run the frozen-grid Monte Carlo convergence campaign for thermal LU centers.

Every job runs the `kinematics`, `apex_<process>` (for apex centers) and `integrate`
blocks of run.toml on a read-only state generated by that card. It adapts the sampling
grid for `--training` iterations of `--batch` samples and then samples the frozen grid
for `--frozen` iterations. Per-iteration archives let analyze.py separate the frozen
samples. Independent seeds are spaced so that the per-iteration seeds
`seed + iteration` of different jobs never coincide.
"""

import argparse
import hashlib
import json
import math
import os
import queue
import shutil
import subprocess
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPOSITORY = HERE.parents[3]
CARD = (HERE / "run.toml").relative_to(REPOSITORY)
SEED_SPACING = 10_000_000

# Probe momenta P=(E,0,0,p) at T=0.5 with mH=0.6, mL=0.25.
KINEMATICS = {
    "rest1": (1.0, 0.0),
    "rest16": (1.6, 0.0),
    "space": (0.5, 1.5),
}


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def git(*arguments, env=None):
    return subprocess.run(
        ["git", *arguments],
        cwd=REPOSITORY,
        env=env,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


def worktree_tree():
    """Tree hash of the working tree including untracked, non-ignored files.

    The files are staged into a copy of the index, so the user's index is untouched.
    """
    with tempfile.TemporaryDirectory() as directory:
        index = Path(directory) / "index"
        shutil.copy(REPOSITORY / git("rev-parse", "--git-path", "index"), index)
        environment = dict(os.environ, GIT_INDEX_FILE=str(index))
        git("add", "-A", env=environment)
        return git("write-tree", env=environment)


def job_argv(job, args):
    energy, momentum = KINEMATICS[job["kinematics"]]
    blocks, centers = ["kinematics", "integrate"], job["centers"]
    if centers == "apex":
        # The fixed centers replace the prescription for the graph of the process.
        blocks.insert(1, f"apex_{job['process']}")
        centers = "origin"
    defines = {
        "process": job["process"],
        "energy": energy,
        "momentum": momentum,
        "e_cm": math.sqrt(abs(energy * energy - momentum * momentum)),
        "centers": centers,
        "batch": args.batch,
        "samples": args.batch * (args.training + args.frozen),
        "seed": job["seed"],
        "training": args.training,
        "cores": args.cores,
        "workspace": job["directory"] / "workspace",
    }
    return [
        str(args.binary),
        "-n",
        "--read-only-state",
        "-s",
        str(args.state),
        str(CARD),
        "run",
        *blocks,
        *(item for key, value in defines.items() for item in ("-D", f"{key}={value}")),
    ]


def run(job, args, slots):
    slot = slots.get()
    try:
        return run_on_slot(job, args, slot)
    finally:
        slots.put(slot)


def run_on_slot(job, args, slot):
    job["directory"].mkdir(parents=True, exist_ok=True)
    first = args.first_cpu + slot * args.cores
    cpus = ",".join(map(str, range(first, first + args.cores)))
    argv = ["taskset", "-c", cpus, *job_argv(job, args)]
    (job["directory"] / "command.json").write_text(json.dumps(argv, indent=1))
    environment = dict(os.environ, RAYON_NUM_THREADS="1", OMP_NUM_THREADS="1")
    with open(job["directory"] / "log.txt", "w") as log:
        code = subprocess.run(
            argv,
            stdout=log,
            stderr=subprocess.STDOUT,
            cwd=REPOSITORY,
            env=environment,
            check=False,
        ).returncode
    return job | {"exit_code": code}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--binary", type=Path, default=REPOSITORY / "target/dev-optim/gammaloop"
    )
    parser.add_argument("--state", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--process", nargs="+", choices=["dt", "tbt"], default=["dt", "tbt"]
    )
    parser.add_argument(
        "--kinematics", nargs="+", choices=list(KINEMATICS), default=list(KINEMATICS)
    )
    parser.add_argument(
        "--centers",
        nargs="+",
        choices=["origin", "search", "apex"],
        default=["origin", "search"],
    )
    parser.add_argument("--seeds", type=int, default=8)
    parser.add_argument("--first-seed", type=int, default=271828)
    parser.add_argument("--batch", type=int, default=10_000)
    parser.add_argument("--training", type=int, default=10)
    parser.add_argument("--frozen", type=int, default=100)
    parser.add_argument("--cores", type=int, default=6)
    parser.add_argument("--jobs", type=int, default=8)
    parser.add_argument("--first-cpu", type=int, default=0)
    args = parser.parse_args()
    args.binary, args.state, args.output = (
        path.resolve() for path in (args.binary, args.state, args.output)
    )

    jobs = [
        {
            "process": process,
            "kinematics": kinematics,
            "centers": centers,
            "seed": args.first_seed + replica * SEED_SPACING,
            "directory": args.output
            / f"{process}_{kinematics}_{centers}"
            / f"seed{replica}",
        }
        for process in args.process
        for kinematics in args.kinematics
        for centers in args.centers
        for replica in range(args.seeds)
    ]
    args.output.mkdir(parents=True, exist_ok=True)
    manifest = {
        "git_head": git("rev-parse", "HEAD"),
        "git_worktree_tree": worktree_tree(),
        "binary_sha256": sha256(args.binary),
        "state_manifest_sha256": sha256(args.state / "state_manifest.toml"),
        "arguments": vars(args),
    }
    (args.output / "manifest.json").write_text(
        json.dumps(manifest, indent=1, default=str)
    )
    # Each concurrent job owns one disjoint block of CPUs.
    slots = queue.Queue()
    for slot in range(args.jobs):
        slots.put(slot)
    with ThreadPoolExecutor(args.jobs) as pool:
        records = list(pool.map(lambda job: run(job, args, slots), jobs))
    (args.output / "jobs.json").write_text(json.dumps(records, indent=1, default=str))
    failed = [record for record in records if record["exit_code"] != 0]
    print(f"{len(records)} jobs, {len(failed)} failed")


if __name__ == "__main__":
    main()
